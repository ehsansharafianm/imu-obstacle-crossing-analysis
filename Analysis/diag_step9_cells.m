function diag_step9_cells(root)
% DIAG_STEP9_CELLS  Stride-level check of the outlying cells of the step 9 SPSS sheet (read-only).
%   diag_step9_cells
%
% A cell = one participant mean (one parameter, obstacle and limb) of
% Results/Group Analysis/GroupCrossing_YoungAdults_SPSS.xlsx. A cell is outlying when its modified z-score
% (x - median) / (1.4826 MAD) across the participants of its column exceeds 3.5 (as in crossing_ml_params.m).
%   [1] JOINT ANGLES: the non-physiological joint max/min of diag_participant (hand-calc candidates) per test,
%       and how many of them already have a value in manualJointValues.m
%   [2] PEAK TIMING: for every outlying timing cell, the per-stride values behind it (recomputed exactly as
%       step 9 does: sign-normalized signal, peak minus foot apex, % gait cycle), the step 9 value, and the
%       robust value step 9 uses for its CLEAN tests (3-MAD stride gate + median)
% Nothing is changed. Output -> Results/Group Analysis/Step9_Cells_To_Check.md

if nargin < 1 || isempty(root), root = fileparts(fileparts(mfilename('fullpath'))); end
X = readtable(fullfile(root, 'Results', 'Group Analysis', 'GroupCrossing_YoungAdults_SPSS.xlsx'), 'VariableNamingRule', 'preserve');
L = {};
L = addl(L, '# Step 9: outlying cells to check');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/diag_step9_cells.m` on %s (read-only; no value is changed)._', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
L = addl(L, '');
L = addl(L, ['A cell is one participant mean of the step 9 SPSS sheet (one parameter, obstacle and limb). It is outlying when its ' ...
    'modified z-score (x - median) / (1.4826 MAD) across the participants of its column exceeds 3.5 (`crossing_ml_params.m`, P4).']);
L = addl(L, '');
L = partJoints(root, X, L);
L = partTiming(root, X, L);
f = fullfile(root, 'Results', 'Group Analysis', 'Step9_Cells_To_Check.md');
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
fprintf('Wrote %s\n', f);
end

%% ========================================================================
%  [1] joint angles: diag_participant hand-calc candidates
%% ========================================================================
function L = partJoints(root, X, L)
MJ = manualJointValues();
L = addl(L, '## 1. Joint angles (IK): hand-calc candidates');
L = addl(L, '');
L = addl(L, ['`diag_participant` section [4] per test: joint max / min per obstacle and role that look non-physiological in the raw IK ' ...
    'output (step 7 convention). Hand-measured values go in `Analysis/manualJointValues.m`; step 9 then uses them for the joint peaks ' ...
    'and ROM. Outlying joint cells of the sheet = joint columns with |z| > 3.5.']);
L = addl(L, '');
L = addl(L, '| test | hand-calc candidates | values in manualJointValues | outlying joint cells in the sheet | candidates |');
L = addl(L, '|---|---|---|---|---|');
nC = zeros(height(X), 1);  nH = nC;  t = 0;
for tn = X.Test'
    t = t + 1;
    txt = evalc(sprintf('diag_participant(%d, ''%s'')', tn, root));  ln = strtrim(strsplit(txt, newline));
    i4 = find(startsWith(ln, '[4]'), 1);  it = find(startsWith(ln, 'Tip:'), 1);  cand = {};
    if ~isempty(i4)
        if isempty(it), it = numel(ln) + 1; end
        cand = ln(i4+1:it-1);  cand = cand(contains(cand, '<-- check'));
    end
    nHand = 0;
    if ~isempty(MJ), nHand = nnz(cell2mat(MJ(:, 1)) == tn & ~cellfun(@isempty, MJ(:, 6))); end
    sh = regexprep(cand, '\s+', ' ');  sh = regexprep(sh, ' <-- check', '');  nC(t) = numel(cand);  nH(t) = nHand;
    L = addl(L, '| %d | %d | %d | %d | %s |', tn, numel(cand), nHand, nOut(X, tn, 'joint_'), ternary(isempty(sh), '-', strjoin(sh, '; ')));
end
L = addl(L, '');
todo = X.Test(nC > 0 & nH == 0)';
L = addl(L, ['**Reading.** %d hand-calc candidates in %d tests; tests with candidates but no hand values yet: %s. Until they are measured, ' ...
    'the joint-angle results of these tests (step 9 sheet, SPSS) contain the drift-affected automatic values.'], sum(nC), nnz(nC), ...
    ternary(isempty(todo), 'none', strjoin(arrayfun(@num2str, todo, 'UniformOutput', false), ', ')));
L = addl(L, '');
end

%% ========================================================================
%  [2] peak timing: the strides behind each outlying cell
%% ========================================================================
function L = partTiming(root, X, L)
key = struct('hip', 'hip_flexion', 'knee', 'knee_angle', 'ankle', 'ankle_angle', 'footheight', 'FootHeight', 'foot', 'Foot', ...
    'shank', 'Shank', 'thigh', 'Thigh');
ext = struct('hip_flexion', 'min', 'knee_angle', 'min', 'ankle_angle', 'max', 'FootHeight', 'max', 'Foot', 'min', 'Shank', 'min', 'Thigh', 'max');
clean = {106, {'hip_flexion', 'knee_angle', 'Thigh'}};                % step 9 CLEAN: MAD gate + median for these
nm = X.Properties.VariableNames;  cols = nm(startsWith(nm, 'timing_') & ~endsWith(nm, 'Level_Walk'));
cells = cell(0, 5);
for c = cols
    x = X.(c{1});  z = mz(x);
    for i = find(abs(z) > 3.5)'
        cells(end+1, :) = {X.Test(i), c{1}, x(i), median(x, 'omitnan'), z(i)}; %#ok<AGROW>
    end
end
L = addl(L, '## 2. Peak timing: the strides behind each outlying cell');
L = addl(L, '');
L = addl(L, ['Per stride: peak of the sign-normalized signal minus the foot apex, in %% of the gait cycle (foot apex timing: the apex ' ...
    'itself), recomputed as in `step09_group_crossing_analysis.m` (`peakTimeRelByCond`). Step 9 averages the strides (mean); for its ' ...
    'CLEAN tests it drops strides more than 3 MAD from the median and takes the median. "Robust" = that rule applied here; its z = the ' ...
    'robust value against the other participants of the column. %d outlying timing cells.'], size(cells, 1));
L = addl(L, '');
L = addl(L, '| test | parameter | condition | strides | stride values | step 9 value (recomputed) | robust | robust z |');
L = addl(L, '|---|---|---|---|---|---|---|---|');
SNT = signNormTools();  TPL = SNT.load(root);  cache = struct();  nFix = 0;
for r = 1:size(cells, 1)
    tn = cells{r,1};  tok = regexp(cells{r,2}, '^timing_(\w+?)_(W\d_H\d_(Leading|Trailing))$', 'tokens', 'once');
    k = key.(tok{1});  cond = tok{2};  f = sprintf('t%d', tn);
    if ~isfield(cache, f), cache.(f) = loadTest(root, tn, SNT, TPL); end
    v = strideTiming(cache.(f).Sg, cache.(f).S5, k, cond, ext.(k));
    isClean = tn == clean{1} && any(strcmp(k, clean{2}));
    s9 = ternary(isClean, robust(v), mean(v, 'omitnan'));  rb = robust(v);
    x = X.(cells{r,2});  others = x(X.Test ~= tn);  zr = (rb - median(others, 'omitnan')) / (1.4826 * median(abs(others - median(others, 'omitnan')), 'omitnan'));
    if abs(zr) <= 3.5, nFix = nFix + 1; end
    L = addl(L, '| %d | %s | %s | %d | %s | %.1f (%.1f) | %.1f | %.1f |', tn, regexprep(cells{r,2}, '_W\d_H\d_(Leading|Trailing)$', ''), cond, ...
        numel(v), strjoin(arrayfun(@(a) sprintf('%.1f', a), sort(v), 'UniformOutput', false), ', '), cells{r,3}, s9, rb, zr);
end
L = addl(L, '');
L = addl(L, ['**Reading.** In %d of the %d outlying timing cells the robust rule (3-MAD stride gate + median) brings the value back within ' ...
    'the range of the other participants (|z| <= 3.5): one or a few strides peak at a different extremum and pull the mean. The other ' ...
    'cells are shifted in all their strides (a real difference, or a problem of the whole trial).'], nFix, size(cells, 1));
L = addl(L, '');
end

function D = loadTest(root, tn, SNT, TPL)
b = fullfile(root, 'Results', 'Parameters Output', sprintf('Test %d', tn));
S5 = load(fullfile(b, sprintf('SegTrajectories_WithCamera_Test%d.mat', tn)));  fn = fieldnames(S5);  D.S5 = S5.(fn{1});
Sg = load(fullfile(b, sprintf('SegmentedParams_Test%d.mat', tn)));  D.Sg = SNT.apply(Sg.Seg, D.S5, TPL, 'Dot');
end

function x = strideTiming(Sg, S5, k, cond, ext)
% Per-stride timing of one condition, as step 9 (peakTimeRelByCond / footHeightPeakTimeByCond).
NSEG = Sg.nseg;  sides = {'L', 'R'};  word = {'Left', 'Right'};  x = [];
camT = {S5.camera.terrainL, S5.camera.terrainR};  camR = {S5.camera.roleL, S5.camera.roleR};  labels = {Sg.signal.label};
for s = 1:2
    if ~isfield(Sg.zhc, sides{s}), continue; end
    pos = Sg.zhc.(sides{s}).posGait;  T = camT{s};  R = camR{s};
    if strcmp(k, 'FootHeight')
        pk = nan(1, size(pos, 3));
    else
        if any(strcmp(k, {'hip_flexion', 'knee_angle', 'ankle_angle'})), lab = sprintf('Joint: %s_%s', k, lower(sides{s}));
        else, lab = sprintf('IMU: %s %s (Dot) X', word{s}, k); end
        li = find(strcmp(labels, lab), 1);  if isempty(li), continue; end
        Y = Sg.signal(li).strides;
        if strcmpi(ext, 'min'), [~, pk] = min(Y, [], 1); else, [~, pk] = max(Y, [], 1); end
        pk = (pk - 1) / (NSEG - 1) * 100;  pk(all(isnan(Y), 1)) = NaN;
    end
    for j = 1:min([numel(pk), numel(T), size(pos, 3)])
        if isempty(T{j}) || isempty(R{j}) || ~strcmp(sprintf('%s_%s', T{j}, R{j}), cond), continue; end
        Z = pos(:, 3, j);  if all(isnan(Z)), continue; end
        [~, ap] = max(Z);  apex = (ap - 1) / (NSEG - 1) * 100;
        if strcmp(k, 'FootHeight'), x(end+1) = apex; %#ok<AGROW>
        elseif ~isnan(pk(j)), x(end+1) = pk(j) - apex; %#ok<AGROW>
        end
    end
end
end

%% ========================================================================
%  SMALL HELPERS
%% ========================================================================
function m = robust(x)
% Step 9 CLEAN rule: drop strides more than 3 MAD from the median (when >= 4 strides), then the median.
x = x(~isnan(x));
if numel(x) >= 4
    md = median(x);  ad = median(abs(x - md));
    if ad > 0, x = x(abs(x - md) <= 3 * 1.4826 * ad); end
end
m = median(x);
end

function z = mz(x)
med = median(x, 'omitnan');  ad = median(abs(x - med), 'omitnan');
if ad > 0, z = (x - med) / (1.4826 * ad); else, z = zeros(size(x)); end
z(isnan(z)) = 0;
end

function n = nOut(X, tn, prefix)
% Outlying cells of one participant in the columns starting with prefix (obstacle columns only).
nm = X.Properties.VariableNames;  n = 0;
for c = nm(startsWith(nm, prefix) & ~endsWith(nm, 'Level_Walk'))
    z = mz(X.(c{1}));  n = n + nnz(abs(z(X.Test == tn)) > 3.5);
end
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end
