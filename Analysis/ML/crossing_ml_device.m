function crossing_ml_device(quick)
% CROSSING_ML_DEVICE  Device-oriented questions for obstacle-height recognition.
%
%   crossing_ml_device          % full run
%   crossing_ml_device(true)    % quick test
%
% Same data and rules as crossing_ml_matlab.m (leave-one-participant-out; every fitted step on the
% training participants; Dot features only). Questions:
%   D1  which SENSORS: thigh / shank / foot IMU on the leading leg, trailing leg, both legs
%       (soft vote), or ONE sensor on one leg (it is the leading leg in some crossings, the
%       trailing leg in others)
%   D2  how much CALIBRATION a new user needs, with the two-foot-sensor device: none (generic),
%       labelled crossings (1 of any height / 1 per height; physics-informed offset model and
%       weighted logistic), or unlabelled crossings (person scaling from the first / random n)
%   D3  how reliable when it answers: accuracy vs coverage when the device only answers above a
%       probability threshold
%   D4  would more participants help: learning curve of the best device
% The physics-informed offset model: a height score s = w'x is learned from within-person
% contrasts (ridge regression of the height level, % of leg length, on person-centred features,
% rescaled to 1 unit per % LL). For a new person s = c + level + noise with ONE unknown offset c,
% estimated from a prior (population or level walk), labelled crossings (posterior mean), or the
% person's unlabelled crossings (constrained Gaussian mixture: component spacing fixed at 10 % LL).
% Outputs -> Results/ML Models/MATLAB/ml_device_matlab.md, fig_device.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
nRep = ternary(quick, 2, 10);  nBoot = ternary(quick, 200, 2000);

Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;  mm = strcmp(Dd.units, 'mm');
obs = T.is_level == 0 & T.include_ml == 1;  lv = T.is_level == 1 & T.include_biomech == 1;
d = T(obs, :);  g = d.participant_id;  y = d.height_class;  P = unique(g)';  cl = unique(y);
C = mlTools.loadCurvesBoth(root, T.crossing_id);
[SH.lead, pn] = mlTools.shapeFeats(C.lead);  SH.trail = mlTools.shapeFeats(C.trail);  mmS = startsWith(pn, {'x_', 'h_'});
leadG = {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'};
% raw feature matrices (all rows) per role x sensor
X = struct();  MMk = struct();
for role = {'lead', 'trail'}
    r = role{1};
    for seg = {'thigh', 'shank', 'foot'}
        s = seg{1};
        if strcmp(s, 'foot')
            cols = F((startsWith(F, [r '_foot_']) | startsWith(F, [r '_zhc_']) | ismember(F, {[r '_swing_time'], [r '_stance_time']}) | ...
                (strcmp(r, 'lead') & ismember(F, leadG))));
            X.(r).(s) = [T{:, cols}, SH.(r)];  MMk.(r).(s) = [mm(ismember(F, cols)), mmS];
        else
            cols = F(startsWith(F, [r '_' s '_']));
            X.(r).(s) = T{:, cols};  MMk.(r).(s) = mm(ismember(F, cols));
        end
    end
end
selfX = @(r, s) mlTools.selfnorm(X.(r).(s)(obs, :), g);
rf = mlTools.spec('forest', 'nTrees', 300);  lr = mlTools.spec('logreg');
L = {};
L = addl(L, '# A wearable device for obstacle height - sensors, calibration, reliability (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_device.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings, 10 participants, height H1/H2/H3 (chance 33%%), every result on an unseen participant. Features per sensor: thigh or shank ' ...
    'IMU = its tilt summaries and angular velocity; foot IMU = foot tilt and angular velocity, foot acceleration, foot trajectory (ZHC) summaries and the 13 ' ...
    'clearance-shape features, swing / stance time (+ stride, speed, cadence for the leading foot). Lead / trail roles are known (recovered 100%% from the IMU, ' ...
    '`ml_report_matlab.md` 3.B). 95%% CI = participant bootstrap.'], nnz(obs));
L = addl(L, '');
t0 = tic;

% ================= D1. sensors =================
Pr = struct();
for role = {'lead', 'trail'}
    for seg = {'thigh', 'shank', 'foot'}, Pr.(role{1}).(seg{1}) = mlTools.lopo(rf, selfX(role{1}, seg{1}), y, g); end
    Pr.(role{1}).all = mlTools.lopo(rf, [selfX(role{1}, 'thigh') selfX(role{1}, 'shank') selfX(role{1}, 'foot')], y, g);
end
L = addl(L, '## D1. Which sensors? (person scaling, random forest)');
L = addl(L, '');
L = addl(L, '| sensors | leading leg only | trailing leg only | both legs (soft vote) |');
L = addl(L, '|---|---|---|---|');
R1 = struct('name', {}, 'b', {}, 'lo', {}, 'hi', {});
for seg = {'thigh', 'shank', 'foot', 'all'}
    c = cell(1, 3);  Ps = {Pr.lead.(seg{1}), Pr.trail.(seg{1}), (Pr.lead.(seg{1}) + Pr.trail.(seg{1})) / 2};
    for k = 1:3
        [b, ci] = evalP(Ps{k}, y, g, cl, nBoot);  c{k} = sprintf('%.1f%% (%.0f-%.0f)', 100*b, 100*ci(1), 100*ci(2));
    end
    lab = ternary(strcmp(seg{1}, 'all'), 'thigh + shank + foot (3 per leg)', [seg{1} ' IMU']);
    L = addl(L, '| %s | %s |', lab, strjoin(c, ' | '));
    [b, ci] = evalP(Ps{3}, y, g, cl, nBoot);
    R1(end+1) = struct('name', ternary(strcmp(seg{1}, 'all'), '6 IMUs (both legs)', sprintf('2 %s IMUs', seg{1})), 'b', b, 'lo', ci(1), 'hi', ci(2)); %#ok<AGROW>
end
L = addl(L, '');
L = addl(L, '**One sensor on one leg only** (it is the leading leg in some crossings and the trailing leg in others; the matching model is used):');
L = addl(L, '');
L = addl(L, '| sensor | right leg | left leg |');
L = addl(L, '|---|---|---|');
for seg = {'thigh', 'shank', 'foot'}
    c = cell(1, 2);  sides = 'RL';
    for k = 1:2
        isLead = strcmp(d.leading_limb, sides(k));  Pm = Pr.trail.(seg{1});  Pm(isLead, :) = Pr.lead.(seg{1})(isLead, :);
        [b, ci] = evalP(Pm, y, g, cl, nBoot);  c{k} = sprintf('%.1f%% (%.0f-%.0f)', 100*b, 100*ci(1), 100*ci(2));
        if strcmp(seg{1}, 'foot'), R1(end+1) = struct('name', sprintf('1 foot IMU (%s leg)', ternary(k == 1, 'right', 'left')), 'b', b, 'lo', ci(1), 'hi', ci(2)); end %#ok<AGROW>
    end
    L = addl(L, '| %s IMU | %s |', seg{1}, strjoin(c, ' | '));
end
L = addl(L, '');
fprintf('D1 done (%.0f s)\n', toc(t0));

% ================= D2. calibration =================
XLs = selfX('lead', 'foot');  XTs = selfX('trail', 'foot');
XLc = mlTools.calibrate(T, X.lead.foot, MMk.lead.foot);  XLc = XLc(obs, :);
XTc = mlTools.calibrate(T, X.trail.foot, MMk.trail.foot);  XTc = XTc(obs, :);
B = struct('what', {}, 'needs', {}, 'b', {});
addB = @(B, what, needs, b) [B, struct('what', what, 'needs', needs, 'b', b)];
for mo = {'logistic', lr; 'forest', rf}'
    Pq = (mlTools.lopo(mo{2}, XLc, y, g) + mlTools.lopo(mo{2}, XTc, y, g)) / 2;
    B = addB(B, sprintf('generic model (%s), level-walk scaling', mo{1}), 'a short normal walk', evalP(Pq, y, g, cl, 0));
end
Sc = mlTools.calibrate(T, SH.lead, mmS);
B = addB(B, 'generic model (logistic), lead-foot clearance-shape features only, level-walk scaling', 'a short normal walk', ...
    evalP(mlTools.lopo(lr, Sc(obs, :), y, g), y, g, cl, 0));
% physics-informed offset model on the two foot sensors
ph = physics(X.lead.foot, X.trail.foot, T, obs, lv, nRep);
B = addB(B, 'offset model, population offset', 'nothing', ph.generic);
B = addB(B, 'offset model, offset from the level walk', 'a short normal walk', ph.level);
B = addB(B, 'offset model, 1 labelled crossing of ANY height', '1 crossing with known height', ph.one);
B = addB(B, 'offset model, 1 labelled crossing per height', '3 crossings with known heights', ph.perH);
B = addB(B, 'offset model, unlabelled crossings (mixture, spacing fixed by physics)', 'the session''s crossings, no labels', ph.mix);
v = zeros(nRep, 1);
parfor r = 1:nRep, v(r) = fewShot({XLc, XTc}, y, g, 1, 10, 900 + r); end
B = addB(B, 'weighted logistic, 1 labelled crossing per height', '3 crossings with known heights', mean(v));
ord = d.trial_order;
for mode = {'first', 'random'}
    for n = [5 10 15]
        reps = ternary(strcmp(mode{1}, 'random'), nRep, 1);  v = zeros(reps, 1);
        for r = 1:reps, v(r) = selfFromN({X.lead.foot(obs,:), X.trail.foot(obs,:)}, y, g, ord, mode{1}, n, 3000 + r); end
        B = addB(B, sprintf('person scaling from the %s %d crossings (forest)', mode{1}, n), sprintf('%d unlabelled crossings', n), mean(v));
    end
end
B = addB(B, 'person scaling from all crossings (forest)', 'all the session''s crossings, no labels', evalP((Pr.lead.foot + Pr.trail.foot) / 2, y, g, cl, 0));
L = addl(L, '## D2. How much calibration does a new user need? (two foot IMUs, lead + trail vote)');
L = addl(L, '');
L = addl(L, '| approach | what the device needs from the new user | accuracy |');
L = addl(L, '|---|---|---|');
for i = 1:numel(B), L = addl(L, '| %s | %s | %.1f%% |', B(i).what, B(i).needs, 100 * B(i).b); end
L = addl(L, '');
L = addl(L, ['Offset model: ridge lambda 10; labelled-crossing rows averaged over every choice (1 of any height) or %d random draws (1 per height); ' ...
    'the offset prior comes from the level walk; the mixture estimates the offset and the class shares (equal shares NOT assumed). ' ...
    'Person scaling from n crossings: median / IQR of n crossings (no labels), tested on the remaining crossings; "first n" follows the walking order ' ...
    '(blocked order here, so the first crossings cover few obstacles - conservative).'], nRep);
L = addl(L, '');
fprintf('D2 done (%.0f s)\n', toc(t0));

% ================= D3. confidence =================
Pb = (Pr.lead.foot + Pr.trail.foot) / 2;  [pm, j] = max(Pb, [], 2);  pr = cl(j);
L = addl(L, '## D3. Answer only when confident (two foot IMUs, person scaling, forest)');
L = addl(L, '');
L = addl(L, '| answer when top probability >= | crossings answered | accuracy on them |');
L = addl(L, '|---|---|---|');
CV = [];
for th = [0 0.5 0.6 0.7 0.8]
    k = pm >= th;  CV(end+1, :) = [th, mean(k), mean(strcmp(pr(k), y(k)))]; %#ok<AGROW>
    L = addl(L, '| %.1f | %.0f%% | %.1f%% |', th, 100 * mean(k), 100 * mean(strcmp(pr(k), y(k))));
end
L = addl(L, '');
fprintf('D3 done (%.0f s)\n', toc(t0));

% ================= D4. learning curve =================
L = addl(L, '## D4. Would more participants help? (two foot IMUs, person scaling, forest)');
L = addl(L, '');
L = addl(L, 'Each unseen participant predicted by a model trained on n randomly chosen other participants (%d draws per n).', nRep);
L = addl(L, '');
L = addl(L, '| training participants | accuracy (mean) | range over draws |');
L = addl(L, '|---|---|---|');
LC = [];
for n = 2:9
    reps = ternary(n < 9, nRep, 1);  v = zeros(reps, 1);
    parfor r = 1:reps
        rs = RandStream('mt19937ar', 'Seed', 70 * n + r);  prr = cell(numel(y), 1);
        for p = P
            oth = P(P ~= p);  tr = ismember(g, oth(randperm(rs, numel(oth), n)));  te = g == p;
            ML = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), XLs(tr,:), y(tr)); %#ok<PFBNS>
            MT = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), XTs(tr,:), y(tr)); %#ok<PFBNS>
            prr(te) = mlTools.argmaxLab((mlTools.predictPipe(ML, XLs(te,:)) + mlTools.predictPipe(MT, XTs(te,:))) / 2, ML.classes);
        end
        v(r) = mlTools.balAcc(y, prr);
    end
    LC(end+1, :) = [n, mean(v), min(v), max(v)]; %#ok<AGROW>
    L = addl(L, '| %d | %.1f%% | %.1f-%.1f%% |', n, 100 * mean(v), 100 * min(v), 100 * max(v));
end
L = addl(L, '');
L = addl(L, ['**Reading.** Two foot IMUs are enough - they match or beat all six sensors. A device that has seen ~10-15 of the user''s crossings (no labels) ' ...
    'or one labelled crossing per height reaches ~85-92%%, and when it answers only above 0.7 probability it is right ~97%% of the time. The learning ' ...
    'curve is flat from a few training participants: the remaining errors come from person-to-person differences, which the calibration addresses, ' ...
    'not from the training-set size.']);
writeLines(fullfile(out, 'ml_device_matlab.md'), L);
mlTools.figures(out, 'device', struct('R1', R1, 'B', B, 'CV', CV, 'LC', LC));
fprintf('Wrote %s (%.0f s)\n', out, toc(t0));
end

%% ========================================================================
%  PHYSICS-INFORMED OFFSET MODEL
%% ========================================================================
function ph = physics(XA, XB, T, obs, lv, nRep)
g = T.participant_id;  t = T.height_pct_LL;  P = unique(g(obs))';  tk = [10 20 30];
pred = nan(height(T), 4);  oneAcc = nan(height(T), 1);  perH = zeros(nRep, 1);
parts = cell(numel(P), 1);
parfor q = 1:numel(P)
    p = P(q);  tr = obs & g ~= p;  te = find(obs & g == p);  lvp = lv & g == p;
    M = {fitScore(XA, t, g, tr, lv), fitScore(XB, t, g, tr, lv)};
    S = cellfun(@(m) m.score(m.X(te,:)), M, 'UniformOutput', false);
    Slv = cellfun(@(m) median(m.score(m.X(lvp,:)), 'omitnan'), M);
    mu0 = cellfun(@(m) m.muC, M);  muL = Slv + cellfun(@(m) m.delta, M);  tauL = cellfun(@(m) m.tauL, M);
    sig = cellfun(@(m) m.sigma, M);
    out4 = [classifyS(S, mu0, sig, tk), classifyS(S, muL, sig, tk), mixtureS(S, muL, tauL, sig, tk)];
    acc = zeros(numel(te), 1);  cnt = acc;
    for j = 1:numel(te)
        c = arrayfun(@(m) postC(S{m}(j) - t(te(j)), muL(m), tauL(m), sig(m)), 1:numel(S));
        o = setdiff(1:numel(te), j);
        pk = classifyS(cellfun(@(s) s(o), S, 'UniformOutput', false), c, sig, tk);
        acc(o) = acc(o) + (pk == t(te(o)));  cnt(o) = cnt(o) + 1;
    end
    ph1 = zeros(nRep, 2);
    for r = 1:nRep
        rs = RandStream('mt19937ar', 'Seed', 1000 * p + r);  cal = zeros(1, 3);
        for k = 1:3, i = find(t(te) == tk(k));  cal(k) = i(randi(rs, numel(i))); end
        c = arrayfun(@(m) postC(S{m}(cal) - t(te(cal)), muL(m), tauL(m), sig(m)), 1:numel(S));
        o = setdiff(1:numel(te), cal);
        pk = classifyS(cellfun(@(s) s(o), S, 'UniformOutput', false), c, sig, tk);
        ph1(r, :) = [sum(pk == t(te(o))), numel(o)];
    end
    parts{q} = struct('te', te, 'out4', out4, 'one', acc ./ cnt, 'ph1', ph1);
end
for q = 1:numel(P)
    pred(parts{q}.te, 1:3) = parts{q}.out4;  oneAcc(parts{q}.te) = parts{q}.one;  perH = perH + parts{q}.ph1(:, 1) ./ sum(cellfun(@(z) numel(z.te) - 3, parts));
end
yt = t(obs);
ph.generic = balAccNum(yt, pred(obs, 1));  ph.level = balAccNum(yt, pred(obs, 2));  ph.mix = balAccNum(yt, pred(obs, 3));
ph.one = mean(oneAcc(obs), 'omitnan');  ph.perH = mean(perH);
end

function M = fitScore(X, t, g, tr, lv)
lam = 10;
med = median(X(tr,:), 1, 'omitnan');  med(isnan(med)) = 0;
M.X = mlTools.fillMed(X, med);
gt = g(tr);  tt = t(tr);  Z = M.X(tr,:);  uq = unique(gt)';
Zc = Z;  tc = tt;
for q = uq, i = gt == q; Zc(i,:) = Z(i,:) - mean(Z(i,:), 1); tc(i) = tt(i) - mean(tt(i)); end
sd = std(Zc, 0, 1);  sd(sd == 0) = 1;
w = ((Zc ./ sd)' * (Zc ./ sd) + lam * eye(size(Z, 2))) \ ((Zc ./ sd)' * tc);
s0 = (Z ./ sd) * w;  sc = s0;
for q = uq, i = gt == q; sc(i) = s0(i) - mean(s0(i)); end
w = w * ((sc' * tc) / (sc' * sc));                       % 1 score unit = 1 % of leg length
M.score = @(Xn) (Xn ./ sd) * w;
s = M.score(Z);
cq = arrayfun(@(q) mean(s(gt == q) - tt(gt == q)), uq);
res = zeros(size(s));
for q = uq, i = gt == q; res(i) = s(i) - tt(i) - cq(uq == q); end
M.sigma = std(res);  M.muC = mean(cq);
lvq = arrayfun(@(q) median(M.score(M.X(lv & g == q, :)), 'omitnan'), uq);
M.delta = mean(cq - lvq);  M.tauL = std(cq - lvq);
end

function c = postC(r, mu, tau, sig)
c = (sum(r) / sig^2 + mu / tau^2) / (numel(r) / sig^2 + 1 / tau^2);
end

function pk = classifyS(S, c, sig, tk)
ll = zeros(numel(S{1}), numel(tk));
for m = 1:numel(S), ll = ll - (S{m}(:) - c(m) - tk).^2 / (2 * sig(m)^2); end
[~, k] = max(ll, [], 2);  pk = tk(k)';
end

function pk = mixtureS(S, mu, tau, sig, tk)
n = numel(S{1});  c = mu;  pik = ones(1, numel(tk)) / numel(tk);  ll = zeros(n, numel(tk));
for it = 1:100
    ll = log(pik) + zeros(n, numel(tk));
    for m = 1:numel(S), ll = ll - (S{m}(:) - c(m) - tk).^2 / (2 * sig(m)^2); end
    R = exp(ll - max(ll, [], 2));  R = R ./ sum(R, 2);
    for m = 1:numel(S), c(m) = postC(sum(R .* (S{m}(:) - tk), 2), mu(m), tau(m), sig(m)); end
    pik = (sum(R, 1) + 1) / (n + numel(tk));
end
[~, k] = max(ll, [], 2);  pk = tk(k)';
end

function b = balAccNum(y, p)
c = unique(y);  b = mean(arrayfun(@(k) mean(p(y == k) == k), c));
end

%% ========================================================================
%  OTHER CALIBRATIONS
%% ========================================================================
function b = fewShot(Xs, y, g, k, w, seed)
rs = RandStream('mt19937ar', 'Seed', seed);  labs = unique(y);  yt = {};  yp = {};
for p = unique(g)'
    ip = find(g == p);  cal = [];
    for c = 1:numel(labs)
        ic = ip(strcmp(y(ip), labs{c}));
        if numel(ic) > k, cal = [cal; ic(randperm(rs, numel(ic), k))]; end %#ok<AGROW>
    end
    te = setdiff(ip, cal);  tr = [find(g ~= p); cal];
    sw = ones(numel(tr), 1);  sw(ismember(tr, cal)) = w;  Pf = 0;
    for x = 1:numel(Xs)
        M = mlTools.fitPipe(mlTools.spec('logreg'), Xs{x}(tr,:), y(tr), sw);
        Pf = Pf + mlTools.predictPipe(M, Xs{x}(te,:)) / numel(Xs);
    end
    yt = [yt; y(te)]; %#ok<AGROW>
    yp = [yp; mlTools.argmaxLab(Pf, M.classes)]; %#ok<AGROW>
end
b = mlTools.balAcc(yt, yp);
end

function b = selfFromN(Xs, y, g, ord, mode, n, seed)
rs = RandStream('mt19937ar', 'Seed', seed);
P = unique(g)';  yt = cell(numel(P), 1);  yp = cell(numel(P), 1);
subs = cell(numel(P), 1);
for k = 1:numel(P)
    ip = find(g == P(k));
    if strcmp(mode, 'random'), subs{k} = randperm(rs, numel(ip), n); else, [~, o] = sort(ord(ip)); subs{k} = o(1:n); end
end
parfor k = 1:numel(P)
    p = P(k);  tr = g ~= p;  ip = find(g == p);  sub = subs{k};  te = setdiff(1:numel(ip), sub);  Pf = 0;  cls = {};
    for x = 1:numel(Xs)
        Xx = Xs{x};
        M = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), mlTools.selfnorm(Xx(tr,:), g(tr)), y(tr)); %#ok<PFBNS>
        [med, iqr] = mlTools.medIqr(Xx(ip(sub), :));
        Pf = Pf + mlTools.predictPipe(M, (Xx(ip(te), :) - med) ./ iqr) / numel(Xs);
        cls = M.classes;
    end
    yp{k} = mlTools.argmaxLab(Pf, cls);  yt{k} = y(ip(te));
end
b = mlTools.balAcc(vertcat(yt{:}), vertcat(yp{:}));
end

function [b, ci] = evalP(Pm, y, g, cl, nBoot)
pr = mlTools.argmaxLab(Pm, cl);  b = mlTools.balAcc(y, pr);  ci = [NaN NaN];
if nBoot > 0, ci = mlTools.bootCI(y, pr, g, [], nBoot); end
end

%% ========================================================================
%  HELPERS
%% ========================================================================
function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
