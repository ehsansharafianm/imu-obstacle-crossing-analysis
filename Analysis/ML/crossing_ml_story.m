     'lead heel after obstacle centre (camera)', d.lead_cam_landing_dist + w/2;
     'crossing step, trail toe -> lead heel (camera)', d.trail_cam_takeoff_dist + w + d.lead_cam_landing_dist;
     'lead toe before centre at its toe-off (camera)', d.lead_cam_takeoff_toeoff + w/2;
     'trail heel after obstacle centre (camera)', d.trail_cam_landing_dist + w/2;
     'lead foot apex progression (Dot)', d.lead_zhc_peak_h_x;
     'lead landing progression (Dot)', d.lead_zhc_x_landing;
     'trail landing progression (Dot)', d.trail_zhc_x_landing;
     'lead -> trail apex lag (Dot)', d.lead_trail_lag_ms};
