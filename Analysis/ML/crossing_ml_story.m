function crossing_ml_story(parts, quick)
% CROSSING_ML_STORY  What the wearable data say about HOW people cross obstacles.
%
%   crossing_ml_story                     % everything
%   crossing_ml_story({'map','cnn'})      % selected parts
%   crossing_ml_story([], true)           % quick test
%
% Parts (descriptive + machine learning; same data and leave-one-participant-out rules as
% crossing_ml_matlab.m / crossing_ml_explore.m):
%   map       where in the swing, and in which signal, obstacle height and width are encoded:
%             within-person effect size (eta^2) at every % of swing for the 6 Dot swing curves
%   person    the walking "signature": variance explained by the participant vs by the obstacle
%             for every feature; identifying the participant from one crossing
%   strategy  dose-response: foot lift (Dot) and clearance (camera) per cm of obstacle height,
%             per participant and limb; adaptation over the 5 repeats of an obstacle
%   cm        obstacle height in cm (nominal = % of the measured leg length) by regression,
%             then the class nearest to the person's own three nominal heights
%   embed     t-SNE map of all crossings: raw features (coloured by participant) vs
%             self-normalized features (coloured by height)
%   margin    mixed-effects slopes of the scaling, and the personal obstacle margin (why a
%             generic model tops out)
%   cnn       deep learning: 1D convolutional network on the six swing curves, one network per
%             limb (lead / trail), fused by soft vote; level and self normalization
%   width     is width visible in the camera foot placement (behaviour) or only missing in the IMU?
%   safety    can the Dot features estimate the toe clearance or detect low-clearance crossings?
%   limbs     which leg leads (dominance, obstacle height), and are the two legs' crossing-to-
%             crossing variations coupled?
% Outputs -> Results/ML Models/MATLAB/ml_story_matlab.md, fig_story_*.png

if nargin < 1 || isempty(parts), parts = {'map','person','strategy','margin','cm','embed','cnn','width','safety','limbs'}; end
if nargin < 2, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;
D.T = T;  D.F = F;  D.mm = strcmp(Dd.units, 'mm');
D.obs = T.is_level == 0 & T.include_ml == 1;
D.y = T.height_class(D.obs);  D.yw = T.width_class(D.obs);  D.g = T.participant_id(D.obs);
D.C = mlTools.loadCurvesBoth(root, T.crossing_id);
D.sig = {'thigh','shank','foot','footacc','zhc_h','zhc_x'};
D.sigName = {'thigh tilt','shank tilt','foot tilt','foot |acc|','foot height','foot progression'};
D.out = out;  D.quick = quick;
D.hNom = T.height_pct_LL / 100 .* T.leg_length_cm;           % nominal obstacle height, cm
L = {};
L = addl(L, '# The story in the data - how people cross, seen by the wearables (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_story.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, '%d obstacle crossings (include_ml), 10 participants. Nominal obstacle height = 10 / 20 / 30 %% of the measured leg length (cm).', nnz(D.obs));
L = addl(L, '');
t0 = tic;
if any(strcmp(parts, 'map')),      L = partMap(D, L);      fprintf('map done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'person')),   L = partPerson(D, L);   fprintf('person done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'strategy')), L = partStrategy(D, L); fprintf('strategy done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'margin')),   L = partMargin(D, L);   fprintf('margin done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'cm')),       L = partCm(D, L);       fprintf('cm done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'embed')),    L = partEmbed(D, L);    fprintf('embed done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'cnn')),      L = partCnn(D, L);      fprintf('cnn done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'width')),    L = partWidth(D, L);    fprintf('width done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'safety')),   L = partSafety(D, L);   fprintf('safety done (%.0f s)\n', toc(t0)); end
if any(strcmp(parts, 'limbs')),    L = partLimbs(D, L);    fprintf('limbs done (%.0f s)\n', toc(t0)); end
writeLines(fullfile(out, 'ml_story_matlab.md'), L);
fprintf('Wrote %s (%.0f s)\n', out, toc(t0));
end

%% ========================================================================
%  MAP: where in the swing are height and width encoded
%% ========================================================================
function L = partMap(D, L)
T = D.T;  o = D.obs;  g = D.g;
E = struct();
for limb = {'lead', 'trail'}
    for k = 1:numel(D.sig)
        M = D.C.(limb{1}).(D.sig{k})(o, :);
        Mc = centreWithin(M, g);
        E.(limb{1}).height(k, :) = eta2(Mc, D.y);
        E.(limb{1}).width(k, :)  = eta2(Mc, D.yw);
        E.(limb{1}).person(k, :) = eta2(M, cellstr(num2str(g)));
    end
end
apex = median(T.lead_zhc_peak_h_t(o), 'omitnan');  apexT = median(T.trail_zhc_peak_h_t(o), 'omitnan');
L = addl(L, '## 1. Where in the swing is the obstacle encoded?');
L = addl(L, '');
L = addl(L, ['For every %% of swing and each Dot swing curve, the share of the within-person variance explained by obstacle height (eta^2; each ' ...
    'participant''s mean curve removed first). 0 = no information, 1 = the curve value alone separates the heights. Median foot apex: lead %.0f%%, trail %.0f%% of swing.'], apex, apexT);
L = addl(L, '');
L = addl(L, '| limb | signal | peak eta^2 height | at %% swing | peak eta^2 width | at %% swing | mean eta^2 person (raw) |');
L = addl(L, '|---|---|---|---|---|---|---|');
pct = 0:2:100;
for limb = {'lead', 'trail'}
    for k = 1:numel(D.sig)
        [mh, ih] = max(E.(limb{1}).height(k,:));  [mw, iw] = max(E.(limb{1}).width(k,:));
        L = addl(L, '| %s | %s | %.2f | %d%% | %.2f | %d%% | %.2f |', limb{1}, D.sigName{k}, mh, pct(ih), mw, pct(iw), mean(E.(limb{1}).person(k,:), 'omitnan'));
    end
end
L = addl(L, '');
top = {};
for limb = {'lead', 'trail'}
    for k = 1:numel(D.sig)
        [mh, ih] = max(E.(limb{1}).height(k,:));  top(end+1, :) = {mh, sprintf('%s %s (eta^2 %.2f at %d%% of swing)', limb{1}, D.sigName{k}, mh, pct(ih))}; %#ok<AGROW>
    end
end
[~, o] = sort(-cell2mat(top(:,1)));
L = addl(L, ['**Reading.** The obstacle height is written most clearly in: %s. For the lead limb the information sits around the foot apex in ' ...
    'mid-swing (foot height, thigh flexion); for the trailing limb it is already there at push-off (shank tilt, foot height early in the swing). ' ...
    'Width leaves almost no trace anywhere (largest eta^2 %.2f).'], strjoin(top(o(1:4), 2), '; '), max([E.lead.width(:); E.trail.width(:)]));
L = addl(L, '');
mlTools.figures(D.out, 'story_map', struct('E', E, 'apex', apex, 'apexT', apexT, 'sigName', {D.sigName}));
end

function Mc = centreWithin(M, g)
Mc = M;
for p = unique(g)'
    i = g == p;  Mc(i,:) = M(i,:) - mean(M(i,:), 1, 'omitnan');
end
end

function e = eta2(M, lab)
u = unique(lab);  e = zeros(1, size(M, 2));
for t = 1:size(M, 2)
    v = M(:, t);  ok = isfinite(v);  v = v(ok);  l = lab(ok);  m = mean(v);
    ssb = 0;
    for k = 1:numel(u), vk = v(strcmp(l, u{k})); ssb = ssb + numel(vk) * (mean(vk) - m)^2; end
    e(t) = ssb / sum((v - m).^2);
end
end


%% ========================================================================
%  PERSON: the walking signature vs the obstacle signal
%% ========================================================================
function L = partPerson(D, L)
T = D.T;  o = D.obs;  g = D.g;  F = D.F;
X = T{o, F};  gs = cellstr(num2str(g));
ep = zeros(1, numel(F));  eh = ep;  ehw = ep;
for j = 1:numel(F)
    ep(j) = eta2(X(:, j), gs);  eh(j) = eta2(X(:, j), D.y);  ehw(j) = eta2(centreWithin(X(:, j), g), D.y);
end
ehw(~isfinite(ehw)) = -inf;  [~, o2] = sort(-ehw);  ehw(~isfinite(ehw)) = NaN;
L = addl(L, '## 2. The walking signature: who you are vs what you step over');
L = addl(L, '');
L = addl(L, ['For each of the %d Dot features: share of the variance explained by the participant (eta^2 person), by obstacle height (eta^2 height), and by ' ...
    'height after removing each participant''s mean (within-person).'], numel(F));
L = addl(L, '');
L = addl(L, '| | median over features | features where person > height |');
L = addl(L, '|---|---|---|');
L = addl(L, '| eta^2 person | %.2f | %d of %d |', median(ep, 'omitnan'), sum(ep > eh), numel(F));
L = addl(L, '| eta^2 height | %.2f | |', median(eh, 'omitnan'));
L = addl(L, '| eta^2 height, within person | %.2f | |', median(ehw, 'omitnan'));
L = addl(L, '');
L = addl(L, 'Features most sensitive to height within a person (top 10):');
L = addl(L, '');
L = addl(L, '| feature | eta^2 height within person | eta^2 person |');
L = addl(L, '|---|---|---|');
for j = o2(1:10), L = addl(L, '| `%s` | %.2f | %.2f |', F{j}, ehw(j), ep(j)); end
% who is it? participant identification from one crossing (5-fold, stratified by participant)
rng(1);  cv = cvpartition(gs, 'KFold', 5);  pr = cell(numel(gs), 1);
for k = 1:cv.NumTestSets
    tr = training(cv, k);  te = test(cv, k);
    M = mlTools.fitPipe(mlTools.spec('logreg'), X(tr,:), gs(tr));
    pr(te) = mlTools.argmaxLab(mlTools.predictPipe(M, X(te,:)), M.classes);
end
idAcc = mlTools.balAcc(gs, pr);
L = addl(L, '');
L = addl(L, ['**Who is walking?** From the features of ONE crossing, a logistic model identifies which of the 10 participants it was with **%.1f%%** ' ...
    'balanced accuracy (5-fold; chance 10%%). The same raw features give only ~53%% for the obstacle height on an unseen person (chance 33%%). ' ...
    'The personal gait signature is far stronger than the obstacle signal - which is why person-specific normalization or a short calibration ' ...
    'lifts height recognition from ~60-70%% to ~90%%.'], 100 * idAcc);
L = addl(L, '');
mlTools.figures(D.out, 'story_person', struct('ep', ep, 'eh', eh, 'ehw', ehw, 'idAcc', idAcc));
end


%% ========================================================================
%  STRATEGY: dose-response and adaptation over repeats
%% ========================================================================
function L = partStrategy(D, L)
T = D.T;  o = D.obs;  P = unique(D.g)';
h = D.hNom(o);
V = {'lead_zhc_peak_foot_h', 'lead foot lift (Dot, mm)'; 'trail_zhc_peak_foot_h', 'trail foot lift (Dot, mm)';
     'lead_cam_min_clearance', 'lead min clearance (camera, mm)'; 'trail_cam_min_clearance', 'trail min clearance (camera, mm)';
     'lead_thigh_max_corr', 'lead thigh flexion (deg)'; 'trail_shank_min_corr', 'trail shank backward tilt (deg)'};
L = addl(L, '## 3. Crossing strategy');
L = addl(L, '');
L = addl(L, '### 3.1 Dose-response: change per cm of obstacle height (nominal height from the measured leg length)');
L = addl(L, '');
L = addl(L, 'Per participant, a straight line of the variable on obstacle height (cm); slope in units per cm. Median and range over the 10 participants.');
L = addl(L, '');
L = addl(L, '| variable | median slope per cm | range over participants | participants with slope > 0 | median R^2 |');
L = addl(L, '|---|---|---|---|---|');
SL = nan(numel(P), size(V, 1));  R2 = SL;
for v = 1:size(V, 1)
    x = T.(V{v,1})(o);
    for k = 1:numel(P)
        m = D.g == P(k) & isfinite(x) & isfinite(h);
        if nnz(m) < 5, continue; end
        c = polyfit(h(m), x(m), 1);  SL(k, v) = c(1);
        r = corrcoef(h(m), x(m));  R2(k, v) = r(1,2)^2;
    end
    L = addl(L, '| %s | %.1f | %.1f to %.1f | %d / %d | %.2f |', V{v,2}, median(SL(:,v), 'omitnan'), min(SL(:,v)), max(SL(:,v)), sum(SL(:,v) > 0), sum(isfinite(SL(:,v))), median(R2(:,v), 'omitnan'));
end
L = addl(L, '');
L = addl(L, ['**Reading.** Foot lift tracks the obstacle almost one-to-one: +%.1f mm (lead) and +%.1f mm (trail) per cm of obstacle (R^2 %.2f / %.2f, ' ...
    'positive in every participant), driven by +%.1f deg of lead thigh flexion and %.1f deg of trailing shank backward tilt per cm. The camera clearance ' ...
    'margin, in contrast, hardly depends on the height (%.1f and %.1f mm per cm, R^2 %.2f / %.2f): people raise the foot by about the obstacle height ' ...
    'and keep a roughly constant safety margin, slightly smaller for taller obstacles. The wearables therefore see the obstacle mainly through how much ' ...
    'the foot is lifted, not through the margin.'], median(SL(:,1), 'omitnan'), median(SL(:,2), 'omitnan'), median(R2(:,1), 'omitnan'), median(R2(:,2), 'omitnan'), ...
    median(SL(:,5), 'omitnan'), median(SL(:,6), 'omitnan'), median(SL(:,3), 'omitnan'), median(SL(:,4), 'omitnan'), median(R2(:,3), 'omitnan'), median(R2(:,4), 'omitnan'));
L = addl(L, '');
% ---- adaptation over repeats ----
L = addl(L, '### 3.2 Adaptation over the 5 repeats of the same obstacle');
L = addl(L, '');
L = addl(L, ['Deviation from the participant x obstacle mean, by repeat position inside the block (1 = first crossing of a new obstacle). ' ...
    'Mean over participants (95%% participant-bootstrap CI).']);
L = addl(L, '');
pos = T.block_pos(o);  key = strcat(cellstr(num2str(D.g)), '_', T.obstacle_code(o));
L = addl(L, '| variable | repeat 1 | 2 | 3 | 4 | 5 | 5 minus 1 |');
L = addl(L, '|---|---|---|---|---|---|---|');
AD = nan(size(V, 1), 5);  ADlo = AD;  ADhi = AD;
for v = 1:size(V, 1)
    x = T.(V{v,1})(o);  d = nan(size(x));
    [u, ~, jj] = unique(key);
    for k = 1:numel(u), m = jj == k; d(m) = x(m) - mean(x(m), 'omitnan'); end
    cells = cell(1, 5);
    for p = 1:5
        pp = arrayfun(@(q) mean(d(D.g == q & pos == p), 'omitnan'), P);
        AD(v, p) = mean(pp, 'omitnan');
        bs = bootstrp(1000, @(z) mean(z, 'omitnan'), pp(isfinite(pp)));
        ADlo(v, p) = prctile(bs, 2.5);  ADhi(v, p) = prctile(bs, 97.5);
        cells{p} = sprintf('%+.1f (%+.1f to %+.1f)', AD(v,p), ADlo(v,p), ADhi(v,p));
    end
    L = addl(L, '| %s | %s | %+.1f |', V{v,2}, strjoin(cells, ' | '), AD(v,5) - AD(v,1));
end
L = addl(L, '');
L = addl(L, ['**Reading.** The first crossing of a new obstacle has the highest lead-foot lift (%+.1f mm vs the person x obstacle mean, 95%% CI %+.1f to %+.1f) - a ' ...
    'cautious first attempt; the later repeats scatter around the mean without a steady trend. The trailing limb shows no such first-crossing effect. ' ...
    'Order effects exist, which is why the crossing order was never used as a model feature.'], AD(1,1), ADlo(1,1), ADhi(1,1));
L = addl(L, '');
mlTools.figures(D.out, 'story_strategy', struct('x', D.hNom(o), 'Y', [T.(V{1,1})(o), T.(V{2,1})(o)], 'g', D.g, ...
    'V', {V}, 'SL', SL, 'AD', AD, 'ADlo', ADlo, 'ADhi', ADhi));
end


%% ========================================================================
%  CM: obstacle height in centimetres
%% ========================================================================
function L = partCm(D, L)
T = D.T;  o = D.obs;  g = D.g;  F = D.F;
lead = F(startsWith(F, 'lead_') | ismember(F, {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'}));
SHl = mlTools.shapeFeats(D.C.lead);  SHt = mlTools.shapeFeats(D.C.trail);
Xr = [T{:, lead}, SHl];
Xl = mlTools.calibrate(T, Xr, false(1, size(Xr, 2)));  Xl = Xl(o, :);            % level offset only (cm target keeps scale)
Xs = mlTools.selfnorm(Xr(o, :), g);
trailF = F(startsWith(F, 'trail_'));
Xts = mlTools.selfnorm([T{o, trailF}, SHt(o, :)], g);
hcm = D.hNom(o);  LL = T.leg_length_cm(o);
L = addl(L, '## 4. Obstacle height in centimetres');
L = addl(L, '');
L = addl(L, ['Regression of the nominal obstacle height (cm) from the Dot features (lead summary + shape; level offset or self normalization), leave-one-participant-out. ' ...
    'The predicted cm is then turned into a class by choosing the nearest of the person''s own three nominal heights (10 / 20 / 30 %% of their leg length, which a device knows).']);
L = addl(L, '');
L = addl(L, '| inputs | model | MAE (cm) | r | class from cm (bal. acc) |');
L = addl(L, '|---|---|---|---|---|');
setups = {'lead, level', Xl, []; 'lead, self', Xs, []; 'lead + trail vote, self', Xs, Xts};
for s = 1:size(setups, 1)
    for mdl = {'ridge', 'forest'}
        pc = lopoReg(setups{s,2}, hcm, g, mdl{1});
        if ~isempty(setups{s,3}), pc = (pc + lopoReg(setups{s,3}, hcm, g, mdl{1})) / 2; end
        cand = LL .* [0.1 0.2 0.3];  [~, k] = min(abs(cand - pc), [], 2);
        lab = {'H1','H2','H3'};  pr = lab(k)';
        r = corrcoef(pc, hcm);
        L = addl(L, '| %s | %s | %.2f | %.2f | %.1f%% |', setups{s,1}, mdl{1}, mean(abs(pc - hcm)), r(1,2), 100 * mlTools.balAcc(D.y, pr));
    end
end
L = addl(L, '');
L = addl(L, 'For scale: neighbouring nominal heights differ by 10 %% of the leg length (8.3-10.6 cm here).');
L = addl(L, '');
end

function pc = lopoReg(X, yv, g, mdl)
P = unique(g)';  parts = cell(numel(P), 1);
parfor k = 1:numel(P)
    te = g == P(k);  Xtr = X(~te,:);  med = median(Xtr, 1, 'omitnan');  med(isnan(med)) = 0; %#ok<PFBNS>
    Xtr = mlTools.fillMed(Xtr, med);  Xte = mlTools.fillMed(X(te,:), med);
    mu = mean(Xtr);  sd = std(Xtr);  sd(sd == 0) = 1;
    Ztr = (Xtr - mu) ./ sd;  Zte = (Xte - mu) ./ sd;
    if strcmp(mdl, 'ridge')
        lam = 10;  A = [ones(size(Ztr,1),1) Ztr];  Rg = lam * eye(size(A,2));  Rg(1,1) = 0;
        b = (A' * A + Rg) \ (A' * yv(~te)); %#ok<PFBNS>
        parts{k} = [ones(size(Zte,1),1) Zte] * b;
    else
        rng(0);  M = TreeBagger(300, Ztr, yv(~te), 'Method', 'regression', 'MinLeafSize', 3);
        parts{k} = predict(M, Zte);
    end
end
pc = zeros(numel(yv), 1);
for k = 1:numel(P), pc(g == P(k)) = parts{k}; end
end

%% ========================================================================
%  EMBED: t-SNE maps
%% ========================================================================
function L = partEmbed(D, L)
T = D.T;  o = D.obs;  g = D.g;  F = D.F;
X = T{o, F};  med = median(X, 1, 'omitnan');  X = mlTools.fillMed(X, med);
Xr = zscore(X);  Xs = mlTools.selfnorm(T{o, F}, g);  Xs = mlTools.fillMed(Xs, zeros(1, numel(F)));
Xs(~isfinite(Xs)) = 0;  Xs = zscore(Xs);  Xs(~isfinite(Xs)) = 0;
rng(0);  Yr = tsne(Xr, 'Perplexity', 30);
rng(0);  Ys = tsne(Xs, 'Perplexity', 30);
sr = silh(Yr, g);  sh_r = silh(Yr, D.y);  sh_s = silh(Ys, D.y);  sp_s = silh(Ys, g);
L = addl(L, '## 5. A map of all crossings (t-SNE)');
L = addl(L, '');
L = addl(L, ['2-D t-SNE of the %d Dot features. Silhouette (-1..1; higher = groups more separated): raw features - by participant %.2f, by height %.2f; ' ...
    'self-normalized - by participant %.2f, by height %.2f. Raw data cluster by PERSON; after removing each person''s own scale, the crossings ' ...
    'order by obstacle HEIGHT.'], numel(F), sr, sh_r, sp_s, sh_s);
L = addl(L, '');
mlTools.figures(D.out, 'story_embed', struct('Yr', Yr, 'Ys', Ys, 'g', g, 'y', {D.y}, 'sil', [sr, sh_r, sp_s, sh_s]));
end

function s = silh(Y, lab)
if isnumeric(lab), lab = cellstr(num2str(lab)); end
s = mean(silhouette(Y, lab), 'omitnan');
end

%% ========================================================================
%  CNN: deep learning on the swing curves
%% ========================================================================
function L = partCnn(D, L)
g = D.g;  y = D.y;  cnnBest = NaN;
nSeed = ternary(D.quick, 1, 3);  ep = ternary(D.quick, 15, 60);
L = addl(L, '## 6. Deep learning: 1D convolutional network on the swing curves');
L = addl(L, '');
L = addl(L, ['Input = the six Dot swing curves of one limb (6 channels x 51 samples, toe-off -> heel-strike). Network: conv1d(5x16) - BN - ReLU - ' ...
    'conv1d(5x32) - BN - ReLU - global average pooling - dropout 0.3 - fully connected(3) - softmax; Adam, %d epochs, L2 1e-3, training-set noise ' ...
    'augmentation (x3, sigma 0.1). One network per limb (lead / trail), fused by soft vote; ensemble of %d seeds; leave-one-participant-out.'], ep, nSeed);
L = addl(L, '');
L = addl(L, '| normalization | target | lead | trail | fusion |');
L = addl(L, '|---|---|---|---|---|');
for norm = {'level', 'self'}
    Xc = struct();
    for limb = {'lead', 'trail'}, Xc.(limb{1}) = curveTensor(D, limb{1}, norm{1}); end
    for tg = {'height', 'width'}
        yy = ternary(strcmp(tg{1}, 'height'), y, D.yw);
        PL = lopoCnn(Xc.lead, yy, g, nSeed, ep);  PT = lopoCnn(Xc.trail, yy, g, nSeed, ep);
        cl = unique(yy);  c = cell(1, 3);  Ps = {PL, PT, (PL + PT) / 2};
        for k = 1:3, c{k} = sprintf('%.1f%%', 100 * mlTools.balAcc(yy, mlTools.argmaxLab(Ps{k}, cl))); end
        if strcmp(norm{1}, 'self') && strcmp(tg{1}, 'height'), cnnBest = mlTools.balAcc(yy, mlTools.argmaxLab(Ps{3}, cl)); end
        L = addl(L, '| %s | %s | %s |', norm{1}, tg{1}, strjoin(c, ' | '));
        fprintf('  cnn %s %s done\n', norm{1}, tg{1});
    end
end
L = addl(L, '');
L = addl(L, ['**Reading.** Learning directly from the raw swing curves, with no hand-made features, the network reaches %.1f%% for height (self normalization, ' ...
    'lead + trail vote) - close to the best classic models on engineered features (~90%%, `ml_explore_matlab.md`) - and stays near chance for width. ' ...
    'So the information is in the curves themselves; at n = 10 the compact clearance features remain the more data-efficient and interpretable route, ' ...
    'and the network is the natural choice once more participants are recorded.'], 100 * cnnBest);
L = addl(L, '');
end

function X = curveTensor(D, limb, norm)
% n x 6 x 51, normalized per participant and channel.
T = D.T;  o = D.obs;  g = D.g;  n = nnz(o);
X = zeros(n, numel(D.sig), 51);
for k = 1:numel(D.sig)
    M = D.C.(limb).(D.sig{k});
    if strcmp(norm, 'level')
        M = mlTools.calibrate(T, M, repmat(any(strcmp(D.sig{k}, {'zhc_h','zhc_x'})), 1, 51));  M = M(o, :);
        s = std(M(:), 'omitnan');  M = M / s;
    else
        M = M(o, :);
        for p = unique(g)'
            i = g == p;  mu = mean(M(i,:), 1, 'omitnan');  s = std(M(i,:), 0, 'all', 'omitnan');
            M(i,:) = (M(i,:) - mu) / max(s, eps);
        end
    end
    M(~isfinite(M)) = 0;
    X(:, k, :) = reshape(M, n, 1, 51);
end
end

function Pr = lopoCnn(X, y, g, nSeed, ep)
cl = unique(y);  P = unique(g)';  parts = cell(numel(P), 1);  K = numel(cl);
parfor k = 1:numel(P)
    te = g == P(k);  tr = find(~te);
    Xtr = X(tr,:,:);  ytr = y(tr); %#ok<PFBNS>
    Xa = cat(1, Xtr, Xtr + 0.1 * randn(size(Xtr)), Xtr + 0.1 * randn(size(Xtr)));  ya = [ytr; ytr; ytr];
    seqTr = squeeze(num2cell(permute(Xa, [2 3 1]), [1 2]));
    seqTe = squeeze(num2cell(permute(X(te,:,:), [2 3 1]), [1 2]));
    Pk = zeros(nnz(te), K);
    for s = 1:nSeed
        rng(100 * k + s);
        layers = [sequenceInputLayer(size(X, 2), 'MinLength', size(X, 3))
                  convolution1dLayer(5, 16, 'Padding', 'same')
                  batchNormalizationLayer
                  reluLayer
                  convolution1dLayer(5, 32, 'Padding', 'same')
                  batchNormalizationLayer
                  reluLayer
                  globalAveragePooling1dLayer
                  dropoutLayer(0.3)
                  fullyConnectedLayer(K)
                  softmaxLayer
                  classificationLayer];
        opts = trainingOptions('adam', 'MaxEpochs', ep, 'MiniBatchSize', 32, 'L2Regularization', 1e-3, ...
            'InitialLearnRate', 1e-3, 'Shuffle', 'every-epoch', 'Verbose', false, 'ExecutionEnvironment', 'cpu');
        net = trainNetwork(seqTr, categorical(ya, cl), layers, opts);
        Pk = Pk + predict(net, seqTe) / nSeed;
    end
    parts{k} = Pk;
end
Pr = zeros(numel(y), K);
for k = 1:numel(P), Pr(g == P(k), :) = parts{k}; end
end

%% ========================================================================
%  MARGIN: personal obstacle margin + mixed-model slopes
%% ========================================================================
function L = partMargin(D, L)
T = D.T;  o = D.obs;  d = T(o, :);  g = D.g;  P = unique(g)';  h = D.hNom(o);
L = addl(L, '### 3.3 Mixed-effects estimate of the scaling (all participants together)');
L = addl(L, '');
L = addl(L, 'Linear mixed model `y ~ height_cm + (1 + height_cm | participant)` (random intercept and slope per participant); fixed slope per cm of obstacle with 95%% CI (Satterthwaite).');
L = addl(L, '');
L = addl(L, '| variable | slope per cm | 95%% CI | p |');
L = addl(L, '|---|---|---|---|');
V = {'lead_zhc_peak_foot_h', 'lead foot lift (Dot, mm)'; 'trail_zhc_peak_foot_h', 'trail foot lift (Dot, mm)';
     'lead_thigh_max_corr', 'lead thigh flexion (deg)'; 'trail_shank_min_corr', 'trail shank backward tilt (deg)';
     'lead_cam_min_clearance', 'lead min clearance (camera, mm)'; 'trail_cam_min_clearance', 'trail min clearance (camera, mm)'};
for v = 1:size(V, 1)
    tb = table(d.(V{v,1}), h, categorical(g), 'VariableNames', {'y', 'h', 'pid'});
    lm = fitlme(tb, 'y ~ h + (1 + h | pid)');
    [b, ~, st] = fixedEffects(lm, 'DFMethod', 'satterthwaite');
    L = addl(L, '| %s | %+.2f | %+.2f to %+.2f | %s |', V{v,2}, b(2), st.Lower(2), st.Upper(2), pstr(st.pValue(2)));
end
L = addl(L, '');
L = addl(L, ['**Reading.** Foot lift rises ~1 mm per mm of obstacle (lead and trail); the camera clearance margin has no reliable slope (its CI includes 0): ' ...
    'people keep a roughly constant safety margin and simply lift the foot by the obstacle height.']);
L = addl(L, '');
% ---- personal margin ----
L = addl(L, '### 3.4 The personal obstacle margin - why a generic model tops out');
L = addl(L, '');
L = addl(L, ['Per participant, the foot lift predicted by their own dose-response line at the cohort''s mean obstacle height ("personal margin"). ' ...
    'Its spread across people is compared with the step between neighbouring heights (median slope x 10 %% of the leg length), and correlated with ' ...
    'what a device could know without crossings (the person''s level-walk value of the same variable, leg length).']);
L = addl(L, '');
L = addl(L, '| variable | between-person SD | step between heights | SD / step | r with level-walk value | r with leg length |');
L = addl(L, '|---|---|---|---|---|---|');
LL = arrayfun(@(p) d.leg_length_cm(find(g == p, 1)), P)';
for v = {'lead_zhc_peak_foot_h', 'trail_zhc_peak_foot_h'}
    x = d.(v{1});  ic = nan(numel(P), 1);  sl = ic;  lvl = ic;
    for k = 1:numel(P)
        m = g == P(k) & isfinite(x);  c = polyfit(h(m), x(m), 1);  sl(k) = c(1);  ic(k) = polyval(c, mean(h));
        lvl(k) = median(T.(v{1})(T.participant_id == P(k) & T.is_level == 1 & T.include_biomech == 1), 'omitnan');
    end
    step = median(sl) * mean(d.leg_length_cm) * 0.1;
    L = addl(L, '| %s | %.0f mm | %.0f mm | %.2f | %.2f | %.2f |', strrep(v{1}, '_zhc_peak_foot_h', ' foot lift'), std(ic), step, std(ic) / step, ...
        corr(ic, lvl, 'rows', 'complete'), corr(ic, LL));
end
L = addl(L, '');
L = addl(L, ['**Reading.** People differ in how much extra they lift for ANY obstacle by about two-thirds of the step between two heights, and this ' ...
    'personal margin is hardly predictable from ordinary walking or body size. A model that has never seen the person therefore confuses neighbouring ' ...
    'heights; a few of the person''s own crossings (labelled or not) remove the problem - the reason for the ~62-73%% generic vs ~90%% personalised accuracy.']);
L = addl(L, '');
end

