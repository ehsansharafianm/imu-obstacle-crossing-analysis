%% ========================================================================
%  SAFETY: can the IMU see the clearance margin?
%% ========================================================================
function L = partSafety(D, L)
T = D.T;  o = D.obs;  d = T(o, :);  g = D.g;  P = unique(g)';  F = D.F;
SHt = mlTools.shapeFeats(D.C.trail);  SHl = mlTools.shapeFeats(D.C.lead);
XT = mlTools.selfnorm([d{:, F(startsWith(F, 'trail_'))} SHt(o,:)], g);
XL = mlTools.selfnorm([d{:, F(startsWith(F, 'lead_'))} SHl(o,:)], g);
cT = d.trail_cam_min_clearance;  cL = d.lead_cam_min_clearance;
L = addl(L, '## 8. Safety: can the wearables see the toe clearance?');
L = addl(L, '');
L = addl(L, ['Camera minimum clearance (marker centre above the obstacle top). Trailing limb: median %.0f mm; %d crossings <= 0 mm (possible contact), ' ...
    '%d < 30 mm, %d < 50 mm (of %d). Leading limb: median %.0f mm.'], median(cT, 'omitnan'), sum(cT <= 0), sum(cT < 30), sum(cT < 50), sum(isfinite(cT)), median(cL, 'omitnan'));
L = addl(L, '');
L = addl(L, '| task | inputs | result |');
L = addl(L, '|---|---|---|');
for tg = {'trail clearance (mm)', cT, XT, 'trail Dot features'; 'lead clearance (mm)', cL, XL, 'lead Dot features'; 'trail clearance (mm)', cT, XL, 'LEAD Dot features (cueing)'}'
    ok = isfinite(tg{2});
    pc = lopoReg(tg{3}(ok,:), tg{2}(ok), g(ok), 'forest');
    r = corrcoef(pc, tg{2}(ok));  gg = g(ok);  yy = tg{2}(ok);
    rw = arrayfun(@(p) corr(pc(gg == p), yy(gg == p)), P);
    L = addl(L, '| regression of %s | %s, self, forest | MAE %.0f mm (predicting the mean: %.0f); r %.2f; within-person r median %.2f |', tg{1}, tg{4}, ...
        mean(abs(pc - yy)), mean(abs(yy - mean(yy))), r(1,2), median(rw, 'omitnan'));
end
for thr = [0 30 50]
    lab = repmat({'safe'}, numel(cT), 1);  lab(cT <= thr) = {'low'};  ok = isfinite(cT);
    [Pr, cl] = mlTools.lopo(mlTools.spec('forest', 'nTrees', 300), XT(ok,:), lab(ok), g(ok));
    [~, ~, ~, auc] = perfcurve(lab(ok), Pr(:, strcmp(cl, 'low')), 'low');
