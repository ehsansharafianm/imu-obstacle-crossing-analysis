    100 * mean(d.lead_is_dominant, 'omitnan'), hh);
L = addl(L, '');
L = addl(L, ['**Reading.** The leading leg is not chosen by dominance (%.0f%% of crossings led with the dominant leg; most participants alternate) - it is ' ...
    'mostly set by which foot arrives first. A device therefore cannot assume which leg leads: it needs a sensor on each foot and the IMU role ' ...
    'detection (100%%).'], 100 * mean(d.lead_is_dominant, 'omitnan'));
L = addl(L, '');
o = T.is_level == 0 & T.include_ml == 1;  e = T(o, :);
