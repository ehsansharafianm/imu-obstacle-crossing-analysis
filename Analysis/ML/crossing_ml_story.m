L = addl(L, ['**Reading.** With person-scaled features the clearance is not predictable (r ~ 0 overall) and low-clearance crossings are only weakly ' ...
    'detectable (AUC ~0.6-0.7): scaling to the person removes their personal margin, which is most of the clearance. The raw foot lift with the ' ...
    'obstacle height does predict part of it, and within one person and obstacle the clearance follows how high the TOE goes, which the foot ' ...
    'sensor tracks only partly because the trailing foot crosses heel-up (`ml_validate_matlab.md`, V3). A safety (trip-risk) application needs a ' ...
    'better toe-height estimate (e.g. a measured sensor-to-toe geometry).']);
L = addl(L, '');
end

function s = pstr(p)
