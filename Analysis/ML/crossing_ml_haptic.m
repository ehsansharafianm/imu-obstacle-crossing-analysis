function crossing_ml_haptic(quick)
% CROSSING_ML_HAPTIC  Design numbers for a real-time haptic cue: when, which limb and segment, which threshold.
%
%   crossing_ml_haptic          % full run
%   crossing_ml_haptic(true)    % quick test
%
% The deadline of a cue for the trailing limb is the moment its toe leaves the floor, taken from the
% camera (`trail_toeoff_t_cam`): the step-4 IMU toe-off comes late on the trailing limb of a crossing
% (dataset build_report.md, task 15). Signals: thigh, shank and foot tilt (Dot, deg) and foot height
% (ZHC, mm), in physical units relative to the person's own normal walking (median level-walk
% value of the same limb role and moment; a short walk calibrates it) or relative to the person's
% typical crossing ("person-centred": median over their obstacle crossings, no labels). Every
% threshold is learned on the other participants (leave-one-participant-out); the moment is
% chosen inside the training data.
%   H1  TIMELINE: when do the events happen relative to the trailing toe lift-off?
%   H2  DETECTION: from one signal over the swing, is this stride an obstacle crossing or normal
%       walking? (swing curves, Crossing_Curves_YoungAdults.csv)
%   H3  GRADING over the swing: which obstacle height from one signal at one moment of the swing
%       (two ordered thresholds: low / middle / high)?
%   H4  DOSE: how much extra angle or lift each obstacle height needs (biofeedback targets), and
%       the crossing-to-crossing variability a personal threshold must tolerate
%   H5  REAL TIME: the same grading from the signals at fixed times before the trailing toe
%       lift-off (Crossing_Aligned_YoungAdults.csv), for cue deadlines of 500 .. 0 ms
% Outputs -> Results/ML Models/MATLAB/ml_haptic_matlab.md, fig_haptic.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
nBoot = ternary(quick, 200, 2000);

Dd = mlTools.load(root);  T = Dd.T;
obs = T.is_level == 0 & T.include_ml == 1;  lv = T.is_level == 1 & T.include_biomech == 1;
g = T.participant_id;  P = unique(g(obs))';  pct = 0:2:100;
yi = zeros(height(T), 1);  for c = 1:3, yi(strcmp(T.height_class, sprintf('H%d', c))) = c; end
hcm = T.height_pct_LL / 100 .* T.leg_length_cm;
C = mlTools.loadCurvesBoth(root, T.crossing_id);
S = {'thigh', 'thigh tilt', 'deg'; 'shank', 'shank tilt', 'deg'; 'foot', 'foot tilt', 'deg'; 'zhc_h', 'foot height', 'mm'};
lim = {'lead', 'trail'};
% swing curves relative to normal walking (ref) and to the person's typical crossing (cen)
for li = 1:2
    for s = 1:size(S, 1)
        X = C.(lim{li}).(S{s,1});  Rf = nan(size(X));  Cn = Rf;
        for p = P
            ip = g == p;  il = find(ip & lv);  io = ip & obs;
            Rf(io, :) = X(io, :) - median(X(il, :), 1, 'omitnan');
            Cn(io, :) = X(io, :) - median(X(io, :), 1, 'omitnan');
            for r = il'
                Rf(r, :) = X(r, :) - median(X(setdiff(il, r), :), 1, 'omitnan');
            end
        end
        V.(lim{li}).(S{s,1}) = struct('ref', Rf, 'cen', Cn);
    end
end
% median time of each % of swing relative to the trailing toe lift-off (camera), ms
tl = (T.lead_toeoff_t + pct / 100 .* (T.lead_landing_t - T.lead_toeoff_t) - T.trail_toeoff_t_cam) * 1000;
tt = (T.trail_toeoff_t + pct / 100 .* (T.trail_landing_t - T.trail_toeoff_t) - T.trail_toeoff_t_cam) * 1000;
tm.lead = median(tl(obs, :), 1, 'omitnan');  tm.trail = median(tt(obs, :), 1, 'omitnan');

L = {};
L = addl(L, '# A real-time haptic cue for obstacle crossing - when, where, how much (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_haptic.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings and %d level-walk strides at the obstacle line, 10 participants. Signals: thigh, shank and foot tilt (Dot ' ...
    'IMUs, deg) and foot height (ZHC, mm). "vs normal walking" = minus the person''s median level-walk value of the same limb role and moment ' ...
    '(a short walk calibrates it); "person-centred" = minus the person''s median crossing (needs some of their crossings, no labels). Times are ' ...
    'relative to the TRAILING toe lift-off seen by the camera, the deadline of a cue for the trailing limb. Thresholds are learned on 9 ' ...
    'participants and tested on the 10th.'], nnz(obs), nnz(lv));
L = addl(L, '');
t0 = tic;

%% ---------------- H1: timeline ----------------
d = T(obs, :);  ref0 = d.trail_toeoff_t_cam;
E = {'leading toe lift-off (camera)', d.lead_toeoff_t_cam; 'leading toe-off event (IMU, step 4)', d.lead_toeoff_t; ...
     'leading foot apex (IMU)', d.lead_crossing_t_imu; 'leading toe over the obstacle centre (camera)', d.lead_crossing_t_cam; ...
     'leading heel-strike (landing, IMU)', d.lead_landing_t; 'trailing toe lift-off (camera) = deadline', d.trail_toeoff_t_cam; ...
     'trailing toe over the obstacle centre (camera)', d.trail_crossing_t_cam; 'trailing toe-off event (IMU, step 4)', d.trail_toeoff_t; ...
     'trailing foot apex (IMU)', d.trail_crossing_t_imu; 'trailing heel-strike (landing, IMU)', d.trail_landing_t};
L = addl(L, '## H1. Timeline of a crossing (ms relative to the trailing toe lift-off)');
L = addl(L, '');
L = addl(L, '| event | median (ms) | IQR (ms) | crossings |');
L = addl(L, '|---|---|---|---|');
for e = 1:size(E, 1)
    v = (E{e,2} - ref0) * 1000;  ok = isfinite(v);
    L = addl(L, '| %s | %+.0f | %+.0f to %+.0f | %d |', E{e,1}, median(v(ok)), prctile(v(ok), 25), prctile(v(ok), 75), nnz(ok));
end
L = addl(L, '');
L = addl(L, ['A cue meant for the TRAILING limb must be felt and acted on before its toe leaves the floor. Time left (median): %.0f ms from the leading ' ...
    'foot apex, %.0f ms from the leading landing.'], median((ref0 - d.lead_crossing_t_imu) * 1000, 'omitnan'), median((ref0 - d.lead_landing_t) * 1000, 'omitnan'));
L = addl(L, '');
fprintf('H1 done (%.0f s)\n', toc(t0));

%% ---------------- H2: detection ----------------
L = addl(L, '## H2. Is this stride an obstacle crossing? (one signal vs normal walking, over the swing)');
L = addl(L, '');
L = addl(L, ['Positives = obstacle crossings, negatives = level-walk strides at the obstacle line. Rule: signal (vs normal walking) beyond a threshold ' ...
    'at one moment of the swing. "Nested" = moment and threshold chosen on the 9 training participants (Youden index), tested on the 10th. ' ...
    '"Earliest moment" = first %% of swing at which the fixed-moment rule reaches >= 90%% sensitivity and >= 90%% specificity on the left-out participants.']);
L = addl(L, '');
L = addl(L, '| limb | signal | nested: sensitivity / specificity | moment chosen (median, %% swing; ms vs trailing lift-off) | threshold (vs normal walking) | earliest moment with both >= 90%% |');
L = addl(L, '|---|---|---|---|---|---|');
for li = 1:2
    for s = 1:size(S, 1)
        A = V.(lim{li}).(S{s,1}).ref;  pos = obs;  use = obs | lv;
        [sn, sp, kk, ~, cur] = detectNested(A, pos, use, g, P);
        k0 = round(median(kk));  [t, sg] = fitBin(A(use & isfinite(A(:, k0)), k0), pos(use & isfinite(A(:, k0))));
        early = find(cur(:, 1) >= 0.9 & cur(:, 2) >= 0.9, 1);
        es = '-';  if ~isempty(early), es = sprintf('%d%% (%+.0f ms)', pct(early), tm.(lim{li})(early)); end
        L = addl(L, '| %s | %s | %.0f%% / %.0f%% | %d%% (%+.0f ms) | %s %+.1f %s | %s |', lim{li}, S{s,2}, 100 * sn, 100 * sp, pct(k0), tm.(lim{li})(k0), ...
            ternary(sg > 0, '>=', '<='), sg * t, S{s,3}, es);
    end
end
L = addl(L, '');
fprintf('H2 done (%.0f s)\n', toc(t0));

%% ---------------- H3: grading over the swing ----------------
L = addl(L, '## H3. How high is the obstacle? (one signal at one moment of the swing; two thresholds: low / middle / high)');
L = addl(L, '');
L = addl(L, ['Ordered rule at one moment of the swing: value below the first threshold = H1, between = H2, above the second = H3 (or the reverse when ' ...
    'the signal falls with height). Balanced accuracy on the left-out participants (chance 33%%; 95%% CI participant bootstrap); "nested" = ' ...
    'moment and thresholds chosen on the training participants only. Thresholds = the rule refitted on all participants at the most often chosen ' ...
    'moment (what a device would use). Note: the trailing swing starts at the step-4 event, i.e. after the toe has left the floor.']);
L = addl(L, '');
L = addl(L, '| limb | signal | reference | nested accuracy (95% CI) | moment (% swing; ms vs trailing lift-off) | thresholds H1/H2, H2/H3 |');
L = addl(L, '|---|---|---|---|---|---|');
yo = T.height_class(obs);  go = g(obs);
for li = 1:2
    for s = 1:size(S, 1)
        for nm = {'ref', 'vs normal walking'; 'cen', 'person-centred'}'
            A = V.(lim{li}).(S{s,1}).(nm{1})(obs, :);
            [pr, kk] = gradeMasks(A, yi(obs), go, P, true(1, size(A, 2)));
            [b, ci] = accCI(pr, yo, go, nBoot);
            k0 = mode(kk);  m = isfinite(A(:, k0));  yk = yi(obs);
            [t1, t2, sg] = fitOrd(A(m, k0), yk(m));
            L = addl(L, '| %s | %s | %s | %.1f%% (%.0f-%.0f) | %d%% (%+.0f ms) | %+.1f, %+.1f %s (%s with height) |', lim{li}, S{s,2}, nm{2}, ...
                100 * b, 100 * ci(1), 100 * ci(2), pct(k0), tm.(lim{li})(k0), sg * t1, sg * t2, S{s,3}, ternary(sg > 0, 'rises', 'falls'));
        end
    end
end
L = addl(L, '');
fprintf('H3 done (%.0f s)\n', toc(t0));

%% ---------------- H4: dose ----------------
L = addl(L, '## H4. How much? Extra angle / lift per obstacle height (targets for biofeedback)');
L = addl(L, '');
L = addl(L, ['At the moment of the swing where the height explains most of the within-person variance (eta^2 of the person-centred signal): ' ...
    'mean value vs normal walking per height (mean of the participant means +- SD across participants), change per cm of obstacle (pooled ' ...
    'within-person regression), and the crossing-to-crossing SD for one person and one obstacle (the scatter a personal threshold must tolerate).']);
L = addl(L, '');
L = addl(L, '| limb | signal | moment (% swing; ms vs trailing lift-off) | eta^2 | H1 | H2 | H3 | per cm of obstacle | crossing-to-crossing SD |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|');
cell6 = findgroups(d.participant_id, d.obstacle_code);  hc = hcm(obs);
for li = 1:2
    for s = 1:size(S, 1)
        Rf = V.(lim{li}).(S{s,1}).ref(obs, :);  Cn = V.(lim{li}).(S{s,1}).cen(obs, :);
        e2 = arrayfun(@(k) eta2c(Cn(:, k), yi(obs)), 1:numel(pct));  [em, k] = max(e2);
        L = addl(L, '| %s | %s | %d%% (%+.0f ms) | %.2f | %s | %s | %s | %s |', lim{li}, S{s,2}, pct(k), tm.(lim{li})(k), em, doseCells(Rf(:, k), Cn(:, k), yi(obs), go, P, hc, cell6, S{s,3}));
    end
end
L = addl(L, '');
fprintf('H4 done (%.0f s)\n', toc(t0));

%% ---------------- H5: real time, aligned on the trailing lift-off ----------------
[A5, kA] = mlTools.loadAligned(root, T.crossing_id);  tA = kA / 60 * 1000;
for li = 1:2
    for s = 1:size(S, 1)
        X = A5.(lim{li}).(S{s,1});  Rf = nan(size(X));  Cn = Rf;
        for p = P
            ip = g == p;  io = ip & obs;
            Rf(io, :) = X(io, :) - median(X(ip & lv, :), 1, 'omitnan');
            Cn(io, :) = X(io, :) - median(X(io, :), 1, 'omitnan');
        end
        W.(lim{li}).(S{s,1}) = struct('ref', Rf(obs, :), 'cen', Cn(obs, :));
    end
end
dl = [-500 -300 -200 -100 0];  masks = tA(:)' <= dl(:);
L = addl(L, '## H5. Real time: what one signal can tell before the trailing toe leaves the floor');
L = addl(L, '');
L = addl(L, ['Signals at fixed times relative to the trailing toe lift-off (60 Hz samples from %.1f s to +%.1f s). For each cue deadline, the moment ' ...
    'and the two thresholds are chosen on the training participants among the samples available by that deadline; balanced accuracy on the left-out ' ...
    'participants (chance 33%%), with the median chosen moment. The device must also leave time for the person to feel the cue and react, so the useful ' ...
    'deadline is earlier than the lift-off by that reaction time.'], tA(1) / 1000, tA(end) / 1000);
L = addl(L, '');
L = addl(L, '| limb | signal | reference | %s |', strjoin(arrayfun(@(x) ternary(x < 0, sprintf('data up to %d ms before', -x), 'up to the lift-off'), dl, 'UniformOutput', false), ' | '));
L = addl(L, '|---|---|---|%s', repmat('---|', 1, numel(dl)));
R5 = struct();  best = [];
for li = 1:2
    for s = 1:size(S, 1)
        for nm = {'ref', 'vs normal walking'; 'cen', 'person-centred'}'
            M = W.(lim{li}).(S{s,1}).(nm{1});
            [PR, KK, cur] = gradeMasks(M, yi(obs), go, P, masks);
            c = cell(1, numel(dl));
            for q = 1:numel(dl)
                b = accCI(PR(:, q), yo, go, 0);  c{q} = sprintf('%.0f%% (%+.0f ms)', 100 * b, median(tA(KK(:, q))));
                best(end+1, :) = [li, s, strcmp(nm{1}, 'cen'), q, b, mode(KK(:, q))]; %#ok<AGROW>
            end
            L = addl(L, '| %s | %s | %s | %s |', lim{li}, S{s,2}, nm{2}, strjoin(c, ' | '));
            R5.(lim{li}).(S{s,1}).(nm{1}) = cur;
        end
    end
end
L = addl(L, '');
q3 = find(dl == -300);
L = addl(L, '**Rules for a cue ready 300 ms before the lift-off** (refitted on all participants at the most often chosen moment; vs normal walking):');
L = addl(L, '');
L = addl(L, '| limb | signal | moment (ms vs lift-off) | H1/H2 threshold | H2/H3 threshold | direction | accuracy on left-out participants |');
L = addl(L, '|---|---|---|---|---|---|---|');
for li = 1:2
    for s = 1:size(S, 1)
        r = best(best(:,1) == li & best(:,2) == s & best(:,3) == 0 & best(:,4) == q3, :);
        M = W.(lim{li}).(S{s,1}).ref;  k0 = r(6);  m = isfinite(M(:, k0));  yk = yi(obs);
        [t1, t2, sg] = fitOrd(M(m, k0), yk(m));
        L = addl(L, '| %s | %s | %+.0f | %+.1f %s | %+.1f %s | %s | %.0f%% |', lim{li}, S{s,2}, tA(k0), sg * t1, S{s,3}, sg * t2, S{s,3}, ...
            ternary(sg > 0, 'higher obstacle = larger value', 'higher obstacle = smaller value'), 100 * r(5));
    end
end
L = addl(L, '');
fprintf('H5 done (%.0f s)\n', toc(t0));
mlTools.figures(out, 'haptic', struct('W', W, 'R5', R5, 'tA', tA, 'yo', yi(obs), 'go', go, 'P', P, ...
    'tImu', median((d.trail_toeoff_t - ref0) * 1000, 'omitnan')));
writeLines(fullfile(out, 'ml_haptic_matlab.md'), L);
fprintf('Wrote %s (%.0f s)\n', fullfile(out, 'ml_haptic_matlab.md'), toc(t0));
end

%% ========================================================================
function [b, ci] = accCI(pr, yo, go, nBoot)
% Balanced accuracy of ordered predictions (1..3; 0 = no value) and its participant-bootstrap CI.
ok = pr > 0;  lab = repmat({''}, numel(pr), 1);
lab(ok) = arrayfun(@(c) sprintf('H%d', c), pr(ok), 'UniformOutput', false);
b = mlTools.balAcc(yo(ok), lab(ok));  ci = [NaN NaN];
if nBoot > 0, ci = mlTools.bootCI(yo(ok), lab(ok), go(ok), [], nBoot); end
end

function c = doseCells(Rf, Cn, yi, go, P, hc, cell6, unit)
mh = cell(1, 3);
for c3 = 1:3
    pm = arrayfun(@(p) mean(Rf(go == p & yi == c3), 'omitnan'), P);
    mh{c3} = sprintf('%+.1f +- %.1f', mean(pm, 'omitnan'), std(pm, 'omitnan'));
end
ok = isfinite(Cn);  hcc = hc - arrayfun(@(p) mean(hc(go == p)), go);
sl = hcc(ok) \ Cn(ok);
r = Cn(ok) - arrayfun(@(k) mean(Cn(ok & cell6 == k)), cell6(ok));
sdc = sqrt(sum(r.^2) / (nnz(ok) - numel(unique(cell6(ok)))));
c = sprintf('%s | %s | %s | %+.2f %s | %.1f %s', mh{:}, sl, unit, sdc, unit);
end

function [sn, sp, kk, thr, cur] = detectNested(A, pos, use, g, P)
% Nested (moment + threshold from training) and fixed-moment LOPO detection of crossings vs level strides.
nk = size(A, 2);  pred = false(size(pos));  kk = nan(numel(P), 1);  thr = kk;  predK = false(numel(pos), nk);
for f = 1:numel(P)
    te = use & g == P(f);  trn = use & g ~= P(f);  J = -inf(1, nk);  tk = nan(1, nk);  sk = tk;
    for k = 1:nk
        m = trn & isfinite(A(:, k));
        [tk(k), sk(k), J(k)] = fitBin(A(m, k), pos(m));
        predK(te, k) = sk(k) * A(te, k) >= tk(k);
    end
    [~, kb] = max(J);  kk(f) = kb;  thr(f) = sk(kb) * tk(kb);
    pred(te) = sk(kb) * A(te, kb) >= tk(kb);
end
sn = mean(pred(use & pos));  sp = mean(~pred(use & ~pos));
cur = [mean(predK(use & pos, :), 1)', mean(~predK(use & ~pos, :), 1)'];
end

function [t, s, J] = fitBin(v, pos)
% Threshold maximising sensitivity + specificity; rule s*v >= t.
s = sign(mean(v(pos)) - mean(v(~pos)));  if s == 0 || isnan(s), s = 1; end
u = s * v;  q = unique(prctile(u, 1:99));  q = q(:)';
sens = mean(u(pos) >= q, 1);  spec = mean(u(~pos) < q, 1);
[J, k] = max(sens + spec - 1);  t = q(k);
end

function [PR, KK, cur] = gradeMasks(A, yi, g, P, masks)
% Ordered-threshold classification, leave-one-participant-out. For each row of `masks` (allowed
% moments), the moment with the best training accuracy is used for the left-out participant
% (PR = 1..3, 0 = no value; KK = chosen moment per fold). cur = fixed-moment accuracy per moment.
nk = size(A, 2);  nm = size(masks, 1);  PR = zeros(numel(yi), nm);  KK = nan(numel(P), nm);  prK = zeros(numel(yi), nk);
for f = 1:numel(P)
    te = g == P(f);  trn = ~te;  B = -inf(1, nk);
    for k = 1:nk
        m = trn & isfinite(A(:, k));
        if nnz(m) < 30 || numel(unique(yi(m))) < 3, continue; end
        [t1, t2, sg, B(k)] = fitOrd(A(m, k), yi(m));
        u = sg * A(te, k);  prK(te, k) = (1 + (u >= t1) + (u >= t2)) .* isfinite(u);
    end
    for q = 1:nm
        Bq = B;  Bq(~masks(q, :)) = -inf;  [~, kb] = max(Bq);  KK(f, q) = kb;  PR(te, q) = prK(te, kb);
    end
end
cur = nan(nk, 1);
for k = 1:nk
    ok = prK(:, k) > 0;
    if any(ok), cur(k) = mean(arrayfun(@(c) mean(prK(ok & yi == c, k) == c), 1:3)); end
end
end

function [t1, t2, s, ba] = fitOrd(v, yi)
% Two ordered thresholds maximising balanced accuracy (H1 below t1, H3 at or above t2, on s*v).
s = sign(corr(v, yi));  if s == 0 || isnan(s), s = 1; end
u = s * v;  q = unique(prctile(u, 2:2:98));  q = q(:)';  n = arrayfun(@(c) nnz(yi == c), 1:3);
c1 = sum(u(yi == 1) < q, 1)';  c2 = sum(u(yi == 2) < q, 1)';  c3 = sum(u(yi == 3) < q, 1)';
BA = (c1 / n(1) + (c2' - c2) / n(2) + (n(3) - c3') / n(3)) / 3;
BA(tril(true(numel(q), numel(q)), -1)) = -inf;
[ba, k] = max(BA(:));  [i, j] = ind2sub(size(BA), k);  t1 = q(i);  t2 = q(j);
end

function e = eta2c(x, yi)
ok = isfinite(x);  x = x(ok) - mean(x(ok));  yi = yi(ok);  sb = 0;
for c = 1:3, m = yi == c;  sb = sb + nnz(m) * mean(x(m))^2; end
e = sb / sum(x.^2);
end

%% ========================================================================
function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
