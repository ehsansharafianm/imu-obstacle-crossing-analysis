function crossing_ml_stream()
% CROSSING_ML_STREAM  Camera-free, end-to-end obstacle recognition from the continuous Dot data.
%
% Everything above (crossing_ml_matlab / _explore / _story) starts from the crossings found by
% the camera. Here the camera is used ONLY to score the result. Pipeline, for a participant the
% models never saw (leave-one-participant-out):
%   1. every ZVP->ZVP stride of both feet over the whole session (~750 per person, incl. normal
%      walking, turns, level walks) gets 12 Dot features from its ZHC foot trajectory
%      (peak height and its timing, time / distance spent high, stride length, vertical speed,
%      end height, duration);
%   2. DETECT obstacle-crossing strides (random forest, features scaled to the person's own walking);
%   3. PAIR consecutive detections of opposite feet within 1.5 s into one crossing; the earlier
%      foot is the LEAD;
%   4. HEIGHT from the lead-stride model and the trail-stride model (soft vote), features scaled to
%      the person's own detected crossings (no labels);
%   5. score against the camera: a crossing is "all correct" only if it was found, its lead and
%      trail strides are the right ones, and its height is right.
% Also: a generic variant (scaled to all walking instead of the detected crossings) and a causal
% variant (each crossing scaled with EARLIER detected crossings only).
% Outputs -> Results/ML Models/MATLAB/ml_stream_matlab.md, fig_stream.png

here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
Dd = mlTools.load(root);  T = Dd.T;
S = mlTools.strideTable(root, T);
fn = mlTools.strideFeatNames();
X = S{:, fn};  g = S.tn;  P = unique(g)';
Xw = mlTools.selfnorm(X, g);                                   % scaled to the person's own walking
yb = repmat({'other'}, height(S), 1);  yb(S.cls == "lead" | S.cls == "trail") = {'crossing'};
nObs = sum(T.is_level == 0);
L = {};
L = addl(L, '# Camera-free, end-to-end obstacle recognition (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_stream.m` on %s._', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
L = addl(L, '');
L = addl(L, ['Every ZVP->ZVP stride of both feet over the whole session: **%d strides** (10 participants), of which %d are obstacle crossings ' ...
    '(%d lead, %d trail strides), %d level-walk strides at the obstacle line, and %d other strides (normal walking, turns, starts / stops). ' ...
    '12 Dot features per stride from the ZHC foot trajectory: %s. The camera is used only to score. Leave-one-participant-out throughout.'], ...
    height(S), sum(yb == "crossing"), sum(S.cls == "lead"), sum(S.cls == "trail"), sum(S.cls == "level"), sum(S.cls == "other"), strjoin(fn, ', '));
L = addl(L, '');

% ================= 1. detection =================
L = addl(L, '## 1. Finding the crossings in the continuous recording');
L = addl(L, '');
L = addl(L, '| features | model | balanced accuracy | recall (crossings found) | precision (detections that are crossings) |');
L = addl(L, '|---|---|---|---|---|');
for nm = {'raw', X; 'scaled to own walking', Xw}'
    for mo = {'logistic', mlTools.spec('logreg'); 'random forest', mlTools.spec('forest', 'nTrees', 300)}'
        [Pr, cl] = mlTools.lopo(mo{2}, nm{2}, yb, g);
        pr = mlTools.argmaxLab(Pr, cl);
        tp = sum(strcmp(pr, 'crossing') & strcmp(yb, 'crossing'));  fp = sum(strcmp(pr, 'crossing') & ~strcmp(yb, 'crossing'));
        fnn = sum(~strcmp(pr, 'crossing') & strcmp(yb, 'crossing'));
        L = addl(L, '| %s | %s | %.1f%% | %.1f%% | %.1f%% |', nm{1}, mo{1}, 100*mlTools.balAcc(yb, pr), 100*tp/(tp+fnn), 100*tp/(tp+fp));
    end
end
L = addl(L, '');
fprintf('detection done\n');

% ================= 2. end-to-end =================
modes = {'crossing-scaled', 'walking-scaled'};
E = struct();
for m = 1:2
    E.(strrep(modes{m}, '-', '_')) = endToEnd(S, X, Xw, yb, g, modes{m}, 0);
end
L = addl(L, '## 2. End to end: detect -> pair (lead = first foot) -> height');
L = addl(L, '');
L = addl(L, ['Height step: one random forest for lead strides, one for trail strides (trained on the other participants'' camera-confirmed crossings), ' ...
    'soft vote. **crossing-scaled** = features scaled to the person''s own DETECTED crossings (median / IQR; no labels; assumes the session ' ...
    'contains a mix of obstacles); **walking-scaled** = scaled to all of the person''s walking (no assumption at all).']);
L = addl(L, '');
L = addl(L, '| height scaling | crossings found | lead + trail strides right | height right (when found) | ALL correct | false crossings (per person) |');
L = addl(L, '|---|---|---|---|---|---|');
for m = 1:2
    r = E.(strrep(modes{m}, '-', '_'));
    L = addl(L, '| %s | %.1f%% | %.1f%% | %.1f%% | **%.1f%%** | %.1f |', modes{m}, 100*mean(r.res(:,2)), 100*mean(r.res(:,3)), ...
        100*sum(r.res(:,4))/sum(r.res(:,2)), 100*mean(r.res(:,5)), mean(r.nFalse));
end
r = E.crossing_scaled;
L = addl(L, '');
L = addl(L, ['Denominator = the %d obstacle crossings with a valid Dot toe-off event (of %d in the dataset). Counting the other %d as missed, ' ...
    'the crossing-scaled pipeline is all-correct for %.1f%% of every crossing walked.'], size(r.res, 1), nObs, nObs - size(r.res, 1), ...
    100 * sum(r.res(:,5)) / nObs);
L = addl(L, '');
L = addl(L, ['| participant | ' strjoin(arrayfun(@num2str, P, 'UniformOutput', false), ' | ') ' |']);
L = addl(L, ['|---|' repmat('---|', 1, numel(P))]);
L = addl(L, ['| all correct, crossing-scaled | ' strjoin(arrayfun(@(p) sprintf('%.0f%%', 100*mean(r.res(r.res(:,1) == p, 5))), P, 'UniformOutput', false), ' | ') ' |']);
L = addl(L, '');
fprintf('end-to-end done\n');

% ================= 3. causal =================
L = addl(L, '## 3. Learning during use (causal): scale each crossing with the person''s EARLIER detected crossings only');
L = addl(L, '');
L = addl(L, 'Crossings before the first n detections are not scored. Blocked obstacle order here makes the early history narrow (conservative).');
L = addl(L, '');
L = addl(L, '| warm-up (earlier detections) | crossings scored | height right (when found) | all correct |');
L = addl(L, '|---|---|---|---|');
CA = zeros(0, 3);
for nmin = [5 10 15 20]
    rc = endToEnd(S, X, Xw, yb, g, 'crossing-scaled', nmin);
    k = rc.res(:,6) == 1;
    CA(end+1, :) = [nmin, sum(rc.res(k,4))/sum(rc.res(k,2)), mean(rc.res(k,5))]; %#ok<AGROW>
    L = addl(L, '| %d | %d | %.1f%% | %.1f%% |', nmin, nnz(k), 100*CA(end,2), 100*CA(end,3));
end
L = addl(L, '');
L = addl(L, ['**Reading.** With no camera, the Dot foot sensors alone find almost every obstacle crossing, tell which foot led, and recognise ' ...
    'the obstacle height for most crossings of a person they were never trained on - provided the device scales the features to the ' ...
    'person''s own crossings (a few minutes of use). Scaled to ordinary walking only, height drops to near the generic level, the same ' ...
    'person-specific bottleneck seen everywhere else.']);
writeLines(fullfile(out, 'ml_stream_matlab.md'), L);
mlTools.figures(out, 'stream', struct('E', E, 'CA', CA, 'P', P));
fprintf('Wrote %s\n', out);
end

%% ========================================================================
function r = endToEnd(S, X, Xw, yb, g, mode, nmin)
% Returns r.res = [participant found roleOK heightOK allOK scored] per camera crossing; r.nFalse per person.
P = unique(g)';  parts = cell(numel(P), 1);  nf = zeros(numel(P), 1);
parfor k = 1:numel(P)
    p = P(k);  tr = g ~= p;  te = find(g == p);
    M = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), Xw(tr,:), yb(tr)); %#ok<PFBNS>
    pd = mlTools.predictPipe(M, Xw(te,:));
    det = te(pd(:, strcmp(M.classes, 'crossing')) >= 0.5);
    [~, o] = sort(S.t0(det));  det = det(o);  ev = zeros(0, 2);  i = 1; %#ok<PFBNS>
    while i < numel(det)
        if S.side(det(i)) ~= S.side(det(i+1)) && S.t0(det(i+1)) - S.t0(det(i)) <= 1.5
            ev(end+1, :) = [det(i) det(i+1)];  i = i + 2; %#ok<AGROW>
        else
            i = i + 1;
        end
    end
    trL = find(tr & S.cls == "lead");  trT = find(tr & S.cls == "trail");
    if strcmp(mode, 'crossing-scaled')
        XL = mlTools.selfnorm(X(trL,:), g(trL));  XT = mlTools.selfnorm(X(trT,:), g(trT)); %#ok<PFBNS>
    else
        XL = Xw(trL,:);  XT = Xw(trT,:);
    end
    ML = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), XL, cellstr(S.hcls(trL)));
    MT = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), XT, cellstr(S.hcls(trT)));
    ne = size(ev, 1);  ZL = zeros(ne, size(X, 2));  ZT = ZL;  scored = true(ne, 1);
    for e = 1:ne
        if strcmp(mode, 'walking-scaled')
            ZL(e,:) = Xw(ev(e,1),:);  ZT(e,:) = Xw(ev(e,2),:);
        else
            hist = 1:ne;  if nmin > 0, hist = 1:e-1; scored(e) = e - 1 >= nmin; end
            if isempty(hist), hist = e; end
            [mL, iL] = mlTools.medIqr(X(ev(hist,1),:));  [mT, iT] = mlTools.medIqr(X(ev(hist,2),:));
            ZL(e,:) = (X(ev(e,1),:) - mL) ./ iL;  ZT(e,:) = (X(ev(e,2),:) - mT) ./ iT;
        end
    end
    hp = {};
    if ne > 0, hp = mlTools.argmaxLab((mlTools.predictPipe(ML, ZL) + mlTools.predictPipe(MT, ZT)) / 2, ML.classes); end
    truth = unique(S.cid(te(S.cls(te) == "lead")))';  rr = zeros(numel(truth), 6);
    for c = 1:numel(truth)
        il = te(S.cid(te) == truth(c) & S.cls(te) == "lead");  it = te(S.cid(te) == truth(c) & S.cls(te) == "trail");
        ie = find(ev(:,1) == il, 1);
        found = ~isempty(ie);  roleOK = found && ~isempty(it) && ev(ie,2) == it;
        hOK = found && strcmp(hp{ie}, S.hcls(il));
        sc = ~found || scored(ie);
        rr(c,:) = [p, found, roleOK, hOK, found && roleOK && hOK, sc];
    end
    parts{k} = rr;
    nf(k) = sum(~ismember(ev(:,1), te(S.cls(te) == "lead")));
end
r.res = vertcat(parts{:});  r.nFalse = nf;
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
