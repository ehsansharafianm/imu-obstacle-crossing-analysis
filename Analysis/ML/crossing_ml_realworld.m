function crossing_ml_realworld(quick)
% CROSSING_ML_REALWORLD  How would the obstacle-height device behave in a real session?
%
%   crossing_ml_realworld          % full run
%   crossing_ml_realworld(true)    % quick test
%
% Same data and rules as crossing_ml_matlab.m (leave-one-participant-out; Dot data only).
%   R1  Mixed obstacle order. The protocol ran obstacles in blocks; in real life they come mixed.
%       Each participant's crossings are shuffled (random orders) and the device works CAUSALLY:
%       it starts with the generic model and, once it has seen n crossings (no labels), scales
%       each new crossing with the median / IQR of the earlier ones (person scaling). Accuracy
%       by crossing number, mixed vs the real blocked order.
%   R2  A virtual real-time cueing device. (a) Detect the leading-leg crossing AT ITS FOOT APEX
%       from online stride features (all strides of the session, incl. normal walking and
%       turns); (b) predict the height from leading-leg data available at the cue moment (lead
%       foot apex, or lead landing), causally scaled as in R1; (c) cue the trailing leg only if
%       confident. Outcome per crossing: correct cue / wrong cue / no cue, the time left before
%       the trailing foot leaves the ground, and false cues on ordinary strides.
%   R3  Why some participants are harder: how consistently each person scales the foot lift with
%       the obstacle (separability d' between neighbouring heights) vs their accuracy.
% Outputs -> Results/ML Models/MATLAB/ml_realworld_matlab.md, fig_realworld.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
nOrd = ternary(quick, 3, 30);

Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;
obs = T.is_level == 0 & T.include_ml == 1;  d = T(obs, :);
g = d.participant_id;  y = d.height_class;  P = unique(g)';  cl = unique(y);  ord = d.trial_order;
C = mlTools.loadCurvesBoth(root, T.crossing_id);
[SHl, pn] = mlTools.shapeFeats(C.lead);  SHt = mlTools.shapeFeats(C.trail);  mmS = startsWith(pn, {'x_', 'h_'});
leadG = {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'};
colsL = F(startsWith(F, 'lead_foot_') | startsWith(F, 'lead_zhc_') | ismember(F, [{'lead_swing_time', 'lead_stance_time'}, leadG]));
colsT = F(startsWith(F, 'trail_foot_') | startsWith(F, 'trail_zhc_') | ismember(F, {'trail_swing_time', 'trail_stance_time'}));
XL = [d{:, colsL}, SHl(obs,:)];  XT = [d{:, colsT}, SHt(obs,:)];          % two foot IMUs (raw)
Sg = mlTools.calibrate(T, SHl, mmS);  Sg = Sg(obs, :);                    % generic fallback input
L = {};
L = addl(L, '# The device in a real session - mixed obstacles, real-time cueing (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_realworld.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings, 10 participants, height H1/H2/H3 (chance 33%%), every participant tested unseen. Device = one IMU per foot ' ...
    '(foot tilt, angular velocity, acceleration, foot trajectory and clearance-shape features). Generic fallback = the lead-foot clearance-shape logistic ' ...
    'model (73%% on its own). Person scaling = the median / IQR of the person''s EARLIER crossings only (no labels).'], nnz(obs));
L = addl(L, '');
t0 = tic;

% ================= R1. mixed obstacle order =================
nmins = [5 10];
R1 = cell(numel(P), 1);
parfor k = 1:numel(P)
    p = P(k);  tr = g ~= p;  ip = find(g == p);  n = numel(ip);
    Mg = mlTools.fitPipe(mlTools.spec('logreg'), Sg(tr,:), y(tr)); %#ok<PFBNS>
    ML = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), mlTools.selfnorm(XL(tr,:), g(tr)), y(tr)); %#ok<PFBNS>
    MT = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), mlTools.selfnorm(XT(tr,:), g(tr)), y(tr)); %#ok<PFBNS>
    Pg = mlTools.predictPipe(Mg, Sg(ip,:));
    rs = RandStream('mt19937ar', 'Seed', 500 + p);
    orders = cell(1 + nOrd, 1);  [~, orders{1}] = sort(ord(ip)); %#ok<PFBNS>
    for r = 1:nOrd, orders{1 + r} = randperm(rs, n)'; end
    res = nan(numel(orders), n, numel(nmins));                        % correctness by position
    for o = 1:numel(orders)
        oo = orders{o};
        for m = 1:numel(nmins)
            nm = nmins(m);  Pr = Pg(oo,:);
            if n > nm
                ZL = causalScale(XL(ip,:), oo, nm);  ZT = causalScale(XT(ip,:), oo, nm);
                Pr(nm+1:end,:) = (mlTools.predictPipe(ML, ZL(nm+1:end,:)) + mlTools.predictPipe(MT, ZT(nm+1:end,:))) / 2;
            end
            res(o, :, m) = strcmp(mlTools.argmaxLab(Pr, Mg.classes), y(ip(oo)))';
        end
    end
    R1{k} = res;
end
bins = {1:5, 6:10, 11:15, 16:20, 21:40};
L = addl(L, '## R1. Mixed obstacle order: the device learns the person as they walk');
L = addl(L, '');
L = addl(L, ['Accuracy by crossing number (all participants). "Mixed" = %d random orders per participant (mean); "blocked" = the real protocol order ' ...
    '(5 repeats of one obstacle, then the next). Up to crossing n the generic model answers; afterwards person scaling from the earlier crossings.'], nOrd);
L = addl(L, '');
L = addl(L, '| order | switch after | crossings 1-5 | 6-10 | 11-15 | 16-20 | 21+ | all |');
L = addl(L, '|---|---|---|---|---|---|---|---|');
CUR = struct();
for m = 1:numel(nmins)
    for kind = {'mixed', 'blocked'}
        cells = cell(1, numel(bins));  allv = [];
        for b = 1:numel(bins)
            v = [];
            for k = 1:numel(P)
                R = R1{k};  pos = bins{b}(bins{b} <= size(R, 2));
                if strcmp(kind{1}, 'blocked'), v = [v; reshape(R(1, pos, m), [], 1)]; else, v = [v; reshape(R(2:end, pos, m), [], 1)]; end %#ok<AGROW>
            end
            cells{b} = sprintf('%.1f%%', 100 * mean(v));  allv = [allv; v]; %#ok<AGROW>
        end
        L = addl(L, '| %s | %d crossings | %s | %.1f%% |', kind{1}, nmins(m), strjoin(cells, ' | '), 100 * mean(allv));
        sz = sort(cellfun(@(R) size(R, 2), R1), 'descend');  nMin = sz(min(8, numel(sz)));   % >= 8 participants contribute
        cur = nan(1, nMin);
        for j = 1:nMin
            v = [];
            for k = 1:numel(P)
                R = R1{k};  if j > size(R, 2), continue; end
                if strcmp(kind{1}, 'blocked'), v = [v; R(1, j, m)]; else, v = [v; reshape(R(2:end, j, m), [], 1)]; end %#ok<AGROW>
            end
            cur(j) = mean(v);
        end
        CUR.(sprintf('%s_%d', kind{1}, nmins(m))) = cur;
    end
end
mx = CUR.mixed_5;  bl = CUR.blocked_5;
L = addl(L, '');
L = addl(L, ['**Reading.** With obstacles in a realistic mixed order, the device starts at the generic level (%.0f%% over the first 5 crossings), ' ...
    'improves steadily while it learns the person (%.0f%% for crossings 6-15) and reaches %.0f%% from crossing 16 on. In the blocked study order the ' ...
    'early history covers only one or two obstacles, so the person scaling is biased and accuracy collapses for crossings 6-15 (%.0f%%) before ' ...
    'catching up (%.0f%% from crossing 16 on, once 3-4 obstacles have been seen). The blocked-order "learning during use" numbers elsewhere in this ' ...
    'project are therefore pessimistic for real use, where obstacles come mixed.'], 100 * mean(mx(1:5)), 100 * mean(mx(6:15)), 100 * mean(mx(16:end)), ...
    100 * mean(bl(6:15)), 100 * mean(bl(16:end)));
L = addl(L, '');
fprintf('R1 done (%.0f s)\n', toc(t0));

% ================= R2. virtual real-time cueing =================
% (a) online detection of crossing strides at the foot apex, over all strides of the sessions
S = mlTools.strideTable(root, T);
fa = {'a_h_peak','a_t_peak','a_dist_peak','a_vz_max','a_vz_mean','a_h_pre'};
XA = mlTools.selfnorm(S{:, fa}, S.tn);
yb = repmat({'other'}, height(S), 1);  yb(S.cls == "lead" | S.cls == "trail") = {'crossing'};
[Pd, cd] = mlTools.lopo(mlTools.spec('forest', 'nTrees', 300), XA, yb, S.tn);
det = Pd(:, strcmp(cd, 'crossing')) >= 0.5;
isLead = S.cls == "lead";  isOther = S.cls == "other" | S.cls == "level";
recallLead = mean(det(isLead));  fpOther = sum(det & isOther);
nSess = numel(unique(S.tn));
% detection lookup for the dataset crossings
detLead = false(height(d), 1);
for i = 1:height(d)
    j = find(isLead & S.cid == string(d.crossing_id{i}), 1);
    if ~isempty(j), detLead(i) = det(j); end
end
% (b) height from leading-leg data at the cue moment, causal person scaling, generic fallback
Cv = mlTools.loadCurves(root, T.crossing_id);
pre = {'stride_len_app1','stride_len_app2','speed_approach','lead_stance_time'};
cues = {'lead foot apex', 50; 'lead landing', 100};
L = addl(L, '## R2. A virtual real-time cueing device');
L = addl(L, '');
L = addl(L, ['**(a) Detection at the lead foot apex.** Over all %d strides of the sessions (online features available at the apex: peak height, time and distance ' ...
    'to the apex, vertical speed, height 0.1 s before; scaled to the person''s walking): %.1f%% of the leading-leg crossing strides are detected at their ' ...
    'apex; %d ordinary strides are falsely detected (%.1f per session of ~%d strides).'], height(S), 100 * recallLead, fpOther, fpOther / nSess, round(height(S) / nSess));
L = addl(L, '');
L = addl(L, ['**(b, c) Height and cue.** Leading-leg data up to the cue moment (approach strides + the lead swing curves cut at the cue), generic model for the ' ...
    'first 5 crossings, then person scaling from the earlier crossings (mixed order: mean of %d random orders; blocked: real order). A cue is given only ' ...
    'when the crossing is detected and the top probability >= the threshold. Time left = median time from the cue to the trailing foot''s toe-off.'], nOrd);
L = addl(L, '');
L = addl(L, '| cue at | time left | order | threshold | correct cue | wrong cue | no cue (missed or unsure) | cues that are right | correct cue after 15 crossings |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|');
CU = [];
for c = 1:size(cues, 1)
    [Fc, names] = mlTools.cutFeatures(Cv, cues{c,2});
    Fc = [Fc, T{:, pre}];  names = [names, pre]; %#ok<AGROW>
    mmc = startsWith(names, {'zhc_h', 'zhc_x'}) | ismember(names, {'stride_len_app1', 'stride_len_app2'});
    Fl = mlTools.calibrate(T, Fc, mmc);  Fl = Fl(obs, :);  Fr = Fc(obs, :);
    if c == 1, tl = median((d.trail_toeoff_t_cam - d.lead_crossing_t_imu) * 1000, 'omitnan');     % to the trailing lift-off (camera)
    else, tl = median((d.trail_toeoff_t_cam - d.lead_landing_t) * 1000, 'omitnan'); end
    PP = cell(numel(P), 1);
    parfor k = 1:numel(P)
        p = P(k);  tr = g ~= p;  ip = find(g == p);  n = numel(ip);
        Mg = mlTools.fitPipe(mlTools.spec('logreg'), Fl(tr,:), y(tr)); %#ok<PFBNS>
        Ms = mlTools.fitPipe(mlTools.spec('forest', 'nTrees', 300), mlTools.selfnorm(Fr(tr,:), g(tr)), y(tr)); %#ok<PFBNS>
        Pg = mlTools.predictPipe(Mg, Fl(ip,:));
        rs = RandStream('mt19937ar', 'Seed', 900 + p);
        orders = cell(1 + nOrd, 1);  [~, orders{1}] = sort(ord(ip)); %#ok<PFBNS>
        for r = 1:nOrd, orders{1 + r} = randperm(rs, n)'; end
        res = cell(numel(orders), 1);
        for o = 1:numel(orders)
            oo = orders{o};  Pr = Pg(oo,:);
            Z = causalScale(Fr(ip,:), oo, 5);  Pr(6:end,:) = mlTools.predictPipe(Ms, Z(6:end,:));
            res{o} = struct('idx', ip(oo), 'P', Pr);
        end
        PP{k} = res;
    end
    for kind = {'mixed', 'blocked'}
        for th = [0 0.6]
            corr_ = 0;  wrong = 0;  none = 0;  tot = 0;  cl15 = 0;  n15 = 0;
            for k = 1:numel(P)
                res = PP{k};  sel = ternary(strcmp(kind{1}, 'blocked'), 1, 2:numel(res));
                for o = sel
                    [pm, j] = max(res{o}.P, [], 2);  pr = cl(j);  idx = res{o}.idx;
                    cue = detLead(idx) & pm >= th;  ok = strcmp(pr, y(idx));  late = (1:numel(idx))' > 15;
                    corr_ = corr_ + sum(cue & ok);  wrong = wrong + sum(cue & ~ok);  none = none + sum(~cue);  tot = tot + numel(idx);
                    cl15 = cl15 + sum(cue & ok & late);  n15 = n15 + sum(late);
                end
            end
            CU(end+1, :) = [c, strcmp(kind{1}, 'mixed'), th, corr_ / tot, wrong / tot, none / tot, corr_ / (corr_ + wrong), cl15 / n15]; %#ok<AGROW>
            L = addl(L, '| %s | %.0f ms | %s | %.1f | %.1f%% | %.1f%% | %.1f%% | %.1f%% | %.1f%% |', cues{c,1}, tl, kind{1}, th, 100 * corr_ / tot, ...
                100 * wrong / tot, 100 * none / tot, 100 * corr_ / (corr_ + wrong), 100 * cl15 / n15);
        end
    end
end
L = addl(L, '');
a0 = CU(CU(:,1) == 1 & CU(:,2) == 1 & CU(:,3) == 0, :);  a6 = CU(CU(:,1) == 1 & CU(:,2) == 1 & CU(:,3) == 0.6, :);
tA = median((d.trail_toeoff_t_cam - d.lead_crossing_t_imu) * 1000, 'omitnan');  tLd = median((d.trail_toeoff_t_cam - d.lead_landing_t) * 1000, 'omitnan');
L = addl(L, ['**Reading.** In real time and without a camera, the lead-foot sensor finds the crossing at its apex (%.0f%%), and %.0f ms before the trailing ' ...
    'toe leaves the floor the device gives a correct height cue for %.0f%% of the crossings over a whole mixed session (%.0f%% once it has seen 15 ' ...
    'crossings). Only leading-leg data exist at that moment, so the real-time cue is less accurate than the after-the-fact recognition; a ' ...
    'confidence threshold of 0.6 raises the share of right cues from %.0f%% to %.0f%%, at the cost of withholding %.0f%% of the cues. Waiting for the ' ...
    'lead landing leaves only %.0f ms. False detections on ordinary strides (~%.0f per session) would need a second check in a product ' ...
    '(e.g. confirm when the trailing foot starts its swing).'], 100 * recallLead, tA, 100 * a0(4), 100 * a0(8), 100 * a0(7), 100 * a6(7), 100 * a6(6), tLd, fpOther / nSess);
L = addl(L, '');
fprintf('R2 done (%.0f s)\n', toc(t0));

% ================= R3. why some participants are harder =================
[PLs, ~] = mlTools.lopo(mlTools.spec('forest', 'nTrees', 300), mlTools.selfnorm(XL, g), y, g);
PTs = mlTools.lopo(mlTools.spec('forest', 'nTrees', 300), mlTools.selfnorm(XT, g), y, g);
prB = mlTools.argmaxLab((PLs + PTs) / 2, cl);
prG = mlTools.argmaxLab(mlTools.lopo(mlTools.spec('logreg'), Sg, y, g), cl);
h = d.height_pct_LL / 100 .* d.leg_length_cm;
L = addl(L, '## R3. Why are some participants harder?');
L = addl(L, '');
L = addl(L, ['d'' = separability of the foot lift between neighbouring heights for that person (mean difference between adjacent heights / pooled within-height SD; ' ...
    'higher = more consistent scaling). Accuracy = two-foot person-scaled model and generic model, each participant tested unseen.']);
L = addl(L, '');
L = addl(L, '| participant | lead lift d'' | trail lift d'' | lead lift SD within height (mm) | lead slope (mm/cm) | accuracy, person-scaled | accuracy, generic |');
L = addl(L, '|---|---|---|---|---|---|---|');
Q = zeros(numel(P), 6);
for k = 1:numel(P)
    m = g == P(k);
    [dl, sdl] = dprime(d.lead_zhc_peak_foot_h(m), y(m));  dt = dprime(d.trail_zhc_peak_foot_h(m), y(m));
    c = polyfit(h(m & isfinite(d.lead_zhc_peak_foot_h)), d.lead_zhc_peak_foot_h(m & isfinite(d.lead_zhc_peak_foot_h)), 1);
    Q(k,:) = [dl, dt, sdl, c(1), mean(strcmp(prB(m), y(m))), mean(strcmp(prG(m), y(m)))];
    L = addl(L, '| %d | %.1f | %.1f | %.0f | %.1f | %.0f%% | %.0f%% |', P(k), Q(k,1:4), 100 * Q(k,5), 100 * Q(k,6));
end
L = addl(L, '');
[~, worst] = min(Q(:,5));
L = addl(L, ['Correlation over the 10 participants: person-scaled accuracy vs lead d'' r = %.2f, vs trail d'' r = %.2f; generic accuracy vs lead d'' ' ...
    'r = %.2f, vs trail d'' r = %.2f. **Reading.** Once the device is scaled to the person, its errors follow how consistently that person lifts the ' ...
    'TRAILING foot for a given height: the weakest participant (%d, %.0f%%) has the least consistent trailing lift (d'' %.1f). The generic model ' ...
    'behaves differently - its accuracy does not rise with consistency (it is even lower for some of the most consistent people): its errors come from ' ...
    'how far a person''s personal margin (offset) is from the group, which person scaling removes. n = 10, so these correlations are indicative.'], ...
    corr(Q(:,5), Q(:,1)), corr(Q(:,5), Q(:,2)), corr(Q(:,6), Q(:,1)), corr(Q(:,6), Q(:,2)), P(worst), 100 * Q(worst,5), Q(worst,2));
L = addl(L, '');
writeLines(fullfile(out, 'ml_realworld_matlab.md'), L);
mlTools.figures(out, 'realworld', struct('CUR', CUR, 'CU', CU, 'cues', {cues}, 'Q', Q, 'P', P));
fprintf('Wrote %s (%.0f s)\n', out, toc(t0));
end

%% ========================================================================
function Z = causalScale(X, oo, nmin)
% Rows of X in the order oo, each scaled with the median / IQR of the rows BEFORE it; NaN for the
% first nmin rows.
Z = nan(numel(oo), size(X, 2));
for j = nmin + 1:numel(oo)
    [med, iqr] = mlTools.medIqr(X(oo(1:j-1), :));
    Z(j,:) = (X(oo(j), :) - med) ./ iqr;
end
end

function [dp, sdw] = dprime(x, y)
lv = {'H1','H2','H3'};  mu = zeros(1, 3);  ss = 0;  nn = 0;
for k = 1:3
    v = x(strcmp(y, lv{k}) & isfinite(x));  mu(k) = mean(v);  ss = ss + sum((v - mu(k)).^2);  nn = nn + numel(v) - 1;
end
sdw = sqrt(ss / nn);  dp = mean(diff(mu)) / sdw;
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
