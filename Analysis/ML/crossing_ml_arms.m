function m = accumMean(x, id)
% Mean of x within each group of id (NaN ignored), returned per element.
ok = isfinite(x);
s = accumarray(id(ok), x(ok), [max(id), 1]);  n = accumarray(id(ok), 1, [max(id), 1]);
m = s(id) ./ n(id);
end

function [r, p] = withinCorr(a, b, id)
% Correlation of a and b after removing the mean of each cell (cells of one crossing dropped); p from t with
% N - cells - 1 degrees of freedom.
ok = isfinite(a) & isfinite(b);  a = a(ok);  b = b(ok);  id = findgroups(id(ok));
n = accumarray(id, 1);  keep = n(id) >= 2;  a = a(keep);  b = b(keep);  id = findgroups(id(keep));
a = a - accumMean(a, id);  b = b - accumMean(b, id);
r = (a' * b) / sqrt((a' * a) * (b' * b));
df = numel(a) - max(id) - 1;
t = r * sqrt(df / (1 - r^2));  p = 2 * tcdf(-abs(t), df);
end

function s = rcell(r, p)
