function crossing_ml_arms(quick)
% CROSSING_ML_ARMS  What do the arms and the trunk do when a person steps over an obstacle?
%
%   crossing_ml_arms          % full run (a few minutes, most of it the permutation tests of A11)
%   crossing_ml_arms(true)    % quick test (fewer permutations and bootstrap resamples)
%
% Input: Results/ML Dataset/Arm_Master_YoungAdults.csv and Arm_Curves_YoungAdults.mat (build_arm_dataset.m:
% heading-free upper-arm, forearm and trunk angles of every crossing from the tilt of the Awinda IMUs, plus
% the OpenSim IK shoulder / elbow angles) and the crossing master (events, obstacle, camera clearance).
% Rows: include_biomech = 1 and arm_ok = 1. The leading-limb stride and the trailing-limb stride are analysed
% separately (never compared with each other). In a stride, "opposite arm" = the arm contralateral to the
% leg of that stride (it swings forward with that leg), "same-side arm" = the ipsilateral arm.
% LEVEL-WALK REFERENCE, MATCHED BY SIDE. People swing their two arms differently and many lead with the same
% leg at every obstacle, so "the opposite arm" of the obstacle strides can be one physical arm and that of
% the few level walks another. The level value of a participant is therefore taken from the level strides
% of the same leg (stride measures; both strides of every level walk are used) or from the level walks led
% by the same limb (crossing measures), weighted by how often each side did the crossing (levelRef).
%   A1  DATA QUALITY: arm IMUs vs the IK shoulder / elbow angles, per participant
%   A2  LEVEL WALKING: swing of the shoulder, forearm and elbow, left / right, coupling with the opposite leg
%   A3  THE TWO ARM IMUs AND THE TWO JOINTS: upper arm, forearm, shoulder and elbow in the level walk and in each of
%       the six obstacles (range, peaks), every obstacle against the level walk, the obstacles against each other,
%       and the variability between people and from repeat to repeat
%   A4  OBSTACLE vs LEVEL WALKING: every arm and trunk measure, participant means, FDR (key measures first)
%   A5  HEIGHT x WIDTH: repeated-measures ANOVA, H3 - H1 and the change per cm (mixed model)
%   A6  TIMING: when the arm reaches its forward peak, and how long its forward swing lasts
%   A7  PARTICIPANTS: who shows each change
%   A8  WHAT GOES WITH IT: walking speed, and the crossing-to-crossing links with the trunk and the clearance
%   A9  THE IK ANGLES: do they agree with the heading-free angles, and do they show the same effects?
%   A10  STRIDES BEFORE AND AFTER the obstacle
%   A11 CAN THE UPPER BODY TELL THE OBSTACLE HEIGHT? leave-one-participant-out classification
% Outputs -> Results/ML Models/MATLAB/ml_arms_matlab.md, fig_arms_*.png (crossing_ml_figures, group 'arms'),
%            figdata/arms_numbers.json (the key numbers of the report, for the slides), and
%            Results/ML Dataset/Arm_YoungAdults_SPSS.xlsx: one row per participant with the participant mean of every
%            measure of A3 and A4 per obstacle and stride and for the level walk (for SPSS, like the step 9 sheet)

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
CFG.nBoot = ternary(quick, 200, 2000);  CFG.nPerm = ternary(quick, 20, 500);
t0 = tic;
D = loadArms(root);
R = effects(D);                                   fprintf('effects done (%.0f s)\n', toc(t0));
[L1, Q] = partQuality(D, {});                     fprintf('A1 done (%.0f s)\n', toc(t0));
[L2, LV] = partLevel(D, {});                      fprintf('A2 done (%.0f s)\n', toc(t0));
[LS, SG] = partSegments(D, {});                   fprintf('A3 done (%.0f s)\n', toc(t0));
L3 = partObstacle(D, {}, R);                      fprintf('A4 done (%.0f s)\n', toc(t0));
L4 = partHeight(D, {}, R);                        fprintf('A5 done (%.0f s)\n', toc(t0));
[L5, TM] = partTiming(D, {});                     fprintf('A6 done (%.0f s)\n', toc(t0));
[L6, PP] = partParticipants(D, {});               fprintf('A7 done (%.0f s)\n', toc(t0));
[L7, LK] = partLinks(D, {});                      fprintf('A8 done (%.0f s)\n', toc(t0));
[L8, IK] = partIK(D, {});                         fprintf('A9 done (%.0f s)\n', toc(t0));
[L9, SQ] = partSequence(D, {});                   fprintf('A10 done (%.0f s)\n', toc(t0));
[L10, ML] = partML(D, {}, CFG);                   fprintf('A11 done (%.0f s)\n', toc(t0));
L = {};
L = addl(L, '# Arms and trunk during obstacle crossing (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_arms.m` on %s%s._', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ...
    ternary(quick, ' (QUICK run: fewer permutations and bootstrap resamples)', ''));
L = addl(L, '');
L = addl(L, ['Source: `Results/ML Dataset/Arm_Master_YoungAdults.csv` (`build_arm_dataset.m`), %d of the %d rows of the crossing master ' ...
    '(`include_biomech` = 1 and both crossing strides with complete arm IMU data): %d obstacle crossings and %d level walks of %d ' ...
    'participants (W1 / W2 = 5 / 15 cm wide, H1-H3 = 10 / 20 / 30 %% of leg length). Angles are heading-free (tilt of the Awinda IMUs on ' ...
    'the upper arms, forearms and sternum; 0 deg = the standing posture at the start of the trial): the upper arm to the vertical, the ' ...
    'upper arm to the trunk (shoulder = upper arm + trunk pitch), the planar elbow (forearm - upper arm), the frontal elevation ' ...
    '(abduction) and the trunk pitch and roll. Windows: the stride (ZVP to ZVP) of the leading limb over the obstacle, the stride of the ' ...
    'trailing limb, and the crossing (leading toe-off to trailing landing). Opposite arm = contralateral to the leg of the stride, ' ...
    'same-side arm = ipsilateral. Statistics on participant means (n = %d); p < 0.05 is called significant; q = Benjamini-Hochberg false ' ...
    'discovery rate over the %d measures of a table.'], D.n(2), D.n(1), D.n(3), D.n(4), numel(D.P), numel(D.P), numel(D.I));
L = addl(L, '');
L = [L, overview(D, R, Q, LV, SG, TM, PP, IK, ML), L1, L2, LS, L3, L4, L5, L6, L7, L8, L9, L10];
mlTools.figures(out, 'arms', figData(D, R, Q, LV, SG, TM, PP, LK, IK, SQ, ML));
writeLines(fullfile(out, 'ml_arms_matlab.md'), L);
writeNumbers(fullfile(out, 'figdata', 'arms_numbers.json'), D, R, Q, LV, SG, TM, PP, LK, IK, SQ, ML, quick);
writeWide(D, SG, fullfile(root, 'Results', 'ML Dataset', 'Arm_YoungAdults_SPSS.xlsx'));
fprintf('Wrote %s (%.0f s)\n', fullfile(out, 'ml_arms_matlab.md'), toc(t0));
end

function writeNumbers(file, D, R, Q, LV, SG, TM, PP, LK, IK, SQ, ML, quick)
% The numbers of the report as JSON (participant means and tests of every measure, and the summaries of each
% part), so that the slides quote them without retyping.
N = struct('quick', quick, 'rows', D.n, 'participants', D.P);
for i = 1:numel(D.I)
    r = R(i);
    N.items.(D.I(i).col) = struct('label', D.I(i).label, 'unit', D.I(i).unit, 'stride', D.I(i).cls, 'level', mean(r.lv, 'omitnan'), ...
        'H', mean(r.Hm, 1, 'omitnan'), 'W', mean(r.Wm, 1, 'omitnan'), 'cells', mean(r.M, 1, 'omitnan'), 'obstacles', mean(r.ob, 'omitnan'), ...
        'd', r.dLev, 'ci', r.ciLev, 'dz', r.dzLev, 'p', r.pLev, 'q', r.qLev, 'nDir', r.nDir, 'eta', r.eta, 'pA', r.pA, 'qH', r.qH, 'qW', r.qW, ...
        'slope', r.slope, 'slopeCI', r.slopeCI, 'pSlope', r.pSlope, 'dH31', r.dH31);
end
N.count = struct('n', numel(R), 'level', nnz([R.qLev] < 0.05), 'height', nnz([R.qH] < 0.05), 'width', nnz([R.qW] < 0.05));
N.quality = struct('trendIK', Q.trendIK, 'trendFree', Q.trendFree, 'elbowLimit', Q.elbowLimit, 'rFlex', Q.rFlex, 'leak', Q.leak, 'ikMiss', Q.ikMiss, ...
    'cons', Q.cons, 'loss', Q.loss, 'rows', Q.rows, 'ikMissingRows', IK.nMissing);
N.level = rmfield(LV, 'curve');
N.seg = rmfield(SG, 'S');  N.seg.key = SG.S(:, 1)';  N.seg.signal = SG.S(:, 2)';  N.seg.measure = SG.S(:, 3)';
N.timing = struct('rows', {TM.rows}, 'tab', TM.tab, 'p', TM.p, 'phase', TM.phase, 'trunk', TM.trunk);
N.people = struct('key', {PP.key(:, 1)'}, 'label', {PP.key(:, 2)'}, 'nDir', PP.nDir, 'd', PP.d, 'p', PP.p);
N.links = struct('slope', LK.scSlope, 'r', LK.scR, 'speed', LK.speed, 'rw', {LK.rw}, 'cl', {LK.cl}, 'rmat', LK.r, 'pmat', LK.pr);
N.ik = struct('r', IK.r, 'bias', IK.bias, 'eff', IK.eff, 'pe', IK.pe);
N.seq = struct('k', SQ.k, 'm', SQ.m, 'p', SQ.p);
N.ml = struct('sets', {ML.sets}, 'acc', ML.acc, 'ci', ML.ci, 'p', ML.p, 'n', ML.n, 'nf', ML.nf, 'cm', ML.cm);
fid = fopen(file, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', file);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s', jsonencode(N));
end

function writeWide(D, SG, file)
% One row per participant, 3 decimals: for every stride measure of A3 and A4 the six obstacle means and the
% side-matched level walk, Leading columns first, then Trailing (names <measure>_<condition>_<stride>, as in the
% step 9 SPSS sheet); the crossing measures have one set of columns (<measure>_<condition>).
cn = {'W1_H1', 'W1_H2', 'W1_H3', 'W2_H1', 'W2_H2', 'W2_H3'};
keys = unique([strcat('con_', SG.S(:, 1)); D.V(:, 1)], 'stable');
W = table(D.P(:), 'VariableNames', {'participant'});
for k = 1:numel(keys)
    for l = 1:2
        [M, lv] = cellMeans([D.pre{l} '_' keys{k}], D);
        for c = 1:6, W.(sprintf('%s_%s_%s', keys{k}, cn{c}, D.lab{l})) = round(M(:, c), 3); end
        W.(sprintf('%s_Level_Walk_%s', keys{k}, D.lab{l})) = round(lv, 3);
    end
end
for k = 1:size(D.W, 1)
    [M, lv] = cellMeans(D.W{k,1}, D);
    for c = 1:6, W.(sprintf('%s_%s', D.W{k,1}, cn{c})) = round(M(:, c), 3); end
    W.(sprintf('%s_Level_Walk', D.W{k,1})) = round(lv, 3);
end
try
    if isfile(file), delete(file); end
    writetable(W, file, 'Sheet', 'ArmsTrunk');
catch err
    warning('crossing_ml_arms:wide', 'Arm_YoungAdults_SPSS.xlsx not written (%s): close it in Excel / SPSS and run again', err.message);
end
end

