    'ips_sh_rom',      'shoulder swing, same-side arm',                        'deg',     'swing';
    'con_arm_rom',     'whole-arm swing to the vertical, opposite arm',        'deg',     'swing';
    'ips_arm_rom',     'whole-arm swing to the vertical, same-side arm',       'deg',     'swing';
    'con_vel_max',     'peak forward speed of the opposite arm',               'deg/s',   'swing';
    'con_sh_max',      'forward peak of the opposite arm, to the trunk',       'deg',     'peaks';
    'con_ua_max',      'forward peak of the opposite arm, to the vertical',    'deg',     'peaks';
    'ips_sh_min',      'backward peak of the same-side arm, to the trunk',     'deg',     'peaks';
    'ips_ua_min',      'backward peak of the same-side arm, to the vertical',  'deg',     'peaks';
    'con_elb_max',     'elbow flexion peak, opposite arm',                     'deg',     'elbow';
    'ips_elb_max',     'elbow flexion peak, same-side arm',                    'deg',     'elbow';
    'con_abt_max',     'abduction peak to the trunk, opposite arm',            'deg',     'abduction';
    'ips_abt_max',     'abduction peak to the trunk, same-side arm',           'deg',     'abduction';
    'con_abd_max',     'abduction peak to the vertical, opposite arm',         'deg',     'abduction';
    'ips_abd_max',     'abduction peak to the vertical, same-side arm',        'deg',     'abduction';
    'trunk_pitch_max', 'trunk forward lean, peak',                             'deg',     'trunk';
    'trunk_pitch_rom', 'trunk pitch range',                                    'deg',     'trunk';
    'trunk_roll_rom',  'trunk roll range',                                     'deg',     'trunk';
    'cpl_gain',        'arm swing per degree of thigh range',                  'deg/deg', 'coordination';
    'cpl_r',           'arm-thigh correlation',                                '-',       'coordination';
    'con_lag_hs',      'arm forward peak minus foot landing',                  'ms',      'coordination';
    'thigh_rom',       'thigh range (Dot)',                                    'deg',     'leg';
    'stride_dur',      'stride duration',                                      's',       'leg'};
% measures of the whole crossing (leading toe-off to trailing landing)
D.W = { ...
    'cw_ls_ua_mean',      'mean posture of the lead-side upper arm, to the vertical',   'deg';
    'cw_ts_ua_mean',      'mean posture of the trail-side upper arm, to the vertical',  'deg';
    'cw_ls_sh_mean',      'mean posture of the lead-side upper arm, to the trunk',      'deg';
