function [Wc, Wl] = repeatSD(D, col)
% Repeat-to-repeat SD of a stride measure within each participant: per obstacle (columns W1_H1 ... W2_H3), pooled
% over the crossings led by the left and by the right limb (so a change of arm between repeats does not count),
% and for the level walk, pooled over the level strides of the left and of the right leg.
cells = {'W1', 'H1'; 'W1', 'H2'; 'W1', 'H3'; 'W2', 'H1'; 'W2', 'H2'; 'W2', 'H3'};
x = D.A.(col);  nP = numel(D.P);  Wc = nan(nP, 6);  Wl = nan(nP, 1);
tok = regexp(col, '^(lead|trail)_(.+)$', 'tokens', 'once');
xl = D.A.(['lead_' tok{2}]);  xt = D.A.(['trail_' tok{2}]);
for k = 1:nP
    i = D.g == D.P(k);  lev = i & D.lev;
    for c = 1:6
        r = i & strcmp(D.wc, cells{c,1}) & strcmp(D.hc, cells{c,2}) & isfinite(x);
        Wc(k, c) = pooledSD({x(r & D.leadL), x(r & ~D.leadL)});
    end
    Wl(k) = pooledSD({[xl(lev & D.leadL); xt(lev & ~D.leadL)], [xl(lev & ~D.leadL); xt(lev & D.leadL)]});
end
end

function s = pooledSD(G)
% Pooled SD of the groups in G (groups of fewer than two values are skipped; NaN if none is left).
ss = 0;  df = 0;
for k = 1:numel(G)
    v = G{k}(isfinite(G{k}));
    if numel(v) >= 2, ss = ss + (numel(v) - 1) * var(v);  df = df + numel(v) - 1; end
end
if df > 0, s = sqrt(ss / df); else, s = NaN; end
end

function sh = varShares(D, x)
% Shares (%) of the variance of the obstacle crossings, from the variance components of the mixed model
% y ~ 1 + (1 | person) + (1 | person:arm) + (1 | person:arm:obstacle) (REML): the person, the arm (leading limb
% left or right, i.e. which physical arm, within the person), the obstacle (within person and arm) and the repeats.
o = ~D.lev & isfinite(x);
tb = table(x(o), categorical(D.g(o)), categorical(double(D.leadL(o))), categorical(D.T.obstacle_code(o)), 'VariableNames', {'y', 'p', 'a', 'c'});
ws = warning('off', 'all');  c0 = onCleanup(@() warning(ws));
lme = fitlme(tb, 'y ~ 1 + (1 | p) + (1 | p:a) + (1 | p:a:c)');
[psi, mse, st] = covarianceParameters(lme);
v = [0 0 0 mse];  nm = {'p', 'p:a', 'p:a:c'};
for k = 1:numel(psi)
    j = find(strcmp(nm, strtrim(char(st{k}.Group(1, :)))), 1);
    v(j) = psi{k}(1);
end
sh = 100 * v / sum(v);
end

function q = holm(p)
% Holm-adjusted p-values; NaN stays NaN.
q = nan(size(p));  ok = isfinite(p);  m = nnz(ok);
[s, o] = sort(p(ok));
qs = min(1, cummax((m - (1:m)' + 1) .* s(:)));
v = zeros(m, 1);  v(o) = qs;  q(ok) = v;
end

function s = pb(p)
% p-value, bold when below 0.05.
s = p3(p);
if p < 0.05, s = ['**' s '**']; end
end

