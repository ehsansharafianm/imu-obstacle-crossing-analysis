function C = subsetRows(C, use, n)
% Keeps the rows `use` of every array with n rows, in nested structs too.
f = fieldnames(C);
for i = 1:numel(f)
    v = C.(f{i});
    if isstruct(v) && isscalar(v)
        C.(f{i}) = subsetRows(v, use, n);
    elseif (isnumeric(v) || iscell(v)) && size(v, 1) == n
        C.(f{i}) = v(use, :);
    end
end
end

function [M, lv, Hm, Wm] = cellMeans(x, D)
% Participant means: the six obstacles (columns W1_H1 ... W2_H3), the level walk, the three heights (mean of the
% two widths) and the two widths (mean of the three heights). x = a column of D.A by name (level value matched
% by side, levelRef) or a vector over the rows (plain level mean).
cells = {'W1', 'H1'; 'W1', 'H2'; 'W1', 'H3'; 'W2', 'H1'; 'W2', 'H2'; 'W2', 'H3'};
nP = numel(D.P);  M = nan(nP, 6);
if ischar(x), lv = levelRef(D, x);  x = D.A.(x); else, lv = arrayfun(@(p) mean(x(D.g == p & D.lev), 'omitnan'), D.P(:)); end
for k = 1:nP
    i = D.g == D.P(k);
    for c = 1:6, M(k, c) = mean(x(i & strcmp(D.wc, cells{c,1}) & strcmp(D.hc, cells{c,2})), 'omitnan'); end
end
Hm = [mean(M(:, [1 4]), 2, 'omitnan'), mean(M(:, [2 5]), 2, 'omitnan'), mean(M(:, [3 6]), 2, 'omitnan')];
Wm = [mean(M(:, 1:3), 2, 'omitnan'), mean(M(:, 4:6), 2, 'omitnan')];
end

function m = classMeans(x, D)
% Participant means of level, H1, H2, H3 (the heights averaged over the two widths); x as in cellMeans.
[~, lv, Hm] = cellMeans(x, D);
m = [lv, Hm];
end

function lv = levelRef(D, col, rows)
% Level-walk value of a measure for each participant, matched by side to the obstacle crossings (all of them, or
% the rows given, e.g. one obstacle).
%   stride measure (lead_* / trail_*): mean of the level strides of the left leg and of the right leg (each
%       level walk has one of each), weighted by the share of the participant's obstacle strides of that class
%       done with the left and with the right leg. The opposite / same-side arm of a leg is one physical arm.
%   crossing measure: mean of the level walks led by the left and by the right limb, weighted by the share of
%       obstacle crossings led by each (plain level mean if one of the two has no level walk).
x = D.A.(col);  nP = numel(D.P);  lv = nan(nP, 1);
if nargin < 3, rows = true(size(x)); end
tok = regexp(col, '^(lead|trail)_(.+)$', 'tokens', 'once');
for k = 1:nP
    i = D.g == D.P(k);  o = i & ~D.lev & isfinite(x) & rows;  lev = i & D.lev;
    if ~isempty(tok)
        xl = D.A.(['lead_' tok{2}]);  xt = D.A.(['trail_' tok{2}]);
        ref = [mean([xl(lev & D.leadL); xt(lev & ~D.leadL)], 'omitnan'), mean([xl(lev & ~D.leadL); xt(lev & D.leadL)], 'omitnan')];
        if strcmp(tok{1}, 'lead'), w = mean(D.leadL(o)); else, w = mean(~D.leadL(o)); end
    else
        ref = [mean(x(lev & D.leadL), 'omitnan'), mean(x(lev & ~D.leadL), 'omitnan')];
        w = mean(D.leadL(o));
    end
    if any(isnan(ref)) || isnan(w), lv(k) = mean(x(lev), 'omitnan'); else, lv(k) = [w, 1 - w] * ref'; end
end
end

%% ========================================================================
%  STATISTICS OF EVERY MEASURE (used by A4 and A5)
%% ========================================================================
function R = effects(D)
nI = numel(D.I);
for i = 1:nI
    r = effectStats(D.I(i).col, D);
    if i == 1, R = repmat(r, nI, 1); end
    R(i) = r;
end
key = {'pLev', 'qLev'; 'pH', 'qH'; 'pW', 'qW'; 'pHW', 'qHW'; 'pH31', 'qH31'; 'pSlope', 'qSlope'};
for k = 1:size(key, 1)
    q = fdr([R.(key{k,1})]');
    for i = 1:nI, R(i).(key{k,2}) = q(i); end
end
end

function S = effectStats(col, D)
[M, lv, Hm, Wm] = cellMeans(col, D);  x = D.A.(col);
S = struct('M', M, 'lv', lv, 'ob', mean(M, 2), 'Hm', Hm, 'Wm', Wm);
d = S.ob - lv;  ok = isfinite(d);
[~, S.pLev, ci] = ttest(d(ok));
S.n = nnz(ok);  S.dLev = mean(d(ok));  S.ciLev = ci(:)';  S.dzLev = mean(d(ok)) / std(d(ok));
S.wLev = signrank(d(ok));  S.nDir = nnz(sign(d(ok)) == sign(mean(d(ok))));
a = rmAnova(M);
S.nA = a.n;  S.F = a.F;  S.pA = a.p;  S.eta = a.eta;  S.df1 = a.df1;  S.df2 = a.df2;
S.pH = a.p(1);  S.pW = a.p(2);  S.pHW = a.p(3);
okH = all(isfinite(Hm), 2);  dH = Hm(okH, 3) - Hm(okH, 1);
[~, S.pH31] = ttest(dH);  S.dH31 = mean(dH);  S.dzH31 = mean(dH) / std(dH);
S.pFried = friedman(Hm(okH, :), 1, 'off');
o = ~D.lev & isfinite(x) & isfinite(D.h);
tb = table(x(o), D.h(o) - mean(D.h(o)), strcmp(D.wc(o), 'W2') - 0.5, categorical(D.g(o)), 'VariableNames', {'y', 'h', 'W', 'pid'});
ws = warning('off', 'all');  c = onCleanup(@() warning(ws));
try
    lme = fitlme(tb, 'y ~ 1 + h*W + (1 + h | pid)');
catch
    lme = fitlme(tb, 'y ~ 1 + h*W + (1 | pid)');
end
[~, ~, st] = fixedEffects(lme, 'DFMethod', 'satterthwaite');
i = find(strcmp(cellstr(st.Name), 'h'), 1);
S.slope = st.Estimate(i);  S.slopeCI = [st.Lower(i), st.Upper(i)];  S.pSlope = st.pValue(i);
[S.qLev, S.qH, S.qW, S.qHW, S.qH31, S.qSlope] = deal(NaN);
end

function a = rmAnova(M)
% 3 (height) x 2 (width) repeated-measures ANOVA on the complete rows of M (columns W1_H1 ... W2_H3).
within = table(categorical({'H1'; 'H2'; 'H3'; 'H1'; 'H2'; 'H3'}), categorical({'W1'; 'W1'; 'W1'; 'W2'; 'W2'; 'W2'}), ...
    'VariableNames', {'Height', 'Width'});
