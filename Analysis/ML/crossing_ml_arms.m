function D = loadArms(root)
Dd = mlTools.load(root);  T = Dd.T;
f = fullfile(root, 'Results', 'ML Dataset', 'Arm_Master_YoungAdults.csv');
o = detectImportOptions(f);
o = setvartype(o, {'crossing_id', 'obstacle_code', 'height_class', 'width_class', 'leading_limb'}, 'char');
A = readtable(f, o);
assert(isequal(A.crossing_id, T.crossing_id), 'Arm_Master rows do not match the crossing master: rerun build_arm_dataset');
C = load(fullfile(root, 'Results', 'ML Dataset', 'Arm_Curves_YoungAdults.mat'));
use = A.arm_ok == 1 & T.include_biomech == 1;
D.all = struct('T', T, 'A', A, 'use', use, 'feats', {Dd.feats}, 'units', {Dd.units});
D.T = T(use, :);  D.A = A(use, :);  D.C = subsetRows(C, use, height(T));
D.g = D.T.participant_id;  D.P = unique(D.g)';  D.lev = D.T.is_level == 1;
D.leadL = strcmp(D.T.leading_limb, 'L');
for l = {'lead', 'trail'}                         % forward swing of the opposite arm: backward peak -> forward peak in the stride
    cv = D.C.(l{1}).con_arm;  n = size(cv, 1);  fw = nan(n, 1);  sz = nan(n, 1);
    for r = 1:n
        [mx, imx] = max(cv(r, :));
        if ~isfinite(mx) || imx < 2, continue; end
        [mn, imn] = min(cv(r, 1:imx));
        fw(r) = (imx - imn) / 100 * D.A.([l{1} '_stride_dur'])(r);  sz(r) = mx - mn;
    end
    D.A.([l{1} '_con_fwd_dur']) = fw;  D.A.([l{1} '_con_fwd_size']) = sz;  D.A.([l{1} '_swing_time']) = D.T.([l{1} '_swing_time']);
end
% trunk lean peak against the camera toe lift-off of the trailing limb (the step 4 toe-off comes late over an obstacle)
D.A.cw_trunk_pitch_t_cam = D.A.cw_trunk_pitch_t_to + 1000 * (D.T.trail_toeoff_t - D.T.trail_toeoff_t_cam);
D.hc = D.T.height_class;  D.wc = D.T.width_class;  D.h = D.T.height_cm;
D.n = [height(T), nnz(use), nnz(use & T.is_level == 0), nnz(use & T.is_level == 1)];
D.qc = C.qc;  D.trend = C.trend;
D.lab = {'Leading', 'Trailing'};  D.pre = {'lead', 'trail'};
D.cls = {'level', 'H1', 'H2', 'H3'};
% measures of a stride: column suffix, label, unit, family
D.V = { ...
