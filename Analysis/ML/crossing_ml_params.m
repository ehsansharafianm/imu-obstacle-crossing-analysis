L = addl(L, '');
qh = R.q(:, :, 1) < 0.05;  strong = any(qh & R.eta(:, :, 1) >= 0.8, 2);
none = cls(cellfun(@(c) ~any(qh(strcmp(D.V(:, 1), c), :), 'all'), cls));
nc = cellfun(@(c) sum(O.count(strcmp(D.V(:, 1), c), :), 'all'), cls);  [~, o] = sort(nc, 'descend');  o = o(nc(o) > 0);
L = addl(L, ['**Reading.** Height changes %d of the 26 parameters of the leading limb and %d of the trailing limb after the FDR correction, ' ...
    'most strongly %s (partial eta^2 >= 0.8); no parameter of: %s. Width changes %d / %d and %d parameters show a height x width ' ...
    'interaction. %d / %d of the %d parameters with a level walk differ from level walking. %d cells in %d parameter x limb combinations ' ...
    'are outlying (P4), most in: %s.'], nnz(qh(:, 1)), nnz(qh(:, 2)), names(D, strong), ...
    ternary(isempty(none), 'none', strjoin(cellfun(@className, none, 'UniformOutput', false), ', ')), nnz(R.q(:, 1, 2) < 0.05), ...
    nnz(R.q(:, 2, 2) < 0.05), nnz(any(R.q(:, :, 3) < 0.05, 2)), nnz(Lv.q(:, 1) < 0.05), nnz(Lv.q(:, 2) < 0.05), nnz(~isnan(Lv.q(:, 1))), ...
    O.nCells, nnz(O.flag), ternary(isempty(o), 'none', strjoin(arrayfun(@(k) sprintf('%s (%d cells)', className(cls{k}), nc(k)), ...
    o(1:min(2, numel(o)))', 'UniformOutput', false), ', ')));
L = addl(L, '');
end

%% ========================================================================
%  P1: repeated-measures ANOVA of every parameter
%% ========================================================================
function [L, R] = partAnova(D, L)
nV = size(D.V, 1);  R.n = zeros(nV, 2);  [R.F, R.p, R.eta, R.df1, R.df2] = deal(nan(nV, 2, 3));
for v = 1:nV
    for l = 1:2
        a = rmAnova(D.M{v, l});
        R.n(v, l) = a.n;  R.F(v, l, :) = a.F;  R.p(v, l, :) = a.p;  R.eta(v, l, :) = a.eta;  R.df1(v, l, :) = a.df1;  R.df2(v, l, :) = a.df2;
    end
end
[R.q, R.h] = deal(nan(size(R.p)));
for e = 1:3
    R.q(:, :, e) = reshape(fdr(reshape(R.p(:, :, e), [], 1)), nV, 2);
    R.h(:, :, e) = reshape(holm(reshape(R.p(:, :, e), [], 1)), nV, 2);
end
L = addl(L, '## P1. Repeated-measures ANOVA: height x width, every parameter');
L = addl(L, '');
L = addl(L, ['The 3 (height) x 2 (width) repeated-measures ANOVA of the SPSS analysis (`fitrm` / `ranova`) for each parameter and limb, on ' ...
    'the participants with all six obstacles. p = Greenhouse-Geisser corrected (width has two levels and needs no correction); q = FDR ' ...
    'over the 52 tests of the same effect; partial eta^2 = SS_effect / (SS_effect + SS_error). Degrees of freedom: height and height x ' ...
    'width (2, 2(n - 1)), width (1, n - 1). Bold = q < 0.05.']);
L = addl(L, '');
L = addl(L, '| parameter | limb | n | height: F | p (q) | eta^2 | width: F | p (q) | eta^2 | height x width: F | p (q) | eta^2 |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|---|---|---|');
for v = 1:nV
    for l = 1:2
        c = arrayfun(@(e) sprintf('%.1f | %s | %.2f', R.F(v, l, e), pq(R.p(v, l, e), R.q(v, l, e)), R.eta(v, l, e)), 1:3, 'UniformOutput', false);
        L = addl(L, '| %s (%s) | %s | %d | %s |', D.V{v,3}, D.V{v,4}, D.lab{l}, R.n(v, l), strjoin(c, ' | '));
    end
end
L = addl(L, '');
qa = R.q < 0.05;  nm = {'height', 'width', 'height x width'};
cnt = arrayfun(@(e) sprintf('%s %d of 52 (p < 0.05: %d; Holm: %d)', nm{e}, nnz(qa(:, :, e)), nnz(R.p(:, :, e) < 0.05), ...
    nnz(R.h(:, :, e) < 0.05)), 1:3, 'UniformOutput', false);
L = addl(L, ['**Reading.** Significant after the FDR correction: %s. Height does not change: leading %s; trailing %s. Width changes: ' ...
    'leading %s; trailing %s. Height x width: leading %s; trailing %s.'], strjoin(cnt, '; '), names(D, ~qa(:, 1, 1)), names(D, ~qa(:, 2, 1)), ...
    names(D, qa(:, 1, 2)), names(D, qa(:, 2, 2)), names(D, qa(:, 1, 3)), names(D, qa(:, 2, 3)));
L = addl(L, '');
end

function a = rmAnova(M)
% 3 (height) x 2 (width) repeated-measures ANOVA on the complete rows of M (columns W1_H1 ... W2_H3).
within = table(categorical({'H1'; 'H2'; 'H3'; 'H1'; 'H2'; 'H3'}), categorical({'W1'; 'W1'; 'W1'; 'W2'; 'W2'; 'W2'}), ...
    'VariableNames', {'Height', 'Width'});
ok = all(isfinite(M), 2);
rm = fitrm(array2table(M(ok, :), 'VariableNames', {'W1H1', 'W1H2', 'W1H3', 'W2H1', 'W2H2', 'W2H3'}), 'W1H1-W2H3 ~ 1', 'WithinDesign', within);
ra = ranova(rm, 'WithinModel', 'Height*Width');
eff = {'(Intercept):Height', 'Error(Height)'; '(Intercept):Width', 'Error(Width)'; '(Intercept):Height:Width', 'Error(Height:Width)'};
a = struct('n', nnz(ok), 'F', zeros(1, 3), 'p', zeros(1, 3), 'eta', zeros(1, 3), 'df1', zeros(1, 3), 'df2', zeros(1, 3));
for e = 1:3
    a.F(e) = ra{eff{e,1}, 'F'};  a.p(e) = ra{eff{e,1}, 'pValueGG'};  a.df1(e) = ra{eff{e,1}, 'DF'};  a.df2(e) = ra{eff{e,2}, 'DF'};
    a.eta(e) = ra{eff{e,1}, 'SumSq'} / (ra{eff{e,1}, 'SumSq'} + ra{eff{e,2}, 'SumSq'});
end
end

%% ========================================================================
%  P2: height contrasts and change per cm of obstacle
%% ========================================================================
function L = partHeight(D, L, R)
nV = size(D.V, 1);  nP = numel(D.P);  pr = [1 2; 2 3; 1 3];  hi = [1 2 3 1 2 3]';
L = addl(L, '## P2. Height: pairwise contrasts and change per cm of obstacle');
L = addl(L, '');
L = addl(L, ['Paired t-tests between the height levels on the participant means averaged over width (participants with all six obstacles), ' ...
    'Holm-corrected over the three pairs: ***, **, * = p < 0.001, 0.01, 0.05; dz = mean / SD of the H3 - H1 differences. Change per cm: ' ...
    '`y ~ 1 + h * W + (1 + h | participant)` (`fitlme`) on every available participant mean, h = obstacle height in cm (10 / 20 / 30 % of ' ...
    'each participant''s leg length, centred), W = -0.5 / +0.5, so h is the slope averaged over the widths; Satterthwaite p.']);
L = addl(L, '');
L = addl(L, '| parameter | limb | H2 - H1 | H3 - H2 | H3 - H1 | dz (H3 - H1) | per cm of obstacle (95 % CI) | p |');
L = addl(L, '|---|---|---|---|---|---|---|---|');
[kk, cc] = ndgrid(1:nP, 1:6);  hcm = D.Hcm(sub2ind(size(D.Hcm), kk(:), hi(cc(:))));
nAll = 0;  part = {};  disc = {};
for v = 1:nV
    u = D.V{v,4};  dd = dec(u);
    for l = 1:2
        M = D.M{v, l};  ok = all(isfinite(M), 2);
        Hm = [mean(M(ok, [1 4]), 2), mean(M(ok, [2 5]), 2), mean(M(ok, [3 6]), 2)];
        pp = zeros(3, 1);  dm = pp;
        for k = 1:3
            df = Hm(:, pr(k,2)) - Hm(:, pr(k,1));  [~, pp(k)] = ttest(df);  dm(k) = mean(df);
        end
        ph = holm(pp);  d13 = Hm(:, 3) - Hm(:, 1);
        c = arrayfun(@(k) sprintf('%+.*f%s', dd, dm(k), stars(ph(k))), 1:3, 'UniformOutput', false);
        tb = table(M(:), hcm, (cc(:) > 3) - 0.5, categorical(D.P(kk(:))), 'VariableNames', {'y', 'h', 'W', 'pid'});
        tb = tb(isfinite(tb.y) & isfinite(tb.h), :);  tb.h = tb.h - mean(tb.h);
        try
            lme = fitlme(tb, 'y ~ 1 + h*W + (1 + h | pid)');
        catch
            lme = fitlme(tb, 'y ~ 1 + h*W + (1 | pid)');
        end
        [~, ~, st] = fixedEffects(lme, 'DFMethod', 'satterthwaite');  i = strcmp(cellstr(st.Name), 'h');
        L = addl(L, '| %s (%s) | %s | %s | %+.1f | %+.*f (%+.*f to %+.*f) | %s |', D.V{v,3}, u, D.lab{l}, strjoin(c, ' | '), ...
            mean(d13) / std(d13), dd + 1, st.Estimate(i), dd + 1, st.Lower(i), dd + 1, st.Upper(i), p3(st.pValue(i)));
        if R.q(v, l, 1) < 0.05
            if all(ph < 0.05), nAll = nAll + 1; else, part{end+1} = sprintf('%s %s', D.lab{l}, D.V{v,3}); end %#ok<AGROW>
        elseif ph(3) < 0.05
            disc{end+1} = sprintf('%s %s', D.lab{l}, D.V{v,3}); %#ok<AGROW>
        end
    end
end
L = addl(L, '');
L = addl(L, ['**Reading.** Of the %d parameter x limb combinations with a significant height effect (P1), %d differ between every pair of ' ...
    'heights (Holm); in the other %d the change sits in one height step: %s. The H3 - H1 contrast is significant although the ANOVA ' ...
    'is not (after FDR) for: %s; an outlying cell that inflates the ANOVA error can cause this (P4).'], nnz(R.q(:, :, 1) < 0.05), nAll, ...
    numel(part), ternary(isempty(part), 'none', strjoin(part, ', ')), ternary(isempty(disc), 'none', strjoin(disc, ', ')));
L = addl(L, '');
end

%% ========================================================================
%  P3: obstacle against level walking
%% ========================================================================
function [L, Lv] = partLevel(D, L)
nV = size(D.V, 1);  [Lv.n, Lv.lev, Lv.ob, Lv.d, Lv.dz, Lv.p, Lv.d1, Lv.dz1, Lv.p1] = deal(nan(nV, 2));
for v = 1:nV
    if isempty(D.lev{v}), continue; end
    for l = 1:2
        M = D.M{v, l};  lv = D.lev{v};  ok = all(isfinite(M), 2) & isfinite(lv);
        ob = mean(M(ok, :), 2);  h1 = mean(M(ok, [1 4]), 2);
        Lv.n(v, l) = nnz(ok);  Lv.lev(v, l) = mean(lv(ok));  Lv.ob(v, l) = mean(ob);
        d = ob - lv(ok);  [~, Lv.p(v, l)] = ttest(d);  Lv.d(v, l) = mean(d);  Lv.dz(v, l) = mean(d) / std(d);
        d = h1 - lv(ok);  [~, Lv.p1(v, l)] = ttest(d);  Lv.d1(v, l) = mean(d);  Lv.dz1(v, l) = mean(d) / std(d);
    end
end
Lv.q = reshape(fdr(Lv.p(:)), nV, 2);  Lv.q1 = reshape(fdr(Lv.p1(:)), nV, 2);
L = addl(L, '## P3. Obstacle against level walking');
L = addl(L, '');
L = addl(L, ['Paired t-tests of each participant''s mean over the six obstacles, and over the two lowest obstacles (H1), against their level ' ...
    'walk (participants with all values); dz = mean / SD of the differences; q = FDR over the 42 tests (21 parameters with a level walk x ' ...
    '2 limbs). The level walk is the same normal stride for both limb columns; the clearance parameters have no level-walk value.']);
L = addl(L, '');
L = addl(L, '| parameter | limb | n | level walk | obstacles | obstacles - level | dz | p (q) | H1 - level | dz | p (q) |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|---|---|');
for v = 1:nV
    if isempty(D.lev{v}), continue; end
    dd = dec(D.V{v,4});
    for l = 1:2
        L = addl(L, '| %s (%s) | %s | %d | %.*f | %.*f | %+.*f | %+.1f | %s | %+.*f | %+.1f | %s |', D.V{v,3}, D.V{v,4}, D.lab{l}, Lv.n(v, l), ...
            dd, Lv.lev(v, l), dd, Lv.ob(v, l), dd, Lv.d(v, l), Lv.dz(v, l), pq(Lv.p(v, l), Lv.q(v, l)), dd, Lv.d1(v, l), Lv.dz1(v, l), ...
            pq(Lv.p1(v, l), Lv.q1(v, l)));
    end
end
L = addl(L, '');
has = ~isnan(Lv.q(:, 1));  qs = Lv.q < 0.05;
L = addl(L, ['**Reading.** Crossing an obstacle differs from level walking (FDR) for %d of the %d parameters with a level walk in the leading ' ...
    'limb and %d in the trailing limb; not different: leading %s; trailing %s. The lowest obstacle alone already differs for %d (leading) ' ...
    'and %d (trailing).'], nnz(qs(:, 1)), nnz(has), nnz(qs(:, 2)), names(D, has & ~qs(:, 1)), names(D, has & ~qs(:, 2)), ...
    nnz(Lv.q1(:, 1) < 0.05), nnz(Lv.q1(:, 2) < 0.05));
L = addl(L, '');
end

%% ========================================================================
%  P4: non-parametric check of P1
%% ========================================================================
function [L, O] = partNonpar(D, L, R)
nV = size(D.V, 1);  [pF, pW] = deal(nan(nV, 2));
for v = 1:nV
    for l = 1:2
        M = D.M{v, l};  ok = all(isfinite(M), 2);
        pF(v, l) = friedman([mean(M(ok, [1 4]), 2), mean(M(ok, [2 5]), 2), mean(M(ok, [3 6]), 2)], 1, 'off');
        pW(v, l) = signrank(mean(M(ok, 4:6), 2), mean(M(ok, 1:3), 2));
    end
end
qF = reshape(fdr(pF(:)), nV, 2);  qW = reshape(fdr(pW(:)), nV, 2);
aH = (qF < 0.05) == (R.q(:, :, 1) < 0.05);  aW = (qW < 0.05) == (R.q(:, :, 2) < 0.05);
L = addl(L, '## P4. Robustness: non-parametric tests and outlying cells');
L = addl(L, '');
L = addl(L, '**Non-parametric tests.**');
L = addl(L, '');
L = addl(L, ['Friedman test across the three heights (participant means averaged over width) and Wilcoxon signed-rank test W2 vs W1 (averaged ' ...
    'over height), on the participants of P1; q = FDR over the 52 tests. They assume no normal distribution; with 10 participants they have ' ...
    'a little less power than the ANOVA. Bold = q < 0.05.']);
L = addl(L, '');
L = addl(L, '| parameter | limb | height: ANOVA q | Friedman p (q) | width: ANOVA q | Wilcoxon p (q) |');
L = addl(L, '|---|---|---|---|---|---|');
dl = {};
for v = 1:nV
    for l = 1:2
        L = addl(L, '| %s (%s) | %s | %s | %s | %s | %s |', D.V{v,3}, D.V{v,4}, D.lab{l}, qb(R.q(v, l, 1)), pq(pF(v, l), qF(v, l)), ...
            qb(R.q(v, l, 2)), pq(pW(v, l), qW(v, l)));
        if ~aH(v, l), dl{end+1} = sprintf('%s %s, height (ANOVA %s, Friedman %s)', D.lab{l}, D.V{v,3}, yn(R.q(v, l, 1)), yn(qF(v, l))); end %#ok<AGROW>
        if ~aW(v, l), dl{end+1} = sprintf('%s %s, width (ANOVA %s, Wilcoxon %s)', D.lab{l}, D.V{v,3}, yn(R.q(v, l, 2)), yn(qW(v, l))); end %#ok<AGROW>
    end
end
L = addl(L, '');
L = addl(L, ['The Friedman test gives the same verdict as the ANOVA (both after FDR) for %d of the 52 height effects and the Wilcoxon test ' ...
    'for %d of the 52 width effects. Different: %s.'], nnz(aH), nnz(aW), ternary(isempty(dl), 'none', strjoin(dl, '; ')));
L = addl(L, '');
% outlying cells: modified z-score (Iglewicz & Hoaglin) within each obstacle column of the participants
O = struct('flag', false(nV, 2), 'dep', false(nV, 2), 'count', zeros(nV, 2), 'nCells', 0);  rows = {};  sens = {};  top = zeros(0, 4);
for v = 1:nV
    dd = dec(D.V{v,4});
    for l = 1:2
        M = D.M{v, l};  med = median(M, 1, 'omitnan');  md = median(abs(M - med), 1, 'omitnan');
        z = (M - med) ./ (1.4826 * md);  z(:, md == 0) = 0;  z(isnan(z)) = 0;  Fl = abs(z) > 3.5;
        if ~any(Fl(:)), continue; end
        O.flag(v, l) = true;  O.count(v, l) = nnz(Fl);
        for k = find(any(Fl, 2))'
            c = find(Fl(k, :));  [zm, j] = max(abs(z(k, c)));  top(end+1, :) = [zm, v, l, k * 10 + c(j)]; %#ok<AGROW>
            rows{end+1} = sprintf('| %d | %s (%s) | %s | %s | %s | %s | %.1f |', D.P(k), D.V{v,3}, D.V{v,4}, D.lab{l}, strjoin(D.cells(c), ', '), ...
                strjoin(arrayfun(@(x) sprintf('%.*f', dd, x), M(k, c), 'UniformOutput', false), ', '), ...
                strjoin(arrayfun(@(x) sprintf('%.*f', dd, x), med(c), 'UniformOutput', false), ', '), zm); %#ok<AGROW>
        end
        keep = ~any(Fl, 2) & all(isfinite(M), 2);  a = rmAnova(M(keep, :));
        O.dep(v, l) = any((a.p(1:2) < 0.05) ~= (squeeze(R.p(v, l, 1:2))' < 0.05));
        sens{end+1} = sprintf('| %s (%s) | %s | %s | %d | %s | %s | %d | %s | %s |', D.V{v,3}, D.V{v,4}, D.lab{l}, ...
            strjoin(arrayfun(@num2str, D.P(any(Fl, 2))', 'UniformOutput', false), ', '), R.n(v, l), p3(R.p(v, l, 1)), p3(R.p(v, l, 2)), ...
            a.n, sb(a.p(1), R.p(v, l, 1)), sb(a.p(2), R.p(v, l, 2))); %#ok<AGROW>
    end
end
O.nCells = sum(O.count(:));
L = addl(L, ['**Outlying cells.** A cell (one participant mean for one obstacle) is outlying when its modified z-score (x - median) / ' ...
    '(1.4826 MAD) across the participants of its column exceeds 3.5 in absolute value (Iglewicz & Hoaglin). %d of the %d cells are ' ...
    'outlying, in %d parameter x limb combinations. They are listed for checking in step 9 (an implausible value is a processing ' ...
    'artefact; a plausible one is an unusual participant). No value is changed here.'], O.nCells, 6 * numel(D.P) * 2 * nV, nnz(O.flag));
L = addl(L, '');
L = addl(L, '| participant | parameter | limb | obstacles | values | column medians | largest robust z |');
L = addl(L, '|---|---|---|---|---|---|---|');
L = [L, rows];
L = addl(L, '');
L = addl(L, ['**ANOVA without the participants with outlying cells** (sensitivity check of P1, Greenhouse-Geisser p before and after; bold = ' ...
    'the verdict at p < 0.05 changes).']);
L = addl(L, '');
L = addl(L, '| parameter | limb | participants left out | n | height p | width p | n without | height p without | width p without |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|');
L = [L, sens];
L = addl(L, '');
[~, o] = sort(top(:, 1), 'descend');  o = o(1:min(4, numel(o)));
ex = arrayfun(@(i) sprintf('%d, %s %s, %s: %.*f %s (column median %.*f)', D.P(floor(top(i,4) / 10)), D.lab{top(i,3)}, D.V{top(i,2),3}, ...
    D.cells{mod(top(i,4), 10)}, dec(D.V{top(i,2),4}), D.M{top(i,2), top(i,3)}(floor(top(i,4) / 10), mod(top(i,4), 10)), D.V{top(i,2),4}, ...
    dec(D.V{top(i,2),4}), median(D.M{top(i,2), top(i,3)}(:, mod(top(i,4), 10)), 'omitnan')), o', 'UniformOutput', false);
dep = arrayfun(@(k) sprintf('%s %s', D.lab{ceil(k / nV)}, D.V{mod(k - 1, nV) + 1, 3}), find(O.dep)', 'UniformOutput', false);
L = addl(L, ['**Reading.** The most extreme outlying cells are: %s. Values like these should be checked in step 9 before the parameters ' ...
    'concerned are interpreted. Without the participants with outlying cells the verdict at p < 0.05 of the height or width effect ' ...
    'changes for: %s.'], strjoin(ex, '; '), ternary(isempty(dep), 'none', strjoin(dep, ', ')));
L = addl(L, '');
end

%% ========================================================================
%  P5: how large a clearance change the data exclude
%% ========================================================================
function [L, E] = partClear(D, L)
iv = find(strcmp(D.V(:, 1), 'clearance'))';  rise = mean(D.Hcm(:, 3) - D.Hcm(:, 1), 'omitnan');
E = struct('names', {D.V(iv, 3)'}, 'rise', rise);  [E.dH, E.loH, E.hiH, E.dW, E.loW, E.hiW, E.n] = deal(nan(numel(iv), 2));
for a = 1:numel(iv)
    for l = 1:2
        M = D.M{iv(a), l};  ok = all(isfinite(M), 2);  n = nnz(ok);  t = tinv(0.95, n - 1);  E.n(a, l) = n;
        dH = mean(M(ok, [3 6]), 2) - mean(M(ok, [1 4]), 2);  dW = mean(M(ok, 4:6), 2) - mean(M(ok, 1:3), 2);
        E.dH(a, l) = mean(dH);  E.loH(a, l) = mean(dH) - t * std(dH) / sqrt(n);  E.hiH(a, l) = mean(dH) + t * std(dH) / sqrt(n);
        E.dW(a, l) = mean(dW);  E.loW(a, l) = mean(dW) - t * std(dW) / sqrt(n);  E.hiW(a, l) = mean(dW) + t * std(dW) / sqrt(n);
    end
end
bH = max(abs(E.loH), abs(E.hiH));  bW = max(abs(E.loW), abs(E.hiW));
L = addl(L, '## P5. Clearance: how large a change the data exclude');
L = addl(L, '');
L = addl(L, ['Mean change of the participant means from H1 to H3 (averaged over width) and from W1 to W2 (averaged over height), with the ' ...
    '90 %% CI. Bound = the larger absolute CI limit: a two one-sided test (TOST, alpha = 0.05) rejects any change larger than the bound, ' ...
    'so the data exclude changes beyond it. Between H1 and H3 the obstacle rises by %.1f cm on average (20 %% of leg length).'], rise);
L = addl(L, '');
L = addl(L, '| parameter | limb | n | H3 - H1 (90 % CI), cm | bound | W2 - W1 (90 % CI), cm | bound |');
L = addl(L, '|---|---|---|---|---|---|---|');
for a = 1:numel(iv)
    for l = 1:2
        L = addl(L, '| %s | %s | %d | %+.1f (%+.1f to %+.1f) | %.1f | %+.1f (%+.1f to %+.1f) | %.1f |', E.names{a}, D.lab{l}, E.n(a, l), ...
            E.dH(a, l), E.loH(a, l), E.hiH(a, l), bH(a, l), E.dW(a, l), E.loW(a, l), E.hiW(a, l), bW(a, l));
    end
end
L = addl(L, '');
im = find(strcmp(E.names, 'minimum clearance'));  it = find(strcmp(E.names, 'toe clearance'));  ih = find(strcmp(E.names, 'heel clearance'));
vd = @(b) ternary(b < 0.25 * rise, 'is shown to stay nearly constant', 'is not shown to be constant');
L = addl(L, ['**Reading.** From H1 to H3 the obstacle rises by %.1f cm, while the minimum clearance changes by %+.1f cm (leading, 90 %% CI ' ...
    '%+.1f to %+.1f) and %+.1f cm (trailing, %+.1f to %+.1f). The minimum clearance of the leading limb %s (changes beyond %.1f cm, %.0f %% of ' ...
    'the obstacle rise, are excluded); that of the trailing limb %s (beyond %.1f cm, %.0f %%). Bounds of the toe and heel clearance: %.1f / ' ...
    '%.1f and %.1f / %.1f cm (leading / trailing).'], rise, E.dH(im, 1), E.loH(im, 1), E.hiH(im, 1), E.dH(im, 2), E.loH(im, 2), E.hiH(im, 2), ...
    vd(bH(im, 1)), bH(im, 1), 100 * bH(im, 1) / rise, vd(bH(im, 2)), bH(im, 2), 100 * bH(im, 2) / rise, bH(it, 1), bH(it, 2), bH(ih, 1), bH(ih, 2));
L = addl(L, '');
end

%% ========================================================================
%  P6: sensitivity and sample size
%% ========================================================================
function L = partPower(D, L)
nV = size(D.V, 1);  ef = {'height (H3 - H1)', 'width (W2 - W1)'};
dz10 = sampsizepwr('t', [0 1], [], 0.8, 10);  dz9 = sampsizepwr('t', [0 1], [], 0.8, 9);  n05 = sampsizepwr('t', [0 1], 0.5, 0.8);
L = addl(L, '## P6. Sensitivity and sample size');
L = addl(L, '');
L = addl(L, ['Two-sided paired t-test, alpha = 0.05, 80 %% power (`sampsizepwr`): with n participants the smallest detectable standardized ' ...
    'effect is dz = %.2f for n = 10 and %.2f for n = 9 (dz = mean / SD of the paired differences). For every height (H3 - H1) and width ' ...
    '(W2 - W1) contrast that is not significant (paired t-test, p >= 0.05): its observed dz and the n that would detect an effect of that ' ...
    'size. Effect sizes observed in 10 people are uncertain, so these n are rough planning values; a correction over many tests needs ' ...
    'more.'], dz10, dz9);
L = addl(L, '');
L = addl(L, '| parameter | limb | effect | observed dz | n for 80 % power |');
L = addl(L, '|---|---|---|---|---|');
dzs = [];  lab = {};
for v = 1:nV
    for l = 1:2
        M = D.M{v, l};  ok = all(isfinite(M), 2);
        dd = {mean(M(ok, [3 6]), 2) - mean(M(ok, [1 4]), 2), mean(M(ok, 4:6), 2) - mean(M(ok, 1:3), 2)};
        for e = 1:2
            [~, p] = ttest(dd{e});
            if p < 0.05, continue; end
            dz = mean(dd{e}) / std(dd{e});
            if abs(dz) < 1e-6, ns = '-'; else, ns = sprintf('%d', sampsizepwr('t', [0 1], abs(dz), 0.8)); end
            L = addl(L, '| %s (%s) | %s | %s | %+.2f | %s |', D.V{v,3}, D.V{v,4}, D.lab{l}, ef{e}, dz, ns);
            dzs(end+1) = dz;  lab{end+1} = sprintf('%s %s, %s (dz %+.2f, n = %s)', D.lab{l}, D.V{v,3}, strtok(ef{e}), dz, ns); %#ok<AGROW>
        end
    end
end
L = addl(L, '');
[~, o] = sort(abs(dzs), 'descend');  top = lab(o(1:min(3, numel(o))));
L = addl(L, ['**Reading.** With 10 participants a paired comparison detects (80 %% power) only effects of dz >= %.2f. Of the %d height and ' ...
    'width contrasts that are not significant, %d have |dz| < 0.5 and would need more than %d participants; the largest of them: %s.'], ...
    dz10, numel(dzs), nnz(abs(dzs) < 0.5), n05, ternary(isempty(top), 'none', strjoin(top, '; ')));
L = addl(L, '');
end

