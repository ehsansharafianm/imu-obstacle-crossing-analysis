function q = fdr(p)
% Benjamini-Hochberg adjusted p-values (q); NaN stays NaN.
q = nan(size(p));  ok = isfinite(p);  m = nnz(ok);
[s, o] = sort(p(ok));
qs = min(1, cummin(s(:) .* m ./ (1:m)', 'reverse'));
v = zeros(m, 1);  v(o) = qs;  q(ok) = v;
end

function q = holm(p)
% Holm-adjusted p-values; NaN stays NaN.
q = nan(size(p));  ok = isfinite(p);  m = nnz(ok);
[s, o] = sort(p(ok));
qs = min(1, cummax((m - (1:m)' + 1) .* s(:)));
v = zeros(m, 1);  v(o) = qs;  q(ok) = v;
end

function s = names(D, m)
if ~any(m), s = 'none'; else, s = strjoin(D.V(m, 3)', ', '); end
end

function s = className(c)
switch c
    case 'clearance', s = 'clearance (camera)';
    case 'joint', s = 'joint angles (IK)';
    case 'segment', s = 'segment tilts (Dot)';
    case 'timing', s = 'peak timing (vs clearance)';
    otherwise, s = c;
end
end

function n = dec(unit)
% Decimals for a unit.
if strcmp(unit, 'm/s'), n = 2; else, n = 1; end
end

function s = stars(p)
if p < 0.001, s = '***'; elseif p < 0.01, s = '**'; elseif p < 0.05, s = '*'; else, s = ''; end
end

function s = p3(p)
if isnan(p), s = '-'; elseif p < 0.001, s = '<0.001'; else, s = sprintf('%.3f', p); end
end

function s = pq(p, q)
% "p (q)", bold when q < 0.05.
s = sprintf('%s (%s)', p3(p), p3(q));
if q < 0.05, s = ['**' s '**']; end
end

function s = qb(q)
s = p3(q);
if q < 0.05, s = ['**' s '**']; end
end

function s = sb(p, p0)
% p, bold when its verdict at p < 0.05 differs from that of p0.
s = p3(p);
if (p < 0.05) ~= (p0 < 0.05), s = ['**' s '**']; end
end

function s = yn(q)
s = ternary(q < 0.05, 'significant', 'not');
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
