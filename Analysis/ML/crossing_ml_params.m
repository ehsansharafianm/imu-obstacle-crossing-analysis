function crossing_ml_params()
% CROSSING_ML_PARAMS  Statistical significance of the 26 step 9 crossing parameters (the SPSS sheet).
%
%   crossing_ml_params      % full run (seconds)
%
% Input: Results/Group Analysis/GroupCrossing_YoungAdults_SPSS.xlsx (step09_group_crossing_analysis.m, writeSpssWide):
% one row per participant with the participant mean of every parameter per obstacle and limb, and the level walk.
% The leading and the trailing limb are analysed separately (never compared with each other).
%   P1  REPEATED-MEASURES ANOVA height (3) x width (2) of every parameter and limb (the SPSS GLM), with the
%       Benjamini-Hochberg false discovery rate (FDR) over the 52 parameter x limb tests of each effect
%   P2  HEIGHT: Holm-corrected pairwise contrasts and the change per cm of obstacle (mixed model on the means)
%   P3  OBSTACLE vs LEVEL WALKING: the mean of the six obstacles, and the lowest height, against the level walk
%   P4  ROBUSTNESS of P1: Friedman (height) and Wilcoxon signed-rank (width) tests; outlying cells (modified z-score
%       > 3.5 within an obstacle column) and the ANOVA without the participants that have them
%   P5  CLEARANCE EQUIVALENCE: 90 % CI of H3 - H1 and W2 - W1, the largest change the data do not exclude
%   P6  SENSITIVITY: the smallest effect detectable with 80 % power, and the n needed for the contrasts not detected
% Outputs -> Results/ML Models/MATLAB/ml_params_matlab.md, fig_params.png, fig_params_clear.png

here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
src = fullfile(root, 'Results', 'Group Analysis', 'GroupCrossing_YoungAdults_SPSS.xlsx');
D = loadParams(src, root);
t0 = tic;
[L1, R] = partAnova(D, {});      fprintf('P1 done (%.0f s)\n', toc(t0));
L2 = partHeight(D, {}, R);       fprintf('P2 done (%.0f s)\n', toc(t0));
[L3, Lv] = partLevel(D, {});     fprintf('P3 done (%.0f s)\n', toc(t0));
[L4, O] = partNonpar(D, {}, R);  fprintf('P4 done (%.0f s)\n', toc(t0));
[L5, E] = partClear(D, {});      fprintf('P5 done (%.0f s)\n', toc(t0));
L6 = partPower(D, {});           fprintf('P6 done (%.0f s)\n', toc(t0));
L = {};
L = addl(L, '# Statistical significance of the step 9 crossing parameters (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_params.m` on %s._', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
L = addl(L, '');
L = addl(L, ['Source: `Results/Group Analysis/GroupCrossing_YoungAdults_SPSS.xlsx`, the step 9 sheet for SPSS: one row per participant ' ...
    '(n = %d), the participant mean of each parameter per obstacle (W1 / W2 = 5 / 15 cm wide, H1-H3 = 10 / 20 / 30 %% of leg length) and ' ...
    'limb, and the level walk. 26 parameters in five classes: clearance (camera, cm), joint angles (IK, deg), segment tilts (Dot, deg), peak ' ...
    'timing relative to the obstacle clearance (%% gait cycle) and spatiotemporal. The leading and the trailing limb are analysed ' ...
    'separately. p < 0.05 is called significant; q = Benjamini-Hochberg false discovery rate (FDR) over the 52 parameter x limb tests of ' ...
    'an effect (42 for the level-walk comparisons). %s'], numel(D.P), missingNote(D));
L = addl(L, '');
L = [L, overview(D, R, Lv, O), L1, L2, L3, L4, L5, L6];
mlTools.figures(out, 'params', figData(D, R, Lv, E, O));
writeLines(fullfile(out, 'ml_params_matlab.md'), L);
fprintf('Wrote %s (%.0f s)\n', fullfile(out, 'ml_params_matlab.md'), toc(t0));
end

%% ========================================================================
%  DATA: the step 9 SPSS sheet and the obstacle heights in cm
%% ========================================================================
function D = loadParams(src, root)
X = readtable(src, 'VariableNamingRule', 'preserve');
D.V = {'clearance', 'toe', 'toe clearance', 'cm';
       'clearance', 'heel', 'heel clearance', 'cm';
       'clearance', 'min', 'minimum clearance', 'cm';
       'clearance', 'takeoff', 'take-off distance', 'cm';
       'clearance', 'landing', 'landing distance', 'cm';
       'joint', 'hip_flexion', 'hip peak flexion', 'deg';
       'joint', 'hip_rom', 'hip ROM', 'deg';
       'joint', 'knee_flexion', 'knee peak flexion', 'deg';
       'joint', 'knee_rom', 'knee ROM', 'deg';
       'joint', 'ankle_rom', 'ankle ROM', 'deg';
       'segment', 'thigh_flexion', 'thigh forward tilt', 'deg';
       'segment', 'thigh_rom', 'thigh tilt ROM', 'deg';
       'segment', 'shank_backward', 'shank backward tilt', 'deg';
       'segment', 'shank_forward', 'shank forward tilt', 'deg';
       'segment', 'shank_rom', 'shank tilt ROM', 'deg';
       'segment', 'foot_rom', 'foot tilt ROM', 'deg';
       'timing', 'hip', 'hip peak timing', '%GC';
       'timing', 'knee', 'knee peak timing', '%GC';
       'timing', 'ankle', 'ankle peak timing', '%GC';
       'timing', 'footheight', 'foot apex timing', '%GC';
       'timing', 'foot', 'foot tilt peak timing', '%GC';
       'timing', 'shank', 'shank tilt peak timing', '%GC';
       'timing', 'thigh', 'thigh tilt peak timing', '%GC';
       'spatiotemporal', 'stride', 'stride length', 'cm';
       'spatiotemporal', 'cadence', 'cadence', 'steps/min';
       'spatiotemporal', 'speed', 'gait speed', 'm/s'};
D.limbs = {'Leading', 'Trailing'};  D.lab = {'lead', 'trail'};
D.cells = {'W1_H1', 'W1_H2', 'W1_H3', 'W2_H1', 'W2_H2', 'W2_H3'};
D.P = X.Test;  nP = numel(D.P);  nV = size(D.V, 1);
D.M = cell(nV, 2);  D.lev = cell(nV, 1);
for v = 1:nV
    for l = 1:2
        M = nan(nP, 6);
        for c = 1:6, M(:, c) = X.(sprintf('%s_%s_%s_%s', D.V{v,1}, D.V{v,2}, D.cells{c}, D.limbs{l})); end
        D.M{v, l} = M;
    end
    k = sprintf('%s_%s_Level_Walk', D.V{v,1}, D.V{v,2});
    if ismember(k, X.Properties.VariableNames), D.lev{v} = X.(k); end
end
% obstacle heights in cm (10 / 20 / 30 % of each participant's leg length), from the ML dataset
Dd = mlTools.load(root);  T = Dd.T;  D.Hcm = nan(nP, 3);
for k = 1:nP
    for j = 1:3
        r = T.participant_id == D.P(k) & strcmp(T.height_class, sprintf('H%d', j));
        D.Hcm(k, j) = median(T.height_pct_LL(r) / 100 .* T.leg_length_cm(r), 'omitnan');
    end
end
end

function s = missingNote(D)
% Which participants miss which obstacles, for which parameters.
msg = {};
for k = 1:numel(D.P)
    nm = {};  cl = {};
    for v = 1:size(D.V, 1)
        bad = isnan(D.M{v, 1}(k, :)) | isnan(D.M{v, 2}(k, :));
        if any(bad), nm{end+1} = D.V{v,3}; cl = union(cl, D.cells(bad)); end %#ok<AGROW>
    end
    if ~isempty(nm), msg{end+1} = sprintf('participant %d has no %s for %s', D.P(k), strjoin(nm, ', '), strjoin(cl, ' and ')); end %#ok<AGROW>
end
if isempty(msg), s = 'No missing values.'; return; end
s = ['Missing: ' strjoin(msg, '; ') ', so these parameters have n = 9 in the repeated-measures tests (the mixed models of P2 use every ' ...
    'available value).'];
end

