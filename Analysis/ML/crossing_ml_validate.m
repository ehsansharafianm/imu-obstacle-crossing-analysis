function [brier, ece, tab] = calib(Pm, y, cl)
n = numel(y);  K = numel(cl);  Y = zeros(n, K);
for k = 1:K, Y(:, k) = strcmp(y, cl{k}); end
[pmax, j] = max(Pm, [], 2);  ok = strcmp(cl(j), y);
brier = mean(sum((Pm - Y).^2, 2));
b = discretize(pmax, 0:0.1:1);  ece = 0;
for i = unique(b)', m = b == i;  ece = ece + nnz(m) / n * abs(mean(ok(m)) - mean(pmax(m))); end
ed = [1/3 0.5 0.6 0.7 0.8 0.9 1.0001];  tab = nan(numel(ed) - 1, 5);
for i = 1:numel(ed) - 1
    m = pmax >= ed(i) & pmax < ed(i+1);
    tab(i, :) = [ed(i), min(ed(i+1), 1), nnz(m), mean(pmax(m)), mean(ok(m))];
end
end

function s = pctStr(v)
if isnan(v), s = '-'; else, s = sprintf('%.0f%%', 100 * v); end
end

%% ========================================================================
%  V6: anticipation before the crossing step
%% ========================================================================
function L = partApproach(D, L, nNull)
d = D.d;  g = D.g;  y = D.y;  h = D.hNom;
V = {'stride_len_app2', 'stride two before the crossing stride (leading foot, mm)';
     'stride_len_app1', 'stride just before the crossing stride (leading foot, mm)';
     'speed_approach', 'approach speed (m/s)';
     'lead_stance_time', 'leading-foot stance before its crossing swing (s)';
     'trail_cam_takeoff_toeoff', 'trailing toe before the obstacle at its toe-off (camera, mm)'};
L = addl(L, '## V6. Anticipation - do the steps before the obstacle change with its height?');
L = addl(L, '');
L = addl(L, ['Linear mixed model `y ~ height_cm + (1 + height_cm | participant)` per variable (slope per cm of obstacle, 95%% CI, Satterthwaite), and ' ...
    'the share of the within-person variance explained by the height level (eta^2, person means removed).']);
L = addl(L, '');
L = addl(L, '| variable | slope per cm | 95% CI | p | eta^2 within person |');
L = addl(L, '|---|---|---|---|---|');
for v = 1:size(V, 1)
    x = d.(V{v,1});  [b, lo, hi, p] = slopeLme(x, h, g);
    L = addl(L, '| %s | %+.3g | %+.3g to %+.3g | %s | %.2f |', V{v,2}, b, lo, hi, pstr(p), eta2w(x, g, y));
end
L = addl(L, '');
app = {'stride_len_app1', 'stride_len_app2', 'speed_approach', 'lead_stance_time'};
Xa = mlTools.selfnorm(d{:, app}, g);  cl = unique(y);
bF = mlTools.balAcc(y, mlTools.argmaxLab(mlTools.lopo(D.rf, Xa, y, g), cl));
bL = mlTools.balAcc(y, mlTools.argmaxLab(mlTools.lopo(D.lr, Xa, y, g), cl));
pv = mlTools.permTest(D.lr, {Xa}, y, g, bL, nNull, 77);
L = addl(L, ['Height from the four IMU approach variables only (data available before the leading foot leaves the floor; person scaling): ' ...
    'forest %.1f%%, logistic %.1f%% (permutation p = %.3f, %d label shuffles within person; chance 33%%).'], 100 * bF, 100 * bL, pv, nNull);
L = addl(L, '');
end

function [b, lo, hi, p] = slopeLme(x, h, g)
ok = isfinite(x) & isfinite(h);
tb = table(x(ok), h(ok), categorical(g(ok)), 'VariableNames', {'y', 'h', 'pid'});
lm = fitlme(tb, 'y ~ h + (1 + h | pid)');
[bb, ~, st] = fixedEffects(lm, 'DFMethod', 'satterthwaite');
b = bb(2);  lo = st.Lower(2);  hi = st.Upper(2);  p = st.pValue(2);
end

function e = eta2w(x, g, lab)
ok = isfinite(x);  x = x(ok);  g = g(ok);  lab = lab(ok);
for p = unique(g)', i = g == p;  x(i) = x(i) - mean(x(i)); end
sb = 0;
for c = unique(lab)', i = strcmp(lab, c{1});  sb = sb + nnz(i) * mean(x(i))^2; end
e = sb / sum(x.^2);
end

function s = pstr(p)
if isnan(p), s = '-'; elseif p < 0.001, s = '< 0.001'; else, s = sprintf('%.3f', p); end
end

%% ========================================================================
%  V7: IMU vs camera
%% ========================================================================
function L = partValidity(D, L)
d = D.d;  g = D.g;  h = D.hNom;
L = addl(L, '## V7. Validity - does the camera see the same 1:1 scaling as the IMU?');
L = addl(L, '');
L = addl(L, ['Camera toe rise = camera toe-marker peak in the stride minus the toe height at the stance before it (same reference as the IMU rise above ' ...
    'its stance). Slopes from the mixed model of V6. Agreement: IMU minus camera, per crossing.']);
L = addl(L, '');
L = addl(L, '| foot lift measure | leading limb, slope per cm (95% CI) | trailing limb, slope per cm (95% CI) |');
L = addl(L, '|---|---|---|');
M = {'camera toe rise', @(l) d.([l '_zhc_peak_foot_h']) - d.([l '_dotcam_peak_h_err']); ...
     'IMU foot-sensor rise', @(l) d.([l '_zhc_peak_foot_h']); ...
     'IMU toe rise (rigid-body, provisional)', @(l) d.([l '_zhc_peak_toe_h'])};
for k = 1:size(M, 1)
    c = cell(1, 2);  lim = {'lead', 'trail'};
    for j = 1:2
        [b, lo, hi] = slopeLme(M{k,2}(lim{j}), h, g);  c{j} = sprintf('%+.1f mm (%+.1f to %+.1f)', b, lo, hi);
    end
    L = addl(L, '| %s | %s |', M{k,1}, strjoin(c, ' | '));
end
L = addl(L, '');
L = addl(L, '| IMU vs camera toe rise | limb | crossings | bias (mm) | SD (mm) | 95% limits (mm) | median abs. difference (mm) | r | within-person r (median) |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|');
for k = 2:3
    for l = {'lead', 'trail'}
        cam = M{1,2}(l{1});  imu = M{k,2}(l{1});  e = imu - cam;  ok = isfinite(e);
        rw = arrayfun(@(p) corr(imu(ok & g == p), cam(ok & g == p)), unique(g(ok)));
        L = addl(L, '| %s | %s | %d | %+.0f | %.0f | %+.0f to %+.0f | %.0f | %.2f | %.2f |', M{k,1}, l{1}, nnz(ok), mean(e(ok)), std(e(ok)), ...
            mean(e(ok)) - 1.96 * std(e(ok)), mean(e(ok)) + 1.96 * std(e(ok)), median(abs(e(ok))), corr(imu(ok), cam(ok)), median(rw, 'omitnan'));
    end
end
L = addl(L, '');
end

