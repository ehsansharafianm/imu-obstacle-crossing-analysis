function crossing_ml_validate(quick)
% CROSSING_ML_VALIDATE  Generalisation, mechanism and validation checks for the obstacle-height story.
%
%   crossing_ml_validate          % full run
%   crossing_ml_validate(true)    % quick test
%
% Same data and rules as crossing_ml_matlab.m (leave-one-participant-out; every fitted step on the
% training participants). The device = two foot IMUs, person scaling, one random forest per limb,
% soft vote (crossing_ml_device.m D1). Questions:
%   V1  UNSEEN HEIGHTS: estimate the obstacle height (cm) for a height level that is missing from
%       training (leave one height out inside leave-one-participant-out): does the model learn the
%       scaling, or only three classes?
%   V2  UNSEEN WIDTH: height recognition trained on one obstacle width, tested on the other
%   V3  CLEARANCE: what sets the toe clearance (camera: how high the toe goes vs where the foot
%       leaves the floor), and how much of it the IMU can see
%   V4  WHAT THE MODEL USES: permutation importance of feature groups and single features
%   V5  STATISTICS: paired accuracy differences, confusion matrix, probability calibration
%   V6  ANTICIPATION: do the strides before the crossing already change with obstacle height?
%   V7  VALIDITY: the foot-lift scaling seen by the IMU vs by the camera
% Outputs -> Results/ML Models/MATLAB/ml_validate_matlab.md, fig_validate.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
nBoot = ternary(quick, 200, 2000);  nPerm = ternary(quick, 2, 10);  nNull = ternary(quick, 20, 200);

Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;  mm = strcmp(Dd.units, 'mm');
obs = T.is_level == 0 & T.include_ml == 1;
D.d = T(obs, :);  D.g = D.d.participant_id;  D.y = D.d.height_class;  D.out = out;
D.hNom = D.d.height_pct_LL / 100 .* D.d.leg_length_cm;          % nominal obstacle height, cm
C = mlTools.loadCurvesBoth(root, T.crossing_id);
[SH.lead, pn] = mlTools.shapeFeats(C.lead);  SH.trail = mlTools.shapeFeats(C.trail);  mmS = startsWith(pn, {'x_', 'h_'});
leadG = {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'};
for r = {'lead', 'trail'}
    l = r{1};
    cols = F(startsWith(F, [l '_foot_']) | startsWith(F, [l '_zhc_']) | ismember(F, {[l '_swing_time'], [l '_stance_time']}) | ...
        (strcmp(l, 'lead') & ismember(F, leadG)));
    raw = [T{:, cols}, SH.(l)];  mk = [mm(ismember(F, cols)), mmS];
    Xc = mlTools.calibrate(T, raw, mk);  Xo = mlTools.calibrate(T, raw, false(1, numel(mk)));
    D.FX.(l).names = [cols, strcat({'shape_'}, pn)];
    D.FX.(l).self = mlTools.selfnorm(raw(obs, :), D.g);             % person scaling (no labels)
    D.FX.(l).level = Xc(obs, :);                                    % generic: level walk, mm / leg length
    D.FX.(l).levelcm = Xo(obs, :);                                  % level-walk offset only (cm target)
    D.FX.(l).six = mlTools.selfnorm([T{obs, F(startsWith(F, [l '_thigh_']))}, T{obs, F(startsWith(F, [l '_shank_']))}, raw(obs, :)], D.g);
end
leadOnly = mlTools.getSet(mlTools.featureSets(F), 'lead only');
Xs = mlTools.calibrate(T, T{:, leadOnly}, mm(ismember(F, leadOnly)));  D.Xsum = Xs(obs, :);
Sc = mlTools.calibrate(T, SH.lead, mmS);  D.Xshape = Sc(obs, :);
D.rf = mlTools.spec('forest', 'nTrees', 300);  D.lr = mlTools.spec('logreg');

L = {};
L = addl(L, '# Generalisation, mechanisms and validation (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_validate.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings (include_ml), 10 participants. Every result is for a participant left out of training. Device = two foot IMUs ' ...
    '(foot tilt and angular velocity, foot acceleration, foot trajectory summaries, 13 clearance-shape features, swing / stance time; + approach ' ...
    'strides for the leading foot), person scaling, one random forest per limb, soft vote. 95%% CI = participant bootstrap.'], nnz(obs));
L = addl(L, '');
t0 = tic;
[L, R1] = partHeights(D, L);             fprintf('V1 done (%.0f s)\n', toc(t0));
L = partWidth(D, L, nBoot);              fprintf('V2 done (%.0f s)\n', toc(t0));
[L, R3] = partClearance(D, L);           fprintf('V3 done (%.0f s)\n', toc(t0));
[L, R4] = partImportance(D, L, nPerm);   fprintf('V4 done (%.0f s)\n', toc(t0));
[L, R5] = partStats(D, L, nBoot);        fprintf('V5 done (%.0f s)\n', toc(t0));
L = partApproach(D, L, nNull);           fprintf('V6 done (%.0f s)\n', toc(t0));
L = partValidity(D, L);                  fprintf('V7 done (%.0f s)\n', toc(t0));
mlTools.figures(out, 'validate', struct('R1', R1, 'R3', R3, 'R4', R4, 'R5', R5));
writeLines(fullfile(out, 'ml_validate_matlab.md'), L);
fprintf('Wrote %s (%.0f s)\n', fullfile(out, 'ml_validate_matlab.md'), toc(t0));
end

%% ========================================================================
%  V1: unseen obstacle heights
%% ========================================================================
function [L, R] = partHeights(D, L)
g = D.g;  y = D.y;  h = D.hNom;  LL = D.d.leg_length_cm;  P = unique(g)';  lab = {'H1', 'H2', 'H3'};
sc = {'self', 'person scaling'; 'levelcm', 'level-walk offset (generic)'};  md = {'ridge', 'forest'};
R = struct();
for s = 1:size(sc, 1)
    XL = D.FX.lead.(sc{s,1});  XT = D.FX.trail.(sc{s,1});
    for m = 1:numel(md)
        mo = md{m};  A = cell(numel(P), 1);  B = A;
        parfor k = 1:numel(P)
            te = g == P(k);  tr = ~te;  yk = y(te);  xl = XL(te, :);  xt = XT(te, :); %#ok<PFBNS>
            A{k} = (regFit(XL(tr,:), h(tr), xl, mo) + regFit(XT(tr,:), h(tr), xt, mo)) / 2; %#ok<PFBNS>
            b = nan(nnz(te), 1);
            for c = 1:numel(lab)
                tc = strcmp(yk, lab{c});  trc = tr & ~strcmp(y, lab{c});
                if any(tc), b(tc) = (regFit(XL(trc,:), h(trc), xl(tc,:), mo) + regFit(XT(trc,:), h(trc), xt(tc,:), mo)) / 2; end
            end
            B{k} = b;
        end
        ref = nan(numel(y), 1);  lo = ref;
        for k = 1:numel(P), ref(g == P(k)) = A{k};  lo(g == P(k)) = B{k}; end
        R.(sc{s,1}).(mo) = struct('ref', ref, 'loho', lo);
    end
end
R.y = y;  R.h = h;
L = addl(L, '## V1. Unseen obstacle heights - does the model learn the scaling, or only three classes?');
L = addl(L, '');
L = addl(L, ['Regression of the nominal obstacle height (cm) from the two foot IMUs (lead + trail models, mean of the two estimates). ' ...
    '"All heights trained" = the usual leave-one-participant-out model. "This height left out" = the model is trained on the OTHER participants'' ' ...
    'crossings of the other two height levels only, so the tested height level was never seen in training (H2 left out = interpolation, H1 or H3 ' ...
    'left out = extrapolation). Cells: mean absolute error in cm (mean signed error, + = too high); "right level" = the estimate is closest to the ' ...
    'person''s true nominal height among their three (10 / 20 / 30 %% of leg length; neighbouring heights 8.3-10.6 cm apart). Person scaling uses ' ...
    'each person''s crossings without labels (all heights), as in the rest of the project.']);
L = addl(L, '');
for s = 1:size(sc, 1)
    L = addl(L, '**%s**', sc{s,2});
    L = addl(L, '');
    L = addl(L, '| model | training | H1 tested | H2 tested | H3 tested | all |');
    L = addl(L, '|---|---|---|---|---|---|');
    for m = 1:numel(md)
        for w = {'ref', 'all heights trained'; 'loho', 'this height left out'}'
            pc = R.(sc{s,1}).(md{m}).(w{1});  c = cell(1, 4);
            for k = 1:4
                if k <= 3, mk = strcmp(y, lab{k}); else, mk = true(size(y)); end
                [ma, bi, ok] = errStats(pc, h, LL, y, mk);
                c{k} = sprintf('%.1f (%+.1f); right level %.0f%%', ma, bi, 100 * ok);
            end
            L = addl(L, '| %s | %s | %s |', md{m}, w{2}, strjoin(c, ' | '));
        end
    end
    L = addl(L, '');
end
end

function yp = regFit(Xtr, ytr, Xte, mdl)
% Ridge (lambda 10 on z-scored features) or random-forest regression; median imputation from the training rows.
med = median(Xtr, 1, 'omitnan');  med(isnan(med)) = 0;
Xtr = mlTools.fillMed(Xtr, med);  Xte = mlTools.fillMed(Xte, med);
mu = mean(Xtr, 1);  sd = std(Xtr, 0, 1);  sd(sd == 0) = 1;
Ztr = (Xtr - mu) ./ sd;  Zte = (Xte - mu) ./ sd;
if strcmp(mdl, 'ridge')
    A = [ones(size(Ztr, 1), 1) Ztr];  Rg = 10 * eye(size(A, 2));  Rg(1, 1) = 0;
    b = (A' * A + Rg) \ (A' * ytr);  yp = [ones(size(Zte, 1), 1) Zte] * b;
else
    rng(0);  M = TreeBagger(300, Ztr, ytr, 'Method', 'regression', 'MinLeafSize', 3);  yp = predict(M, Zte);
end
end

function [mae, bias, ok] = errStats(pc, h, LL, y, m)
e = pc(m) - h(m);  mae = mean(abs(e));  bias = mean(e);
[~, k] = min(abs(LL(m) .* [0.1 0.2 0.3] - pc(m)), [], 2);
labs = {'H1', 'H2', 'H3'};  ok = mean(strcmp(reshape(labs(k), [], 1), y(m)));
end

%% ========================================================================
%  V2: unseen obstacle width
%% ========================================================================
function L = partWidth(D, L, nBoot)
g = D.g;  y = D.y;  P = unique(g)';  cl = unique(y);  wc = D.d.width_class;  wl = unique(wc);
XL = D.FX.lead.self;  XT = D.FX.trail.self;  rf = D.rf;  parts = cell(numel(P), 1);
parfor k = 1:numel(P)
    te = g == P(k);  idx = find(te);  wk = wc(te);  A = zeros(numel(idx), numel(cl), 3); %#ok<PFBNS>
    for j = 1:numel(wl)
        tw = strcmp(wk, wl{j});  ii = idx(tw);  same = strcmp(wc, wl{j});
        A(tw, :, 1) = fusePred(rf, XL, XT, y, ~te & same, ii, cl);
        A(tw, :, 2) = fusePred(rf, XL, XT, y, ~te & ~same, ii, cl);
        A(tw, :, 3) = fusePred(rf, XL, XT, y, ~te, ii, cl);
    end
    parts{k} = A;
end
Pw = zeros(numel(y), numel(cl), 3);
for k = 1:numel(P), Pw(g == P(k), :, :) = parts{k}; end
pred = cell(1, 3);
for c = 1:3, pred{c} = mlTools.argmaxLab(Pw(:, :, c), cl); end
L = addl(L, '## V2. Unseen obstacle width - does the height model transfer across widths?');
L = addl(L, '');
L = addl(L, ['Height recognition (two foot IMUs, person scaling, forest, soft vote) tested on one width, trained on the other participants'' ' ...
    'crossings of the SAME width, of the OTHER width only, or of both. Same-width and other-width training sets have the same size, so their ' ...
    'difference is the cost of a width never seen in training.']);
L = addl(L, '');
L = addl(L, '| tested on | trained on the same width | trained on the other width only | trained on both widths |');
L = addl(L, '|---|---|---|---|');
for j = 1:numel(wl) + 1
    if j <= numel(wl)
        m = strcmp(wc, wl{j});  nm = sprintf('%s (%.0f cm)', wl{j}, median(D.d.width_cm(m), 'omitnan'));
    else
        m = true(size(y));  nm = 'both widths';
    end
    c = arrayfun(@(i) sprintf('%.1f%%', 100 * mlTools.balAcc(y(m), pred{i}(m))), 1:3, 'UniformOutput', false);
    L = addl(L, '| %s | %s |', nm, strjoin(c, ' | '));
end
ci = mlTools.bootCI(y, pred{2}, g, pred{1}, nBoot);
L = addl(L, '');
L = addl(L, 'Other width minus same width (all crossings): %+.1f points (95%% CI %+.1f to %+.1f).', ...
    100 * (mlTools.balAcc(y, pred{2}) - mlTools.balAcc(y, pred{1})), 100 * ci(3), 100 * ci(4));
L = addl(L, '');
end

function Pf = fusePred(s, XL, XT, y, tr, ii, cl)
% Lead and trail models fitted on rows `tr`, soft vote for rows `ii` (class order `cl`).
Pf = zeros(numel(ii), numel(cl));
for X = {XL, XT}
    M = mlTools.fitPipe(s, X{1}(tr, :), y(tr));
    [~, j] = ismember(M.classes, cl);
    Pf(:, j) = Pf(:, j) + mlTools.predictPipe(M, X{1}(ii, :)) / 2;
end
end

%% ========================================================================
%  V3: what sets the toe clearance
%% ========================================================================
function [L, R] = partClearance(D, L)
d = D.d;  g = D.g;  gc = findgroups(d.participant_id, d.obstacle_code);  hmm = 10 * D.hNom;
R = struct();  Q = struct();
for l = {'lead', 'trail'}
    li = l{1};
    clr = d.([li '_cam_min_clearance']);
    apex = d.([li '_cam_peak_foot_h']) - d.cam_obstacle_h;        % camera toe peak above the obstacle top
    tko = d.([li '_cam_takeoff_toeoff']);                         % toe before the near edge at its own toe-off
    imuS = d.([li '_zhc_peak_foot_h']);  imuT = d.([li '_zhc_peak_toe_h']);
    ok = all(isfinite([clr apex tko imuS imuT]), 2);  n = nnz(ok);  nC = numel(unique(gc(ok)));
    yc = centreCells(clr(ok), gc(ok));
    X = [centreCells(apex(ok), gc(ok)), centreCells(tko(ok), gc(ok)), centreCells(imuS(ok), gc(ok)), centreCells(imuT(ok), gc(ok))];
    sdw = sqrt(sum([yc X].^2, 1) / (n - nC));
    r2 = @(Z) 1 - sum((yc - Z * (Z \ yc)).^2) / sum(yc.^2);
    rr = corr(yc, X);
    Q.(li) = struct('n', n, 'nC', nC, 'sdw', sdw, 'r', rr, 'rImuApex', corr(X(:,3), X(:,1)), 'rImuTko', corr(X(:,3), X(:,2)), ...
        'r2', [r2(X(:,1)), r2(X(:,2)), r2(X(:,1:2)), r2(X(:,3)), r2(X(:,4)), r2(X(:,[3 2]))]);
    % absolute clearance on a new person (ordinary least squares, leave-one-participant-out)
    go = g(ok);  ya = clr(ok);
    E = {'constant (training mean)', zeros(n, 0); 'IMU: foot lift + obstacle height', [imuS(ok) hmm(ok)]; ...
         'IMU + take-off distance (camera)', [imuS(ok) hmm(ok) tko(ok)]; 'camera toe peak + take-off distance', [apex(ok) tko(ok)]};
    for e = 1:size(E, 1)
        pc = lopoOls(E{e,2}, ya, go);
        Q.(li).est(e) = struct('name', E{e,1}, 'mae', mean(abs(pc - ya)), 'r', corr(pc, ya));
    end
    R.(li) = Q.(li).r2;
end
L = addl(L, '## V3. What sets the toe clearance, and what the IMU can see of it');
L = addl(L, '');
L = addl(L, ['Camera minimum clearance over the obstacle. Two camera quantities could set it: how HIGH the toe goes (camera toe-marker peak above the ' ...
    'obstacle top) and WHERE the foot leaves the floor (take-off distance: toe before the near edge at the limb''s own toe-off). The IMU measures the ' ...
    'first (foot lift = foot-sensor rise; toe rise = rigid-body toe estimate, provisional) but has no reference to the obstacle position. ' ...
    '"Within cells" = each variable minus its participant x obstacle mean, so only the crossing-to-crossing variation is left (the part a device ' ...
    'would have to track for one person and one obstacle).']);
L = addl(L, '');
L = addl(L, '| within participant x obstacle cells | leading limb | trailing limb |');
L = addl(L, '|---|---|---|');
L = addl(L, '| crossings (cells) | %d (%d) | %d (%d) |', Q.lead.n, Q.lead.nC, Q.trail.n, Q.trail.nC);
L = addl(L, '| clearance SD (mm) | %.0f | %.0f |', Q.lead.sdw(1), Q.trail.sdw(1));
nm = {'camera toe peak above the obstacle', 'camera take-off distance', 'IMU foot lift', 'IMU toe rise (provisional)'};
for k = 1:4
    L = addl(L, '| %s: SD (mm), r with clearance | %.0f, r = %+.2f | %.0f, r = %+.2f |', nm{k}, Q.lead.sdw(k+1), Q.lead.r(k), Q.trail.sdw(k+1), Q.trail.r(k));
end
L = addl(L, '| r of IMU foot lift with the camera toe peak | %+.2f | %+.2f |', Q.lead.rImuApex, Q.trail.rImuApex);
L = addl(L, '| r of IMU foot lift with the take-off distance | %+.2f | %+.2f |', Q.lead.rImuTko, Q.trail.rImuTko);
r2n = {'camera toe peak', 'camera take-off distance', 'camera toe peak + take-off', 'IMU foot lift', 'IMU toe rise (provisional)', 'IMU foot lift + take-off (camera)'};
for k = 1:numel(r2n)
    L = addl(L, '| share of clearance variance explained: %s | %.0f%% | %.0f%% |', r2n{k}, 100 * Q.lead.r2(k), 100 * Q.trail.r2(k));
end
L = addl(L, '');
L = addl(L, '**Absolute clearance on a new participant** (ordinary least squares, leave-one-participant-out; obstacle height = nominal; mm):');
L = addl(L, '');
L = addl(L, '| inputs | leading limb: MAE, r | trailing limb: MAE, r |');
L = addl(L, '|---|---|---|');
for e = 1:numel(Q.lead.est)
    L = addl(L, '| %s | %.0f mm, r = %.2f | %.0f mm, r = %.2f |', Q.lead.est(e).name, Q.lead.est(e).mae, Q.lead.est(e).r, Q.trail.est(e).mae, Q.trail.est(e).r);
end
L = addl(L, '');
end

function v = centreCells(v, gc)
for c = unique(gc)'
    i = gc == c;  v(i) = v(i) - mean(v(i), 'omitnan');
end
end

function yp = lopoOls(X, yv, g)
yp = nan(size(yv));
for p = unique(g)'
    te = g == p;  tr = ~te;
    b = [ones(nnz(tr), 1) X(tr, :)] \ yv(tr);
    yp(te) = [ones(nnz(te), 1) X(te, :)] * b;
end
end

%% ========================================================================
%  V4: what the model uses
%% ========================================================================
function [L, R] = partImportance(D, L, nPerm)
g = D.g;  y = D.y;  P = unique(g)';  cl = unique(y);  rf = D.rf;
XL = D.FX.lead.self;  XT = D.FX.trail.self;  nl = size(XL, 2);  nF = nl + size(XT, 2);
names = [strcat({'lead: '}, D.FX.lead.names), strcat({'trail: '}, D.FX.trail.names)];
G = groupsOf(D.FX.lead.names, D.FX.trail.names, nl);  nG = numel(G);
parts = cell(numel(P), 1);
parfor k = 1:numel(P)
    te = g == P(k);  n = nnz(te);  rs = RandStream('mt19937ar', 'Seed', 500 + k);
    ML = mlTools.fitPipe(rf, XL(~te, :), y(~te));  MT = mlTools.fitPipe(rf, XT(~te, :), y(~te)); %#ok<PFBNS>
    xl = XL(te, :);  xt = XT(te, :);
    pl = alignP(ML, mlTools.predictPipe(ML, xl), cl);  pt = alignP(MT, mlTools.predictPipe(MT, xt), cl);
    [~, base] = max(pl + pt, [], 2);
    PG = zeros(n, nG, nPerm);  PF = zeros(n, nF, nPerm);
    for r = 1:nPerm
        pm = randperm(rs, n);
        for j = 1:nG
            cL = G(j).cols(G(j).cols <= nl);  cT = G(j).cols(G(j).cols > nl) - nl;  ql = pl;  qt = pt; %#ok<PFBNS>
            if ~isempty(cL), z = xl;  z(:, cL) = xl(pm, cL);  ql = alignP(ML, mlTools.predictPipe(ML, z), cl); end
            if ~isempty(cT), z = xt;  z(:, cT) = xt(pm, cT);  qt = alignP(MT, mlTools.predictPipe(MT, z), cl); end
            [~, PG(:, j, r)] = max(ql + qt, [], 2);
        end
        for f = 1:nF
            ql = pl;  qt = pt;
            if f <= nl
                z = xl;  z(:, f) = xl(pm, f);  ql = alignP(ML, mlTools.predictPipe(ML, z), cl);
            else
                z = xt;  z(:, f - nl) = xt(pm, f - nl);  qt = alignP(MT, mlTools.predictPipe(MT, z), cl);
            end
            [~, PF(:, f, r)] = max(ql + qt, [], 2);
        end
    end
    parts{k} = {base, PG, PF};
end
base = zeros(numel(y), 1);  PG = zeros(numel(y), nG, nPerm);  PF = zeros(numel(y), nF, nPerm);
for k = 1:numel(P)
    m = g == P(k);  base(m) = parts{k}{1};  PG(m, :, :) = parts{k}{2};  PF(m, :, :) = parts{k}{3};
end
b0 = mlTools.balAcc(y, cl(base));
dG = zeros(nG, nPerm);  dF = zeros(nF, nPerm);
for r = 1:nPerm
    for j = 1:nG, dG(j, r) = b0 - mlTools.balAcc(y, cl(PG(:, j, r))); end
    for f = 1:nF, dF(f, r) = b0 - mlTools.balAcc(y, cl(PF(:, f, r))); end
end
L = addl(L, '## V4. What the device model relies on (permutation importance)');
L = addl(L, '');
L = addl(L, ['Final model (two foot IMUs, person scaling, forest, soft vote; %.1f%% here). In each left-out participant, one feature group (or one ' ...
    'feature) is shuffled across that participant''s crossings and the drop in balanced accuracy is recorded (mean +- SD over %d shuffles). ' ...
    'A large drop = the model needs that information; a small drop for a group can also mean another group carries the same information.'], 100 * b0, nPerm);
L = addl(L, '');
L = addl(L, '| shuffled feature group | features | accuracy drop (points) |');
L = addl(L, '|---|---|---|');
[~, o] = sort(mean(dG, 2), 'descend');
for j = o'
    L = addl(L, '| %s | %d | %.1f +- %.1f |', G(j).name, numel(G(j).cols), 100 * mean(dG(j, :)), 100 * std(dG(j, :)));
end
L = addl(L, '');
L = addl(L, '**Top 12 single features:**');
L = addl(L, '');
L = addl(L, '| feature | accuracy drop (points) |');
L = addl(L, '|---|---|');
[~, o] = sort(mean(dF, 2), 'descend');
for f = o(1:min(12, nF))'
