function X = normX(D, cols, norm, rows)
j = ci(D.feats, cols);
switch norm
    case 'raw',   X = D.Xraw(rows, j);
    case 'level', X = D.Xcal(rows, j);
    case 'self',  X = mlTools.selfnorm(D.Xraw(rows, j), D.T.participant_id(rows));
end
end

function b = fewShot(Xs, y, g, labs, k, w, seed)
rs = RandStream('mt19937ar', 'Seed', seed);
yt = {};  yp = {};
for p = unique(g)'
    ip = find(g == p);  cal = [];
    for c = 1:numel(labs)
        ic = ip(strcmp(y(ip), labs{c}));
        if numel(ic) > k, cal = [cal; ic(randperm(rs, numel(ic), k))]; end %#ok<AGROW>
    end
    te = setdiff(ip, cal);  tr = [find(g ~= p); cal];
    sw = ones(numel(tr), 1);  sw(ismember(tr, cal)) = w;
    Pf = 0;
    for x = 1:numel(Xs)
        M = mlTools.fitPipe(mlTools.spec('logreg'), Xs{x}(tr,:), y(tr), sw);
        Pf = Pf + mlTools.predictPipe(M, Xs{x}(te,:)) / numel(Xs);
    end
    yt = [yt; y(te)]; %#ok<AGROW>
    yp = [yp; mlTools.argmaxLab(Pf, M.classes)]; %#ok<AGROW>
end
b = mlTools.balAcc(yt, yp);
end

function b = selfFromN(s, X, y, g, ord, mode, n, seed)
rs = RandStream('mt19937ar', 'Seed', seed);
P = unique(g)';  yt = cell(numel(P), 1);  yp = cell(numel(P), 1);
parfor k = 1:numel(P)
    p = P(k);  tr = g ~= p;
    Xtr = mlTools.selfnorm(X(tr,:), g(tr)); %#ok<PFBNS>
    ip = find(g == p);
    if strcmp(mode, 'random'), sub = randperm(rs, numel(ip), n); else, [~, o] = sort(ord(ip)); sub = o(1:n); end %#ok<PFBNS>
    te = setdiff(1:numel(ip), sub);
    [med, iqr] = mlTools.medIqr(X(ip(sub), :));
    Xp = (X(ip(te), :) - med) ./ iqr;
    M = mlTools.fitPipe(s, Xtr, y(tr)); %#ok<PFBNS>
    yp{k} = mlTools.argmaxLab(mlTools.predictPipe(M, Xp), M.classes);
    yt{k} = y(ip(te));
end
b = mlTools.balAcc(vertcat(yt{:}), vertcat(yp{:}));
end

