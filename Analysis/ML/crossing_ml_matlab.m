if n < 9, s = sprintf('%.0f%% (%.0f-%.0f)', 100*LC.mean(m,i), 100*LC.p10(m,i), 100*LC.p90(m,i));
else, s = sprintf('%.0f%%', 100*LC.mean(m,i)); end
end

function s = confCell(Pk, pr, y, th)
k = max(Pk, [], 2) >= th;
if any(k), s = sprintf('%.0f%% acc, %.0f%% kept', 100*mean(strcmp(pr(k), y(k))), 100*mean(k)); else, s = '-'; end
end

