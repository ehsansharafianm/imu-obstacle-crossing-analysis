function crossing_ml_matlab(sections, quick)
% CROSSING_ML_MATLAB  MATLAB port of the ML feasibility analyses (Python: Analysis/ML/python/).
%
%   crossing_ml_matlab                    % everything (takes a while: permutation tests)
%   crossing_ml_matlab({'main','limbs'})  % selected parts
%   crossing_ml_matlab([], true)          % quick test run (few permutations / repeats)
%
% Question: do the wearable (Dot) features ALONE carry information about the obstacle, in a
% participant the model has never seen? Same analyses as the Python scripts:
%   main      crossing_ml.py           height / width, all / lead / trail / segment groups,
%                                      raw vs level-calibrated, logistic vs forest, top-k
%   followup  crossing_ml_followup.py  cueing window, time-resolved prediction, bootstrap CIs,
%                                      learning curve, ordinal model, confidence
%   limbs     crossing_ml_limbs.py     separate lead / trail models + soft-vote fusion, height /
%                                      width / 6 obstacles, lead-vs-trail, obstacle-vs-level,
%                                      personal calibration, self-normalization from n crossings
%   settings  crossing_ml_settings.py  nested setting selection, segment ranking and timing with
%                                      self-normalization, causal normalization, per participant
% Rules: leave-one-participant-out; every fitted step on the training participants only;
% inputs = FEATURE columns of the data dictionary (Dot only, toe height left out); participant
% bootstrap 95% CIs; permutation tests with labels shuffled within participant.
% Building blocks: mlTools.m. Outputs -> Results/ML Models/MATLAB/:
%   ml_report_matlab.md, ml_results_matlab.csv, fig_*.png (incl. a MATLAB vs Python comparison).

if nargin < 1 || isempty(sections), sections = {'main','followup','limbs','settings'}; end
if nargin < 2, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);

CFG.include   = 'include_ml';
CFG.nPermMain = 1000;  CFG.nPermGroup = 300;  CFG.nPermLimb = 300;
CFG.nBoot     = 2000;  CFG.lcRepeats = 40;    CFG.fsRepeats = 20;  CFG.selfRepeats = 10;
CFG.cuts      = 0:10:100;
CFG.preSwing  = {'stride_len_app1','stride_len_app2','speed_approach','lead_stance_time'};
CFG.leadG     = {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'};
CFG.kSparse   = [1 3 5 10];
if quick
    CFG.nPermMain = 20;  CFG.nPermGroup = 10;  CFG.nPermLimb = 10;  CFG.nBoot = 200;
    CFG.lcRepeats = 3;   CFG.fsRepeats = 2;    CFG.selfRepeats = 2;
end
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end

D = mlTools.load(root);
D.Xraw = D.T{:, D.feats};
D.mm = strcmp(D.units, 'mm');
D.Xcal = mlTools.calibrate(D.T, D.Xraw, D.mm);
D.S = mlTools.featureSets(D.feats);
D.out = out;
fprintf('%d rows, %d Dot features\n', height(D.T), numel(D.feats));

L = {};  R = [];
L = addl(L, '# ML feasibility analyses - MATLAB version');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_matlab.m` (building blocks `mlTools.m`) on %s, MATLAB %s._', ...
    char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), version('-release'));
L = addl(L, '');
L = addl(L, ['Port of the Python analyses in `Analysis/ML/python/`. Same data, rules and models: leave-one-participant-out on 10 participants; ' ...
    'imputation, scaling, feature selection and the model fitted on the 9 training participants only; L2 logistic regression with the ' ...
    'scikit-learn objective (C*sum(loss) + 0.5*||W||^2, fminunc quasi-Newton); random forest = TreeBagger (min leaf 2, sqrt(p) ' ...
    'predictors per split, uniform class prior). Logistic results reproduce Python to rounding; forest results and anything with random ' ...
    'draws (bootstrap, permutations, learning curve, calibration draws) differ slightly because the random generators and the forest ' ...
    'implementation differ. Comparison in the last section.%s'], ternary(quick, ' **QUICK TEST RUN (few permutations).**', ''));
L = addl(L, '');
t0 = tic;
if any(strcmp(sections, 'main')),     [L, R] = secMain(D, CFG, L, R);     fprintf('main done (%.0f s)\n', toc(t0)); end
if any(strcmp(sections, 'followup')), [L, R] = secFollowup(D, CFG, L, R); fprintf('followup done (%.0f s)\n', toc(t0)); end
if any(strcmp(sections, 'limbs')),    [L, R] = secLimbs(D, CFG, L, R);    fprintf('limbs done (%.0f s)\n', toc(t0)); end
if any(strcmp(sections, 'settings')), [L, R] = secSettings(D, CFG, L, R); fprintf('settings done (%.0f s)\n', toc(t0)); end
L = secCompare(D, R, L);
writeLines(fullfile(out, 'ml_report_matlab.md'), L);
writeResults(fullfile(out, 'ml_results_matlab.csv'), R);
fprintf('Wrote %s (%.0f s)\n', out, toc(t0));
end

%% ========================================================================
%  MAIN (crossing_ml.py)
%% ========================================================================
function [L, R] = secMain(D, CFG, L, R)
T = D.T;  S = D.S;
tasks = {'height','height_class'; 'width','width_class'};
mainSets = {'all','lead only','trail only'};
conf = struct('key', {}, 'lab', {}, 'cm', {});
for t = 1:2
    for s = 1:numel(S)
        isMain = any(strcmp(S(s).name, mainSets));
        np = ternary(isMain, CFG.nPermMain, CFG.nPermGroup);
        [R, conf] = mainRun(D, CFG, R, conf, tasks(t,:), S(s).name, 'calibrated', 'logreg', CFG.include, np);
        if isMain
            [R, conf] = mainRun(D, CFG, R, conf, tasks(t,:), S(s).name, 'raw', 'logreg', CFG.include, 0);
            [R, conf] = mainRun(D, CFG, R, conf, tasks(t,:), S(s).name, 'calibrated', 'forest', CFG.include, 0);
            [R, conf] = mainRun(D, CFG, R, conf, tasks(t,:), S(s).name, 'raw', 'forest', CFG.include, 0);
        end
    end
end
[R, conf] = mainRun(D, CFG, R, conf, tasks(1,:), 'all', 'calibrated', 'logreg', 'include_ml_noflag', 0);
% ---- top-k sparse ----
sel = T.is_level == 0 & T.(CFG.include) == 1;
y = T.height_class(sel);  g = T.participant_id(sel);
SP = struct('features', {}, 'k', {}, 'bal', {}, 'top', {});
for nm = {'all', 'lead only'}
    cols = mlTools.getSet(S, nm{1});  X = D.Xcal(sel, ci(D.feats, cols));
    for k = CFG.kSparse
        [Pr, cl, sl] = mlTools.lopo(mlTools.spec('logreg', 'k', k), X, y, g);
        fr = zeros(1, numel(cols));
        for f = 1:numel(sl), fr(sl{f}) = fr(sl{f}) + 1; end
        [~, o] = sort(-fr);  o = o(1:max(k, 5));  o = o(fr(o) > 0);
        SP(end+1) = struct('features', nm{1}, 'k', k, 'bal', mlTools.balAcc(y, mlTools.argmaxLab(Pr, cl)), ...
            'top', strjoin(arrayfun(@(i) sprintf('%s (%d/10)', cols{i}, fr(i)), o, 'UniformOutput', false), '; ')); %#ok<AGROW>
    end
end
% ---- report ----
M = R(strcmp({R.analysis}, 'main'));
L = addl(L, '# Part 1. Main models (Python: `ml_report.md`)');
L = addl(L, '');
L = addl(L, '- **Rows:** obstacle crossings with `%s` = 1: %d rows, %d participants (H1/H2/H3 = %d, %d, %d; W1/W2 = %d, %d).', CFG.include, nnz(sel), ...
    numel(unique(g)), sum(strcmp(y,'H1')), sum(strcmp(y,'H2')), sum(strcmp(y,'H3')), sum(strcmp(T.width_class(sel),'W1')), sum(strcmp(T.width_class(sel),'W2')));
L = addl(L, '- **Inputs:** the %d Dot FEATURE columns; no labels, camera, timing / block or flag columns; toe height left out (provisional).', numel(D.feats));
L = addl(L, '- **Main model:** L2 logistic regression, C = 0.1 fixed in advance; check: random forest (500 trees). **Calibrated** = minus own level-walk median, lengths / leg length.');
L = addl(L, '- **Permutation test:** labels shuffled within participant (%d permutations for all / lead / trail, %d for the groups).', CFG.nPermMain, CFG.nPermGroup);
L = addl(L, '');
L = addl(L, '## Q1 / Q3 / Q4. Headline runs');
L = addl(L, '');
L = mainTable(L, M(ismember({M.features}, mainSets) & strcmp({M.rows}, CFG.include)));
L = addl(L, 'Sensitivity (drift flag ignored, `include_ml_noflag`):');
L = addl(L, '');
L = mainTable(L, M(~strcmp({M.rows}, CFG.include)));
L = addl(L, '## Q2. Which segment and limb (calibrated logistic regression)');
L = addl(L, '');
for task = {'height', 'width'}
    L = mainTable(L, M(strcmp({M.task}, task{1}) & ~ismember({M.features}, mainSets) & strcmp({M.rows}, CFG.include)));
end
L = addl(L, '## Q3b. How few features (height, calibrated, ANOVA-F top-k inside each training fold)');
L = addl(L, '');
L = addl(L, '| features | k | bal. acc | most often selected (folds of 10) |');
L = addl(L, '|---|---|---|---|');
for i = 1:numel(SP), L = addl(L, '| %s | %d | %.1f%% | %s |', SP(i).features, SP(i).k, 100*SP(i).bal, SP(i).top); end
L = addl(L, '');
L = addl(L, '## Per participant (height, calibrated logistic regression)');
L = addl(L, '');
P = 101:110;
L = addl(L, ['| features | ' strjoin(arrayfun(@num2str, P, 'UniformOutput', false), ' | ') ' |']);
L = addl(L, ['|---|' repmat('---|', 1, numel(P))]);
for nm = mainSets
    r = M(strcmp({M.task}, 'height') & strcmp({M.features}, nm{1}) & strcmp({M.normalization}, 'calibrated') & strcmp({M.model}, 'logreg') & strcmp({M.rows}, CFG.include));
    L = addl(L, '| %s | %s |', nm{1}, strjoin(arrayfun(@(a) sprintf('%.0f%%', 100*a), r.acc, 'UniformOutput', false), ' | '));
end
L = addl(L, '');
L = addl(L, '## Confusion matrices (calibrated logistic regression; rows = true)');
L = addl(L, '');
for key = {'height|all', 'height|lead only', 'width|all'}
    c = conf(strcmp({conf.key}, key{1}));
    L = addl(L, '**%s**', strrep(key{1}, '|', ' - '));
    L = addl(L, '');
    L = addl(L, ['| true \\ pred | ' strjoin(c.lab', ' | ') ' |']);
    L = addl(L, ['|---|' repmat('---|', 1, numel(c.lab))]);
    for i = 1:numel(c.lab), L = addl(L, ['| %s | ' strjoin(arrayfun(@num2str, c.cm(i,:), 'UniformOutput', false), ' | ') ' |'], c.lab{i}); end
    L = addl(L, '');
end
mlTools.figures(D.out, 'main', struct('M', M, 'conf', conf, 'include', CFG.include));
end

function [R, conf] = mainRun(D, CFG, R, conf, task, setName, norm, model, include, nPerm)
T = D.T;
sel = T.is_level == 0 & T.(include) == 1;
cols = mlTools.getSet(D.S, setName);
if strcmp(norm, 'calibrated'), X = D.Xcal(sel, ci(D.feats, cols)); else, X = D.Xraw(sel, ci(D.feats, cols)); end
y = T.(task{2})(sel);  g = T.participant_id(sel);
s = mlTools.spec(model);
[Pr, cl] = mlTools.lopo(s, X, y, g);
pred = mlTools.argmaxLab(Pr, cl);
r = newRow('main');
r.task = task{1};  r.features = setName;  r.normalization = norm;  r.model = model;  r.rows = include;
r.n_features = numel(cols);  r.n_rows = numel(y);  r.chance = 1 / numel(cl);
r.bal_acc = mlTools.balAcc(y, pred);  r.macro_f1 = mlTools.macroF1(y, pred);  r.acc = accPer(y, pred, g);
if nPerm > 0
    [r.perm_p, r.null95] = mlTools.permTest(s, {X}, y, g, r.bal_acc, nPerm, 1);
end
R = [R, r];
if strcmp(include, CFG.include) && strcmp(norm, 'calibrated') && strcmp(model, 'logreg')
    conf(end+1) = struct('key', [task{1} '|' setName], 'lab', {cl}, 'cm', confmat(y, pred, cl));
end
fprintf('  %-6s %-24s %-10s %-6s bal_acc=%.3f\n', task{1}, setName, norm, model, r.bal_acc);
end

function L = mainTable(L, M)
L = addl(L, '| task | features | norm | model | n feat | n rows | bal. acc | macro F1 | chance | perm p | null 95%% |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|---|---|');
for r = M
    L = addl(L, '| %s | %s | %s | %s | %d | %d | %.1f%% | %.2f | %.0f%% | %s | %s |', r.task, r.features, r.normalization, r.model, ...
        r.n_features, r.n_rows, 100*r.bal_acc, r.macro_f1, 100*r.chance, pstr(r.perm_p), pctOr(r.null95));
end
L = addl(L, '');
end

%% ========================================================================
%  FOLLOW-UP (crossing_ml_followup.py)
%% ========================================================================
function [L, R] = secFollowup(D, CFG, L, R)
T = D.T;  S = D.S;  F = D.feats;
obs = T.is_level == 0 & T.(CFG.include) == 1;
y = T.height_class(obs);  g = T.participant_id(obs);  d = T(obs, :);
lead = mlTools.getSet(S, 'lead only');
models = {'all', mlTools.getSet(S, 'all');
          'lead only', lead;
          'trail only', mlTools.getSet(S, 'trail only');
          'lead foot IMU', lead(startsWith(lead, {'lead_foot_', 'lead_zhc_'}) | ismember(lead, [{'lead_swing_time', 'lead_stance_time'}, CFG.leadG]));
          'lead thigh IMU', lead(startsWith(lead, 'lead_thigh_'));
          'lead shank IMU', lead(startsWith(lead, 'lead_shank_'));
          'lead foot peak height (1 feature)', {'lead_zhc_peak_foot_h'};
          'lead thigh max flexion (1 feature)', {'lead_thigh_max'}};
pred = cell(size(models, 1), 1);
for m = 1:size(models, 1)
    [Pr, cl] = mlTools.lopo(mlTools.spec('logreg'), D.Xcal(obs, ci(F, models{m,2})), y, g);
    pred{m} = mlTools.argmaxLab(Pr, cl);
end
L = addl(L, '# Part 2. Cueing window, time-resolved prediction, robustness (Python: `ml_followup.md`)');
L = addl(L, '');
L = addl(L, 'Same rows and rules as Part 1: %d obstacle crossings, logistic regression (C = 0.1), calibrated features, height (chance 33%%). 95%% CI = participant bootstrap (%d resamples).', nnz(obs), CFG.nBoot);
L = addl(L, '');
% ---- 1. cueing window ----
W = {'lead toe-off -> trailing lift-off', d.trail_toeoff_t_cam - d.lead_toeoff_t;
     'lead foot apex -> trailing lift-off', d.trail_toeoff_t_cam - d.lead_crossing_t_imu;
     'lead landing -> trailing lift-off', d.trail_toeoff_t_cam - d.lead_landing_t;
     'trailing lift-off -> trailing foot apex', d.trail_crossing_t_imu - d.trail_toeoff_t_cam;
     'trailing lift-off -> step-4 trailing toe-off event (IMU)', d.trail_toeoff_t - d.trail_toeoff_t_cam};
L = addl(L, '## 2.1 Cueing window (ms)');
L = addl(L, '');
L = addl(L, ['Deadline = the trailing toe lift-off seen by the camera (`trail_toeoff_t_cam`): the step-4 IMU toe-off comes late on the trailing limb of a ' ...
    'crossing (last row; dataset build_report.md, task 15).']);
L = addl(L, '');
L = addl(L, '| interval | n | median | IQR | %% > 0 | H1 median | H2 median | H3 median |');
L = addl(L, '|---|---|---|---|---|---|---|---|');
for i = 1:size(W, 1)
    v = W{i,2} * 1000;  f = isfinite(v);
    hm = arrayfun(@(h) median(v(strcmp(y, sprintf('H%d', h))), 'omitnan'), 1:3);
    L = addl(L, '| %s | %d | %.0f | %.0f to %.0f | %.0f%% | %.0f | %.0f | %.0f |', W{i,1}, nnz(f), median(v(f)), ...
        mlTools.q7(v(f), 0.25), mlTools.q7(v(f), 0.75), 100*mean(v(f) > 0), hm);
end
P = unique(g)';
v = W{3,2} * 1000;
L = addl(L, '');
L = addl(L, 'Per participant median, lead landing -> trailing lift-off (ms): %s.', strjoin(arrayfun(@(p) sprintf('%d: %.0f', p, median(v(g == p), 'omitnan')), P, 'UniformOutput', false), ', '));
L = addl(L, '');
% ---- 2. time-resolved ----
Cv = mlTools.loadCurves(D.root, T.crossing_id);
TR = timeResolved(D, CFG, Cv, obs, {'level'}, {'logreg'}, CFG.nBoot);
Xp = mlTools.calibrate(T, T{:, CFG.preSwing}, ismember(CFG.preSwing, {'stride_len_app1','stride_len_app2'}));
[Pr, cl] = mlTools.lopo(mlTools.spec('logreg'), Xp(obs, :), y, g);
pp = mlTools.argmaxLab(Pr, cl);  pci = mlTools.bootCI(y, pp, g, [], CFG.nBoot);
L = addl(L, '## 2.2 Time-resolved prediction (lead limb only)');
L = addl(L, '');
L = addl(L, ['Features = the approach strides (%s) plus, for each lead swing curve (thigh, shank, foot tilt, foot |acc|, ZHC height and progression), ' ...
    'its value at the cut and its max / min / mean / slope from toe-off to the cut; calibrated (level-walk median, lengths / leg length). Median lead foot apex = %.0f%% of the lead swing.'], ...
    strjoin(CFG.preSwing, ', '), median(d.lead_zhc_peak_h_t, 'omitnan'));
L = addl(L, '');
L = addl(L, 'Approach strides only (before the lead foot leaves the floor): %.1f%% (95%% CI %.0f-%.0f).', 100*mlTools.balAcc(y, pp), 100*pci(1), 100*pci(2));
L = addl(L, '');
L = addl(L, '| data up to (%% lead swing) | median time before the trailing lift-off (ms) | n features | bal. acc | 95%% CI |');
L = addl(L, '|---|---|---|---|---|');
for i = 1:height(TR)
    L = addl(L, '| %d%% | %.0f | %d | %.1f%% | %.0f-%.0f |', TR.cut(i), TR.ms(i), TR.nfeat(i), 100*TR.level_logreg(i), 100*TR.level_logreg_lo(i), 100*TR.level_logreg_hi(i));
end
L = addl(L, '');
% ---- 3. bootstrap CIs ----
L = addl(L, '## 2.3 Bootstrap confidence intervals (height)');
L = addl(L, '');
L = addl(L, '| model | n features | bal. acc | 95%% CI | minus `all`: 95%% CI of the difference |');
L = addl(L, '|---|---|---|---|---|');
for m = 1:size(models, 1)
    ba = mlTools.balAcc(y, pred{m});
    if m == 1
        c = mlTools.bootCI(y, pred{m}, g, [], CFG.nBoot);  dd = '-';
    else
        c = mlTools.bootCI(y, pred{m}, g, pred{1}, CFG.nBoot);  dd = sprintf('%+.0f to %+.0f points', 100*c(3), 100*c(4));
    end
    r = newRow('followup');  r.task = 'height';  r.features = models{m,1};  r.normalization = 'calibrated';  r.model = 'logreg';
    r.n_features = numel(models{m,2});  r.n_rows = numel(y);  r.chance = 1/3;  r.bal_acc = ba;  r.ci_lo = c(1);  r.ci_hi = c(2);
    r.acc = accPer(y, pred{m}, g);  R = [R, r]; %#ok<AGROW>
    L = addl(L, '| %s | %d | %.1f%% | %.0f-%.0f | %s |', models{m,1}, numel(models{m,2}), 100*ba, 100*c(1), 100*c(2), dd);
end
c = mlTools.bootCI(y, pred{7}, g, pred{2}, CFG.nBoot);
L = addl(L, '');
L = addl(L, 'One feature (lead foot peak height) minus lead only: %+.0f to %+.0f points (95%% CI).', 100*c(3), 100*c(4));
dl = arrayfun(@(p) mean(strcmp(pred{2}(g == p), y(g == p))) - mean(strcmp(pred{1}(g == p), y(g == p))), P);
L = addl(L, 'Lead only minus all, per participant (accuracy points): %s. Better in %d of %d; mean without 108: %+.1f.', ...
    strjoin(arrayfun(@(p, v) sprintf('%d: %+.0f', p, 100*v), P, dl, 'UniformOutput', false), ', '), sum(dl > 0), numel(P), 100*mean(dl(P ~= 108)));
yw = T.width_class(obs);
[Pr, cl] = mlTools.lopo(mlTools.spec('logreg'), D.Xcal(obs, ci(F, models{1,2})), yw, g);
pw = mlTools.argmaxLab(Pr, cl);  c = mlTools.bootCI(yw, pw, g, [], CFG.nBoot);
L = addl(L, '');
L = addl(L, 'Width (all features): %.1f%% (95%% CI %.0f-%.0f; chance 50%%).', 100*mlTools.balAcc(yw, pw), 100*c(1), 100*c(2));
L = addl(L, '');
% ---- 4. learning curve ----
lcNames = {'all', 'lead only', 'lead foot IMU', 'lead foot peak height (1 feature)'};
LC = learningCurve(D, CFG, obs, y, g, models, lcNames);
L = addl(L, '## 2.4 Learning curve (height)');
L = addl(L, '');
L = addl(L, 'Each unseen participant predicted by a model trained on n randomly chosen other participants (%d draws per n; n = 9 = full LOPO). Mean balanced accuracy (10th-90th percentile over draws).', CFG.lcRepeats);
L = addl(L, '');
L = addl(L, ['| model | ' strjoin(arrayfun(@(n) sprintf('n=%d', n), 2:9, 'UniformOutput', false), ' | ') ' |']);
L = addl(L, ['|---|' repmat('---|', 1, 8)]);
for m = 1:numel(lcNames)
    c = arrayfun(@(n) lcCell(LC, m, n), 2:9, 'UniformOutput', false);
    L = addl(L, '| %s | %s |', lcNames{m}, strjoin(c, ' | '));
end
gain = arrayfun(@(m) 100 * (LC.mean(m, 8) - LC.mean(m, 5)), 1:numel(lcNames));
L = addl(L, '');
L = addl(L, 'Gain from 6 to 9 training participants (points): %s.', strjoin(arrayfun(@(m) sprintf('%s: %+.1f', lcNames{m}, gain(m)), 1:numel(lcNames), 'UniformOutput', false), ', '));
L = addl(L, '');
% ---- 5. ordinal + confidence ----
L = addl(L, '## 2.5 Ordinal model and confidence (height)');
L = addl(L, '');
L = addl(L, ['Frank & Hall ordinal logistic: two binary models P(height > H1) and P(height > H2) fitted inside each training set; P(H1) = 1 - P(>H1), ' ...
    'P(H2) = P(>H1) - P(>H2), P(H3) = P(>H2). Error in %% of leg length (H1/H2/H3 = 10/20/30%%); expected height = sum P x level.']);
L = addl(L, '');
L = addl(L, '| model | features | bal. acc | 95%% CI | H1<->H3 errors | MAE of class (%% LL) | MAE of expected height (%% LL) |');
L = addl(L, '|---|---|---|---|---|---|---|');
lvl = [10 20 30];  yl = lvl(cellfun(@(s) str2double(s(2)), y))';
confRows = {};
for nm = {'lead only', 'all', 'lead foot peak height (1 feature)'}
    X = D.Xcal(obs, ci(F, models{strcmp(models(:,1), nm{1}), 2}));
    [Pm, lab] = mlTools.lopo(mlTools.spec('logreg'), X, y, g);
    [P1, ~] = mlTools.lopo(mlTools.spec('logreg'), X, cellstr(num2str(yl > 10)), g);
    [P2, ~] = mlTools.lopo(mlTools.spec('logreg'), X, cellstr(num2str(yl > 20)), g);
    p1 = P1(:, 2);  p2 = min(P2(:, 2), p1);
    Po = [1 - p1, p1 - p2, p2];
    for kind = {'nominal', 'ordinal'}
        Pk = ternary(strcmp(kind{1}, 'nominal'), Pm, Po);
        pr = mlTools.argmaxLab(Pk, lab);
        pl = lvl(cellfun(@(s) str2double(s(2)), pr))';
        c = mlTools.bootCI(y, pr, g, [], CFG.nBoot);
        L = addl(L, '| %s | %s | %.1f%% | %.0f-%.0f | %d | %.1f | %.1f |', kind{1}, nm{1}, 100*mlTools.balAcc(y, pr), 100*c(1), 100*c(2), ...
            sum(abs(pl - yl) == 20), mean(abs(pl - yl)), mean(abs(Pk * lvl' - yl)));
        if strcmp(kind{1}, 'nominal'), confRows(end+1, :) = {nm{1}, Pk, pr}; end %#ok<AGROW>
    end
end
L = addl(L, '');
L = addl(L, 'Confidence (nominal model): accuracy on the crossings whose top class probability >= threshold, and the share kept.');
L = addl(L, '');
L = addl(L, '| model | >= 0.4 | >= 0.5 | >= 0.6 | >= 0.7 |');
L = addl(L, '|---|---|---|---|---|');
for i = 1:size(confRows, 1)
    c = arrayfun(@(th) confCell(confRows{i,2}, confRows{i,3}, y, th), [0.4 0.5 0.6 0.7], 'UniformOutput', false);
    L = addl(L, '| %s | %s |', confRows{i,1}, strjoin(c, ' | '));
end
L = addl(L, '');
ev = -[median((d.trail_toeoff_t_cam - d.lead_crossing_t_imu) * 1000, 'omitnan'), median((d.trail_toeoff_t_cam - d.lead_landing_t) * 1000, 'omitnan')];   % lead apex, lead landing
mlTools.figures(D.out, 'followup', struct('TR', TR, 'ev', ev, 'LC', LC, 'lcNames', {lcNames}));
end

function TR = timeResolved(D, CFG, Cv, obs, norms, mdls, nBoot)
% Lead-limb features up to each cut (% swing) + approach strides; one LOPO per norm x model.
T = D.T;  d = T(obs, :);  y = d.height_class;  g = d.participant_id;
TR = table();
for cut = CFG.cuts
    [Fc, names] = mlTools.cutFeatures(Cv, cut);
    Fc = [Fc, T{:, CFG.preSwing}];  names = [names, CFG.preSwing]; %#ok<AGROW>
    mm = startsWith(names, {'zhc_h', 'zhc_x'}) | ismember(names, {'stride_len_app1','stride_len_app2'});
    row = table(cut, median((d.trail_toeoff_t_cam - (d.lead_toeoff_t + cut/100 * d.lead_swing_time)) * 1000, 'omitnan'), numel(names), ...
        'VariableNames', {'cut','ms','nfeat'});
    for n = 1:numel(norms)
        if strcmp(norms{n}, 'level'), X = mlTools.calibrate(T, Fc, mm); X = X(obs, :);
        else, X = mlTools.selfnorm(Fc(obs, :), g); end
        for m = 1:numel(mdls)
            s = ternary(strcmp(mdls{m}, 'forest'), mlTools.spec('forest', 'nTrees', 300), mlTools.spec('logreg'));
            [Pr, cl] = mlTools.lopo(s, X, y, g);
            pr = mlTools.argmaxLab(Pr, cl);  c = mlTools.bootCI(y, pr, g, [], nBoot);
            k = [norms{n} '_' mdls{m}];
            row.(k) = mlTools.balAcc(y, pr);  row.([k '_lo']) = c(1);  row.([k '_hi']) = c(2);
        end
    end
    TR = [TR; row]; %#ok<AGROW>
end
end

function LC = learningCurve(D, CFG, obs, y, g, models, names)
P = unique(g)';  nm = numel(names);  ns = 2:9;
jobs = [];
for m = 1:nm
    for n = ns
        for r = 1:ternary(n < 9, CFG.lcRepeats, 1), jobs = [jobs; m n r]; end %#ok<AGROW>
    end
end
Xs = cellfun(@(nmm) D.Xcal(obs, ci(D.feats, models{strcmp(models(:,1), nmm), 2})), names, 'UniformOutput', false);
val = zeros(size(jobs, 1), 1);
parfor j = 1:size(jobs, 1)
    m = jobs(j, 1);  n = jobs(j, 2);  rs = RandStream('mt19937ar', 'Seed', 1000 * n + jobs(j, 3)); %#ok<PFBNS>
    X = Xs{m};  pr = cell(numel(y), 1); %#ok<PFBNS>
    for p = P
        oth = P(P ~= p);  pick = oth(randperm(rs, numel(oth), n));
        tr = ismember(g, pick);  te = g == p;
        M = mlTools.fitPipe(mlTools.spec('logreg'), X(tr,:), y(tr));
        pr(te) = mlTools.argmaxLab(mlTools.predictPipe(M, X(te,:)), M.classes);
    end
    val(j) = mlTools.balAcc(y, pr);
end
LC.mean = zeros(nm, 8);  LC.p10 = LC.mean;  LC.p90 = LC.mean;
for m = 1:nm
    for i = 1:8
        v = val(jobs(:,1) == m & jobs(:,2) == ns(i));
        LC.mean(m, i) = mean(v);  LC.p10(m, i) = mlTools.q7(v, 0.1);  LC.p90(m, i) = mlTools.q7(v, 0.9);
    end
end
end

function s = lcCell(LC, m, n)
