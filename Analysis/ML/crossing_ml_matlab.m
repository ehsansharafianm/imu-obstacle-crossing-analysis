    '(soft vote); features never mixed. **level** = minus own level-walk median, lengths / leg length; **self** = each participant scaled to their own ' ...
    'median / IQR over the analysed crossings (no labels; assumes the crossings span a mix of obstacles, guaranteed here - optimistic, see 3.E).']);
