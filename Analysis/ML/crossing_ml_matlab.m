%  SETTINGS (crossing_ml_settings.py)
%% ========================================================================
function [L, R] = secSettings(D, CFG, L, R)
T = D.T;  F = D.feats;  S = D.S;
LEAD = mlTools.getSet(S, 'lead only');  TRAIL = mlTools.getSet(S, 'trail only');
obs = T.is_level == 0 & T.(CFG.include) == 1;
y = T.height_class(obs);  g = T.participant_id(obs);  P = unique(g)';
XN.level = D.Xcal(obs, :);  XN.self = mlTools.selfnorm(D.Xraw(obs, :), g);
jl = ci(F, LEAD);  jt = ci(F, TRAIL);
cand = {'logreg C=0.03', mlTools.spec('logreg', 'C', 0.03); 'logreg C=0.1', mlTools.spec('logreg', 'C', 0.1); ...
        'logreg C=0.3', mlTools.spec('logreg', 'C', 0.3); 'logreg C=1', mlTools.spec('logreg', 'C', 1); ...
        'forest', mlTools.spec('forest', 'nTrees', 300)};
L = addl(L, '# Part 4. Finding a good setting, and re-checking the conclusions (Python: `ml_settings.md`)');
L = addl(L, '');
% ---- 1. nested selection ----
norms = {'level', 'self'};
chosen = cell(numel(P), 1);  inner = zeros(numel(P), 1);  predC = cell(numel(P), 1);
parfor k = 1:numel(P)
    p = P(k);  tr = g ~= p;  best = [];  bs = -inf;
    for n = 1:2
        Xn = XN.(norms{n}); %#ok<PFBNS>
        for m = 1:size(cand, 1)
            [PL, lab] = mlTools.lopo(cand{m,2}, Xn(tr, jl), y(tr), g(tr)); %#ok<PFBNS>
            PT = mlTools.lopo(cand{m,2}, Xn(tr, jt), y(tr), g(tr));
            Ps = {PL, PT, (PL + PT) / 2};
            for l = 1:3
                sc = mlTools.balAcc(y(tr), mlTools.argmaxLab(Ps{l}, lab));
                if sc > bs, bs = sc; best = [n m l]; end
            end
        end
    end
    Xn = XN.(norms{best(1)});  Pf = 0;  cnt = 0;
    for l = 1:2
        if best(3) == l || best(3) == 3
            jj = ternary(l == 1, jl, jt);
            M = mlTools.fitPipe(cand{best(2),2}, Xn(tr, jj), y(tr));
            Pf = Pf + mlTools.predictPipe(M, Xn(~tr, jj));  cnt = cnt + 1;
        end
    end
    predC{k} = mlTools.argmaxLab(Pf / cnt, M.classes);
    chosen{k} = sprintf('%s, %s, %s', norms{best(1)}, cand{best(2),1}, ternary(best(3) == 1, 'lead', ternary(best(3) == 2, 'trail', 'fusion')));
    inner(k) = bs;
end
pred = cell(numel(y), 1);
for k = 1:numel(P), pred(g == P(k)) = predC{k}; end
ba = mlTools.balAcc(y, pred);  c = mlTools.bootCI(y, pred, g, [], CFG.nBoot);
r = newRow('settings');  r.task = 'height';  r.features = 'nested selection';  r.normalization = 'chosen in inner CV';  r.model = 'chosen';
r.limb = 'chosen';  r.n_rows = numel(y);  r.chance = 1/3;  r.bal_acc = ba;  r.ci_lo = c(1);  r.ci_hi = c(2);  r.acc = accPer(y, pred, g);
R = [R, r];
L = addl(L, '## 4.1 Nested setting selection (honest accuracy for "the best setting")');
L = addl(L, '');
L = addl(L, ['Candidates: normalization {level, self} x model {logistic C = 0.03 / 0.1 / 0.3 / 1, random forest (300 trees)} x limb {lead, trail, fusion} = 30. ' ...
    'For each unseen participant the setting with the best inner leave-one-participant-out accuracy on the other 9 is chosen, refitted on those 9 and applied to the unseen one.']);
L = addl(L, '');
L = addl(L, '**Nested accuracy: %.1f%% (95%% CI %.0f-%.0f).**', 100*ba, 100*c(1), 100*c(2));
L = addl(L, '');
L = addl(L, '| unseen participant | chosen setting | inner accuracy | accuracy on the unseen participant |');
L = addl(L, '|---|---|---|---|');
for k = 1:numel(P)
    L = addl(L, '| %d | %s | %.1f%% | %.0f%% |', P(k), chosen{k}, 100*inner(k), 100*mean(strcmp(predC{k}, y(g == P(k)))));
end
[u, ~, j] = unique(chosen);  cnt = accumarray(j, 1);  [~, o] = sort(-cnt);
L = addl(L, '');
L = addl(L, 'Chosen settings: %s.', strjoin(arrayfun(@(i) sprintf('%s (%d/10)', u{i}, cnt(i)), o', 'UniformOutput', false), '; '));
L = addl(L, '');
fprintf('  nested selection: %.1f%%\n', 100*ba);
% ---- 2. segment ranking, self ----
names = [{'lead only', 'trail only'}, setdiff({S.name}, {'all', 'lead only', 'trail only'}, 'stable')];
SR = struct('model', {}, 'features', {}, 'n', {}, 'bal', {}, 'lo', {}, 'hi', {});
for m = [2 5]
    for i = 1:numel(names)
        cols = mlTools.getSet(S, names{i});
        [Pr, lab] = mlTools.lopo(cand{m,2}, XN.self(:, ci(F, cols)), y, g);
        pr = mlTools.argmaxLab(Pr, lab);  c = mlTools.bootCI(y, pr, g, [], CFG.nBoot);
        SR(end+1) = struct('model', cand{m,1}, 'features', names{i}, 'n', numel(cols), 'bal', mlTools.balAcc(y, pr), 'lo', c(1), 'hi', c(2)); %#ok<AGROW>
    end
end
L = addl(L, '## 4.2 Which segment and limb, with the self normalization');
L = addl(L, '');
L = addl(L, '| features | n feat | logistic (C = 0.1) | random forest |');
L = addl(L, '|---|---|---|---|');
for i = 1:numel(names)
    a = SR(strcmp({SR.features}, names{i}) & strcmp({SR.model}, 'logreg C=0.1'));
    f = SR(strcmp({SR.features}, names{i}) & strcmp({SR.model}, 'forest'));
    L = addl(L, '| %s | %d | %.1f%% (%.0f-%.0f) | %.1f%% (%.0f-%.0f) |', names{i}, a.n, 100*a.bal, 100*a.lo, 100*a.hi, 100*f.bal, 100*f.lo, 100*f.hi);
end
L = addl(L, '');
% ---- 3. time-resolved, level vs self ----
Cv = mlTools.loadCurves(D.root, T.crossing_id);
TR = timeResolved(D, CFG, Cv, obs, {'level', 'self'}, {'logreg', 'forest'}, 500);
L = addl(L, '## 4.3 When is height known? (lead limb data up to x %% of its swing)');
L = addl(L, '');
L = addl(L, '| data up to | ms before the trailing lift-off | level, logistic | level, forest | self, logistic | self, forest |');
L = addl(L, '|---|---|---|---|---|---|');
for i = 1:height(TR)
    L = addl(L, '| %d%% | %.0f | %.1f%% | %.1f%% | %.1f%% | %.1f%% |', TR.cut(i), TR.ms(i), 100*TR.level_logreg(i), 100*TR.level_forest(i), 100*TR.self_logreg(i), 100*TR.self_forest(i));
end
L = addl(L, '');
% ---- 4. causal ----
L = addl(L, '## 4.4 Self normalization learned during use (causal)');
L = addl(L, '');
L = addl(L, ['Each crossing normalized with the median / IQR of the same person''s EARLIER crossings only (walking order), once n earlier crossings exist; ' ...
    'earlier crossings not scored. Blocked order here makes the early history cover few obstacles (conservative).']);
L = addl(L, '');
L = addl(L, '| model | limbs | after 5 crossings | after 10 | after 15 | after 20 |');
L = addl(L, '|---|---|---|---|---|---|');
ord = T.trial_order(obs);  Xr = D.Xraw(obs, :);
for m = [2 5]
    for lim = {'lead', 'fusion'}
        js = ternary(strcmp(lim{1}, 'lead'), {jl}, {jl, jt});
        cells = arrayfun(@(nm) causalCell(cand{m,2}, XN.self, Xr, js, y, g, ord, nm), [5 10 15 20], 'UniformOutput', false);
        L = addl(L, '| %s | %s | %s |', cand{m,1}, lim{1}, strjoin(cells, ' | '));
    end
end
L = addl(L, '');
% ---- 5. per participant ----
L = addl(L, '## 4.5 Per participant (accuracy on each unseen participant)');
L = addl(L, '');
L = addl(L, ['| setting | ' strjoin(arrayfun(@num2str, P, 'UniformOutput', false), ' | ') ' | overall |']);
L = addl(L, ['|---|' repmat('---|', 1, numel(P) + 1)]);
sets5 = {'level', 2, 'lead'; 'self', 2, 'lead'; 'self', 5, 'lead'; 'self', 5, 'fusion'};
for i = 1:size(sets5, 1)
    Xn = XN.(sets5{i,1});
    [PL, lab] = mlTools.lopo(cand{sets5{i,2},2}, Xn(:, jl), y, g);
    if strcmp(sets5{i,3}, 'fusion'), PL = (PL + mlTools.lopo(cand{sets5{i,2},2}, Xn(:, jt), y, g)) / 2; end
    pr = mlTools.argmaxLab(PL, lab);  a = accPer(y, pr, g);
    L = addl(L, '| %s, %s, %s | %s | %.1f%% |', sets5{i,1}, cand{sets5{i,2},1}, sets5{i,3}, ...
        strjoin(arrayfun(@(v) sprintf('%.0f%%', 100*v), a(~isnan(a)), 'UniformOutput', false), ' | '), 100*mlTools.balAcc(y, pr));
end
L = addl(L, '');
mlTools.figures(D.out, 'settings', struct('SR', SR, 'TR', TR));
end

function s = causalCell(spec, Xself, Xr, js, y, g, ord, nmin)
P = unique(g)';  yt = cell(numel(P), 1);  yp = cell(numel(P), 1);
parfor k = 1:numel(P)
    p = P(k);  tr = g ~= p;  ip = find(g == p);  [~, o] = sort(ord(ip));  ip = ip(o); %#ok<PFBNS>
    Pf = 0;
    for x = 1:numel(js)
        M = mlTools.fitPipe(spec, Xself(tr, js{x}), y(tr)); %#ok<PFBNS>
        Xp = Xr(ip, js{x});  Z = nan(numel(ip) - nmin, numel(js{x})); %#ok<PFBNS>
        for j = nmin + 1:numel(ip)
            [med, iqr] = mlTools.medIqr(Xp(1:j-1, :));
            Z(j - nmin, :) = (Xp(j, :) - med) ./ iqr;
        end
        Pf = Pf + mlTools.predictPipe(M, Z) / numel(js);
        cls = M.classes;
    end
    yp{k} = mlTools.argmaxLab(Pf, cls);  yt{k} = y(ip(nmin+1:end));
end
yt = vertcat(yt{:});  yp = vertcat(yp{:});
s = sprintf('%.1f%% (n=%d)', 100 * mlTools.balAcc(yt, yp), numel(yt));
end

%% ========================================================================
%  COMPARISON WITH PYTHON
%% ========================================================================
function L = secCompare(D, R, L)
pyDir = fullfile(D.root, 'Results', 'ML Models');
L = addl(L, '# Part 5. MATLAB vs Python');
L = addl(L, '');
L = addl(L, 'Balanced accuracy of the same analyses in both implementations (Python files in `Results/ML Models/`).');
L = addl(L, '');
L = addl(L, '| analysis | task | features / limb | norm | model | Python | MATLAB | MATLAB - Python |');
L = addl(L, '|---|---|---|---|---|---|---|---|');
dd = struct('model', {}, 'd', {});
f = fullfile(pyDir, 'ml_results.csv');
if isfile(f)
    Pm = readtable(f, 'TextType', 'char', 'Delimiter', ',');
    M = R(strcmp({R.analysis}, 'main'));
    for r = M
        i = find(strcmp(Pm.task, r.task) & strcmp(Pm.features, r.features) & strcmp(Pm.normalization, r.normalization) & ...
            strcmp(Pm.model, r.model) & strcmp(Pm.rows, r.rows), 1);
        if isempty(i), continue; end
        dd(end+1) = struct('model', r.model, 'd', r.bal_acc - Pm.bal_acc(i)); %#ok<AGROW>
        if any(strcmp(r.features, {'all', 'lead only', 'trail only'}))
            lab = r.features;  if ~strcmp(r.rows, 'include_ml'), lab = [lab ' (' r.rows ')']; end %#ok<AGROW>
            L = addl(L, '| main | %s | %s | %s | %s | %.1f%% | %.1f%% | %+.1f |', r.task, lab, r.normalization, r.model, 100*Pm.bal_acc(i), 100*r.bal_acc, 100*dd(end).d);
        end
    end
end
f = fullfile(pyDir, 'ml_limbs_results.csv');
if isfile(f)
    Pl = readtable(f, 'TextType', 'char', 'Delimiter', ',');
    A = R(strcmp({R.analysis}, 'limbs'));
    for r = A
        i = find(strcmp(Pl.block, r.block) & strcmp(Pl.target, r.task) & strcmp(Pl.norm, r.normalization) & strcmp(Pl.model, r.model) & strcmp(Pl.limb, r.limb), 1);
        if isempty(i), continue; end
        dd(end+1) = struct('model', r.model, 'd', r.bal_acc - Pl.bal_acc(i)); %#ok<AGROW>
        L = addl(L, '| limbs %s | %s | %s | %s | %s | %.1f%% | %.1f%% | %+.1f |', r.block, r.task, r.limb, r.normalization, r.model, 100*Pl.bal_acc(i), 100*r.bal_acc, 100*dd(end).d);
    end
end
f = fullfile(pyDir, 'ml_settings.md');
n = R(strcmp({R.analysis}, 'settings'));
if isfile(f) && ~isempty(n)
    t = regexp(fileread(f), 'Nested accuracy: ([\d.]+)%', 'tokens', 'once');
    if ~isempty(t), L = addl(L, '| settings | height | nested selection | chosen | chosen | %s%% | %.1f%% | %+.1f |', t{1}, 100*n.bal_acc, 100*n.bal_acc - str2double(t{1})); end
end
L = addl(L, '');
for m = {'logreg', 'forest'}
    v = [dd(strcmp({dd.model}, m{1})).d];
    if ~isempty(v)
        L = addl(L, '- %s: %d matched results, mean |difference| %.1f points, max %.1f points.', m{1}, numel(v), 100*mean(abs(v)), 100*max(abs(v)));
    end
end
L = addl(L, '');
L = addl(L, ['Logistic regression is deterministic and fits the same objective, so it reproduces Python up to optimizer tolerance. ' ...
    'Random-forest results differ by a few points because TreeBagger and scikit-learn grow different trees from different random streams; ' ...
    'bootstrap intervals, permutation p-values and random-draw analyses differ slightly for the same reason.']);
L = addl(L, '');
L = addl(L, 'Figures: fig_feature_sets, fig_confusion, fig_participants, fig_cueing_time, fig_learning_curve, fig_limbs, fig_settings (PNG, drawn by crossing_ml_figures.m).');
end

%% ========================================================================
%  SMALL HELPERS
%% ========================================================================
function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function j = ci(feats, cols)
[~, j] = ismember(cols, feats);
end

function r = newRow(analysis)
r = struct('analysis', analysis, 'block', '', 'task', '', 'features', '', 'normalization', '', 'model', '', 'limb', '', ...
    'rows', 'include_ml', 'n_features', NaN, 'n_rows', NaN, 'chance', NaN, 'bal_acc', NaN, 'ci_lo', NaN, 'ci_hi', NaN, ...
    'macro_f1', NaN, 'perm_p', NaN, 'null95', NaN, 'acc', nan(1, 10));
end

function a = accPer(y, pred, g)
P = 101:110;  a = nan(1, numel(P));
for k = 1:numel(P)
    m = g == P(k);
    if any(m), a(k) = mean(strcmp(pred(m), y(m))); end
end
end

function cm = confmat(y, pred, lab)
cm = zeros(numel(lab), numel(lab));
for i = 1:numel(lab)
    for j = 1:numel(lab), cm(i,j) = sum(strcmp(y, lab{i}) & strcmp(pred, lab{j})); end
end
end

function s = pstr(p)
if isnan(p), s = '-'; elseif p < 0.001, s = '< 0.001'; else, s = sprintf('%.3f', p); end
end

function s = pctOr(x)
if isnan(x), s = '-'; else, s = sprintf('%.1f%%', 100 * x); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end

function writeResults(f, R)
if isempty(R), return; end
A = vertcat(R.acc);
R = rmfield(R, 'acc');
T = struct2table(R(:));
for k = 1:10, T.(sprintf('acc_%d', 100 + k)) = A(:, k); end
writetable(T, f);
end
