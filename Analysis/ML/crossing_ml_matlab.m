           '6 obstacles', cellfun(@(c) ['W' c(1) 'H' c(2)], code, 'UniformOutput', false)};
Xsel = @(cols, norm, rows) normX(D, cols, norm, rows);
mdl = {'logreg', mlTools.spec('logreg'); 'forest', mlTools.spec('forest')};
