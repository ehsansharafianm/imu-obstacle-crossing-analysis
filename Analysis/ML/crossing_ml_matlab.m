            L = addl(L, '| %s | %.0f%% | %s | %s | %s |', targets{t,1}, 100*ch, norm{1}, mdl{m,1}, strjoin(cells, ' | '));
            fprintf('  limbs A %s %s %s done\n', targets{t,1}, norm{1}, mdl{m,1});
        end
    end
end
L = addl(L, '');
L = addl(L, 'Cells: balanced accuracy (95%% CI), unseen participant. Permutation tests (logistic, labels shuffled within participant, %d permutations; fusion refits both limb models on every permutation):', CFG.nPermLimb);
