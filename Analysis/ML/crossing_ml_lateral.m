function crossing_ml_lateral()
% CROSSING_ML_LATERAL  Is obstacle WIDTH visible in the out-of-plane (side-to-side) motion?
%
% All earlier models used the sagittal (forward / backward) tilt of the Dot segments and the foot
% height / progression. A wider obstacle might instead change the side-to-side movement (hip
% hiking, circumduction, foot turned out). For every crossing and limb (swing = the step-4 toe-off
% -> heel-strike of the crossing stride):
%   * frontal-plane tilt (Dot euler Y) and twist / heading (Dot euler Z, unwrapped) of the thigh,
%     shank and foot: range in the swing, largest deviation from the toe-off value, signed mean
%     deviation (sign flipped for the right leg so + = outward / abduction-like for both legs);
%   * the foot's sideways path from the ZHC trajectory: largest outward and inward excursion
%     from the straight line between the stride's ZVPs, the excursion at the foot apex, and the
%     horizontal path length relative to the stride length.
% Then: within-person x height effect size of width (eta^2), W2 - W1 differences, and width (and
% height) classification, leave-one-participant-out.
% Outputs -> Results/ML Models/MATLAB/ml_lateral_matlab.md, fig_lateral.png

here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;
[XLat, names] = lateralFeatures(root, T);
obs = T.is_level == 0 & T.include_ml == 1;  d = T(obs, :);  X = XLat(obs, :);
g = d.participant_id;  P = unique(g)';  y = d.height_class;  yw = d.width_class;
L = {};
L = addl(L, '# Is obstacle width visible in the side-to-side motion? (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_lateral.m` on %s._', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings. %d new out-of-plane features per crossing (lead + trail): frontal tilt and twist of the thigh, shank and foot Dots ' ...
    '(range, largest deviation from toe-off, signed mean deviation with + = outward for both legs) and the foot''s sideways path from the ZHC ' ...
    '(outward / inward excursion, excursion at the apex, path length / stride length).'], nnz(obs), numel(names));
L = addl(L, '');
% ---- effect sizes ----
key = strcat(cellstr(num2str(g)), y);  [u, ~, jj] = unique(key);
ew = nan(1, numel(names));  dd = nan(numel(P), numel(names));  eh = ew;
for k = 1:numel(names)
    v = X(:, k);  vc = v;
    for q = 1:numel(u), m = jj == q; vc(m) = v(m) - mean(v(m), 'omitnan'); end
    ew(k) = eta2(vc, yw);
    vh = v;  for p = P, m = g == p; vh(m) = v(m) - mean(v(m), 'omitnan'); end
    eh(k) = eta2(vh, y);
    for a = 1:numel(P)
        dh = nan(1, 3);  hc = {'H1','H2','H3'};
        for q = 1:3
            m = g == P(a) & strcmp(y, hc{q});
            dh(q) = mean(v(m & strcmp(yw, 'W2')), 'omitnan') - mean(v(m & strcmp(yw, 'W1')), 'omitnan');
        end
        dd(a, k) = mean(dh, 'omitnan');
    end
end
% sagittal reference: best width eta^2 among the original Dot features
ewS = nan(1, numel(F));  Xs0 = d{:, F};
for k = 1:numel(F)
    v = Xs0(:, k);  vc = v;
    for q = 1:numel(u), m = jj == q; vc(m) = v(m) - mean(v(m), 'omitnan'); end
    ewS(k) = eta2(vc, yw);
end
[~, o] = sort(ew, 'descend', 'MissingPlacement', 'last');
L = addl(L, '## 1. Effect of width on each out-of-plane feature');
L = addl(L, '');
L = addl(L, ['eta^2 width = share of the within-person x height variance explained by width; W2 - W1 = mean difference per participant (within height), ' ...
    'median over participants. For reference, the largest width eta^2 among the %d original (sagittal) Dot features is %.2f (`%s`).'], numel(F), max(ewS), F{find(ewS == max(ewS), 1)});
L = addl(L, '');
L = addl(L, '| feature | eta^2 width | W2 - W1 (median) | participants > 0 | eta^2 height (within person) |');
L = addl(L, '|---|---|---|---|---|');
for k = o(1:min(15, numel(o)))
    L = addl(L, '| `%s` | %.2f | %+.2f | %d / %d | %.2f |', names{k}, ew(k), median(dd(:,k), 'omitnan'), sum(dd(:,k) > 0), sum(isfinite(dd(:,k))), eh(k));
end
L = addl(L, '');
% ---- classification ----
lead = startsWith(names, 'lead_');  trail = startsWith(names, 'trail_');
Xn = mlTools.selfnorm(X, g);
leadS = F(startsWith(F, 'lead_') | ismember(F, {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'}));
trailS = F(startsWith(F, 'trail_'));
C = mlTools.loadCurvesBoth(root, T.crossing_id);  SHl = mlTools.shapeFeats(C.lead);  SHt = mlTools.shapeFeats(C.trail);
SL = mlTools.selfnorm([d{:, leadS}, SHl(obs,:)], g);  ST = mlTools.selfnorm([d{:, trailS}, SHt(obs,:)], g);
sets = {'out-of-plane only', Xn(:, lead), Xn(:, trail);
        'original sagittal + shape', SL, ST;
        'sagittal + shape + out-of-plane', [SL Xn(:, lead)], [ST Xn(:, trail)]};
L = addl(L, '## 2. Width and height classification (person scaling, leave-one-participant-out)');
L = addl(L, '');
L = addl(L, '| target | features | model | lead | trail | fusion |');
L = addl(L, '|---|---|---|---|---|---|');
RES = struct('t', {}, 's', {}, 'm', {}, 'b', {});
for tg = {'width', yw; 'height', y}'
    for s = 1:size(sets, 1)
        for mo = {'logistic', mlTools.spec('logreg'); 'forest', mlTools.spec('forest', 'nTrees', 300)}'
            [PLr, cl] = mlTools.lopo(mo{2}, sets{s,2}, tg{2}, g);  PTr = mlTools.lopo(mo{2}, sets{s,3}, tg{2}, g);
            Ps = {PLr, PTr, (PLr + PTr) / 2};  c = cell(1, 3);
            for k = 1:3
                pr = mlTools.argmaxLab(Ps{k}, cl);  b = mlTools.balAcc(tg{2}, pr);  ci = mlTools.bootCI(tg{2}, pr, g, [], 1000);
                c{k} = sprintf('%.1f%% (%.0f-%.0f)', 100*b, 100*ci(1), 100*ci(2));
            end
            RES(end+1) = struct('t', tg{1}, 's', sets{s,1}, 'm', mo{1}, 'b', mlTools.balAcc(tg{2}, mlTools.argmaxLab(Ps{3}, cl))); %#ok<AGROW>
            L = addl(L, '| %s | %s | %s | %s |', tg{1}, sets{s,1}, mo{1}, strjoin(c, ' | '));
        end
    end
end
w = RES(strcmp({RES.t}, 'width'));  [bw, iw] = max([w.b]);
L = addl(L, '');
L = addl(L, ['**Reading.** The side-to-side motion carries %s width information (largest eta^2 %.2f vs %.2f for the sagittal features; best width ' ...
    'model %.1f%% with %s, %s, chance 50%%). Together with the camera result (foot placement 57%%) this confirms that, within 5-15 cm, people do not ' ...
    'cross a wider obstacle differently enough to be recognised - the width limit is behavioural, not a missing sensor axis.'], ...
    ternary(max(ew) < 0.1, 'almost no', 'some'), max(ew), max(ewS), 100 * bw, w(iw).s, w(iw).m);
L = addl(L, '');
writeLines(fullfile(out, 'ml_lateral_matlab.md'), L);
mlTools.figures(out, 'lateral', struct('names', {names}, 'ew', ew, 'ewS', ewS, 'F', {F}));
fprintf('Wrote %s\n', out);
end

%% ========================================================================
function [X, names] = lateralFeatures(root, T)
segs = {'Thigh', 'Shank', 'Foot'};
base = {};
for s = segs
    for a = {'fr', 'yaw'}
        base = [base, strcat(lower(s{1}), '_', a{1}, {'_range', '_maxdev', '_meandev'})]; %#ok<AGROW>
    end
end
base = [base, {'foot_lat_out', 'foot_lat_in', 'foot_lat_apex', 'foot_path_ratio'}];
names = [strcat('lead_', base), strcat('trail_', base)];
X = nan(height(T), numel(names));
for tn = unique(T.participant_id)'
    b = fullfile(root, 'Results', 'Parameters Output', sprintf('Test %d', tn));
    dA = load(fullfile(b, sprintf('AllData_Test%d.mat', tn)), 'Data');  Dt = dA.Data;
    dS = load(fullfile(b, sprintf('SegmentedParams_Test%d.mat', tn)), 'Seg');  Sg = dS.Seg;
    t = Dt.time(:);  lab = {Dt.imu.label};
    E = struct();
    for sd = 'LR'
        w = ternary(sd == 'L', 'Left', 'Right');
        for s = segs
            k = find(strcmp(lab, sprintf('%s %s (Dot)', w, s{1})), 1);
            if isempty(k), E.(sd).(s{1}) = []; continue; end
            e = Dt.imu(k).euler_ZXY_deg;
            E.(sd).(s{1}) = [e(:,3), rad2deg(unwrap(deg2rad(e(:,1))))];   % [frontal tilt, unwrapped heading]
        end
    end
    rows = find(T.participant_id == tn);
    for r = rows'
        ll = T.leading_limb{r};  if isempty(ll), continue; end
        sides = {ll, ternary(ll == 'L', 'R', 'L')};
        for li = 1:2
            sd = sides{li};  sgn = ternary(sd == 'L', 1, -1);
            if li == 1, t0 = T.lead_toeoff_t(r); t1 = T.lead_landing_t(r); else, t0 = T.trail_toeoff_t(r); t1 = T.trail_landing_t(r); end
            if ~isfinite(t0) || ~isfinite(t1) || t1 <= t0, continue; end
            [~, i0] = min(abs(t - t0));  [~, i1] = min(abs(t - t1));
            f = nan(1, numel(base));  c = 0;
            for s = segs
                A = E.(sd).(s{1});
                for a = 1:2
                    if isempty(A), c = c + 3; continue; end
                    v = A(i0:i1, a) - A(i0, a);
                    f(c+1) = max(v) - min(v);  f(c+2) = max(abs(v));  f(c+3) = sgn * mean(v);  c = c + 3;
                end
            end
            % sideways foot path from the ZHC of the stride that contains the toe-off
            tz = Sg.zhc.(sd).tZvp;  z = Sg.(['zvp' sd]);  PT = Sg.zhc.(sd).posTime;
            cc = find(tz(1:end-1) <= t0 & t0 < tz(2:end), 1);
            if ~isempty(cc) && cc <= size(PT, 3)
                P = PT(1:min(z(cc+1) - z(cc) + 1, size(PT,1)), :, cc);
                if all(isfinite(P(:))) && size(P, 1) > 5
                    uu = P(end,1:2) - P(1,1:2);  sl = norm(uu);
                    if sl > 0
                        uu = uu / sl;  vv = [-uu(2) uu(1)];
                        lat = sgn * (P(:,1:2) - P(1,1:2)) * vv' * 1000;        % + = outward
                        [~, ip] = max(P(:,3));
                        f(c+1) = max(lat);  f(c+2) = -min(lat);  f(c+3) = lat(ip);
                        f(c+4) = sum(vecnorm(diff(P(:,1:2)), 2, 2)) / sl;
                    end
                end
            end
            off = (li - 1) * numel(base);
            X(r, off + (1:numel(base))) = f;
        end
    end
    fprintf('  test %d done\n', tn);
end
end

function e = eta2(v, lab)
ok = isfinite(v);  v = v(ok);  l = lab(ok);  u = unique(l);  m = mean(v);  ssb = 0;
for k = 1:numel(u), vk = v(strcmp(l, u{k})); ssb = ssb + numel(vk) * (mean(vk) - m)^2; end
e = ssb / sum((v - m).^2);
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
