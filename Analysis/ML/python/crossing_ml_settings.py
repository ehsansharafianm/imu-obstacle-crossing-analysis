"""Finding a good setting honestly, and re-checking the conclusions at the better setting.

  1. Nested setting selection (height). Candidate settings = normalization (level / self)
     x model (logistic C = 0.03, 0.1, 0.3, 1 / random forest) x limb (lead / trail / fusion).
     For each unseen participant, the setting is chosen by an INNER leave-one-participant-out
     on the 9 training participants only, then refitted and applied to the unseen one. The
     outer accuracy is therefore not inflated by picking the best of many settings.
  2. Segment / limb ranking with the self normalization (does the leading foot still win?).
  3. Time-resolved prediction with the self normalization (is the information still there by
     the lead foot apex?).
  4. Causal self normalization: each crossing normalized with the person's EARLIER crossings
     only (as a device learning during use; blocked order here makes this conservative).
  5. Per-participant accuracy for the main settings.

Rules as crossing_ml.py; descriptive only. Writes Results/ML Models/ml_settings.md, fig_settings.png.
"""
from __future__ import annotations

import sys
from collections import Counter
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import balanced_accuracy_score
from sklearn.model_selection import LeaveOneGroupOut
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, str(Path(__file__).resolve().parent))
import crossing_ml as M                                                  # noqa: E402
from crossing_ml_followup import (CURVES, CUTS, PRE_SWING, boot_ci,      # noqa: E402
                                  calibrate_frame, cut_features)
from crossing_ml_limbs import selfnorm                                   # noqa: E402

import matplotlib.pyplot as plt                                          # noqa: E402


def logreg(C):
    return lambda: make_pipeline(SimpleImputer(strategy="median", keep_empty_features=True), StandardScaler(),
                                 LogisticRegression(C=C, max_iter=5000))


def forest(n_jobs=-1):
    return lambda: make_pipeline(SimpleImputer(strategy="median", keep_empty_features=True),
                                 RandomForestClassifier(n_estimators=300, min_samples_leaf=2, class_weight="balanced",
                                                        random_state=M.SEED, n_jobs=n_jobs))


CANDIDATE_MODELS = {"logreg C=0.03": 0.03, "logreg C=0.1": 0.1, "logreg C=0.3": 0.3, "logreg C=1": 1.0, "forest": None}


def maker(name, n_jobs=-1):
    c = CANDIDATE_MODELS[name]
    return forest(n_jobs) if c is None else logreg(c)


def lopo_proba(make, X, y, g):
    labels = np.unique(y)
    P = np.zeros((len(y), len(labels)))
    for tr, te in LeaveOneGroupOut().split(X, y, g):
        m = make()
        m.fit(X[tr], y[tr])
        P[te] = m.predict_proba(X[te])
    return labels, P


def main():
    df, feats, units = M.load()
    sets = M.feature_sets(feats)
    LEAD, TRAIL = sets["lead only"], sets["trail only"]
    obs = ((df.is_level == 0) & (df[M.INCLUDE] == 1)).to_numpy()
    D = df.loc[obs].reset_index(drop=True)
    g = D.participant_id.to_numpy()
    y = D.height_class.astype(str).to_numpy()
    P_ = np.unique(g)
    Xcal = M.calibrate(df, feats, units).loc[obs].reset_index(drop=True)
    Xself = selfnorm(D[feats], g)
    XN = {"level": Xcal, "self": Xself}
    out = []
    W = out.append
    W("# Finding a good setting, and re-checking the conclusions\n")
    W(f"_Generated by `Analysis/ML/python/crossing_ml_settings.py` on {datetime.now():%Y-%m-%d %H:%M}._\n")
    W(f"Height (H1/H2/H3, chance 33%), {obs.sum()} crossings, 10 participants, every result on an unseen participant. "
      "Normalizations: *level* = minus own level-walk median, lengths / leg length; *self* = each person scaled to their own "
      "median / IQR over their crossings (no labels; needs ~10-15 mixed crossings, see `ml_limbs.md` E). 95% CI = participant bootstrap.\n")

    # ================= 1. nested setting selection =================
    def outer(p):
        tr = g != p
        best, scores = None, {}
        for norm in ("level", "self"):
            for mname in CANDIDATE_MODELS:
                Ps = {}
                for limb, cols in (("lead", LEAD), ("trail", TRAIL)):
                    lab, Ps[limb] = lopo_proba(maker(mname, 1), XN[norm].loc[tr, cols].to_numpy(float), y[tr], g[tr])
                Ps["fusion"] = (Ps["lead"] + Ps["trail"]) / 2
                for limb, P in Ps.items():
                    s = balanced_accuracy_score(y[tr], lab[np.argmax(P, axis=1)])
                    scores[(norm, mname, limb)] = s
                    if best is None or s > scores[best]:
                        best = (norm, mname, limb)
        norm, mname, limb = best
        Pt = []
        for lb, cols in (("lead", LEAD), ("trail", TRAIL)):
            if limb in (lb, "fusion"):
                m = maker(mname, 1)()
                m.fit(XN[norm].loc[tr, cols].to_numpy(float), y[tr])
                Pt.append(m.predict_proba(XN[norm].loc[~tr, cols].to_numpy(float)))
                lab = m.classes_
        pred = lab[np.argmax(np.mean(Pt, axis=0), axis=1)]
        return p, best, scores[best], pred

    print("nested selection ...", flush=True)
    R = Parallel(n_jobs=-1)(delayed(outer)(p) for p in P_)
    pred = np.empty_like(y)
    for p, best, inner, pr in R:
        pred[g == p] = pr
    ba = balanced_accuracy_score(y, pred)
    lo, hi = boot_ci(y, pred, g)
    W("## 1. Nested setting selection (honest accuracy for 'the best setting')\n")
    W("Candidates: normalization {level, self} x model {logistic C = 0.03 / 0.1 / 0.3 / 1, random forest (300 trees)} x limb "
      "{lead, trail, fusion} = 30 settings. For each unseen participant the setting with the best inner leave-one-participant-out "
      "accuracy on the other 9 is chosen, refitted on those 9, and applied to the unseen one.\n")
    W(f"**Nested accuracy: {ba*100:.1f}% (95% CI {lo*100:.0f}-{hi*100:.0f}).**\n")
    W("| unseen participant | chosen setting | inner accuracy | accuracy on the unseen participant |\n|---|---|---|---|")
    for p, best, inner, pr in R:
        W(f"| {p} | {best[0]}, {best[1]}, {best[2]} | {inner*100:.1f}% | {np.mean(pr == y[g == p])*100:.0f}% |")
    cnt = Counter(b for _, b, _, _ in R)
    W("\nChosen settings: " + "; ".join(f"{k[0]}, {k[1]}, {k[2]} ({v}/10)" for k, v in cnt.most_common()) + ".\n")

    # ================= 2. segment / limb ranking with self normalization =================
    print("segment ranking ...", flush=True)
    groups = [k for k in sets if k not in ("all", "lead only", "trail only")]
    seg_rows = []
    for mname in ("logreg C=0.1", "forest"):
        for k in ["lead only", "trail only"] + groups:
            cols = sets[k]
            lab, P = lopo_proba(maker(mname), Xself[cols].to_numpy(float), y, g)
            pr = lab[np.argmax(P, axis=1)]
            b = balanced_accuracy_score(y, pr)
            l_, h_ = boot_ci(y, pr, g)
            seg_rows.append({"model": mname, "features": k, "n": len(cols), "bal_acc": b, "lo": l_, "hi": h_})
    S = pd.DataFrame(seg_rows)
    W("## 2. Which segment and limb, with the self normalization\n")
    W("| features | n feat | logistic (C = 0.1) | random forest |\n|---|---|---|---|")
    for k in ["lead only", "trail only"] + groups:
        a = S[(S.features == k) & (S.model == "logreg C=0.1")].iloc[0]
        f = S[(S.features == k) & (S.model == "forest")].iloc[0]
        W(f"| {k} | {a.n} | {a.bal_acc*100:.1f}% ({a.lo*100:.0f}-{a.hi*100:.0f}) | {f.bal_acc*100:.1f}% ({f.lo*100:.0f}-{f.hi*100:.0f}) |")
    W("")

    # ================= 3. time-resolved with self normalization =================
    print("time-resolved ...", flush=True)
    C = pd.read_csv(CURVES).set_index("crossing_id").reindex(df.crossing_id)
    C.index = df.index
    TR = []
    ref = (D.trail_toeoff_t).to_numpy()
    for cut in CUTS:
        F = pd.concat([cut_features(C, cut), df[PRE_SWING]], axis=1)
        mm = [c for c in F.columns if c.startswith(("zhc_h", "zhc_x"))] + ["stride_len_app1", "stride_len_app2"]
        Fl = calibrate_frame(df, F, mm).loc[obs].reset_index(drop=True)
        Fs = selfnorm(F.loc[obs].reset_index(drop=True), g)
        t_cut = (D.lead_toeoff_t + cut / 100 * D.lead_swing_time).to_numpy()
        row = {"cut": cut, "ms": np.nanmedian((ref - t_cut) * 1000)}
        for norm, X in (("level", Fl), ("self", Fs)):
            for mname in ("logreg C=0.1", "forest"):
                lab, P = lopo_proba(maker(mname), X.to_numpy(float), y, g)
                pr = lab[np.argmax(P, axis=1)]
                row[f"{norm}|{mname}"] = balanced_accuracy_score(y, pr)
                l_, h_ = boot_ci(y, pr, g, n=500)
                row[f"{norm}|{mname}|lo"], row[f"{norm}|{mname}|hi"] = l_, h_
        TR.append(row)
    TR = pd.DataFrame(TR)
    W("## 3. When is height known? (lead limb data up to x % of its swing)\n")
    W("Same cropped-curve features as `ml_followup.md` section 2. Median lead foot apex ~54% of the lead swing.\n")
    W("| data up to | ms before trail toe-off | level, logistic | level, forest | self, logistic | self, forest |\n|---|---|---|---|---|---|")
    for _, r in TR.iterrows():
        W(f"| {r.cut:.0f}% | {r.ms:.0f} | " + " | ".join(f"{r[f'{n}|{m}']*100:.1f}%" for n in ("level", "self")
                                                      for m in ("logreg C=0.1", "forest")) + " |")
    W("")

    # ================= 4. causal self normalization =================
    print("causal ...", flush=True)
    order = D.trial_order.to_numpy()

    def causal(mname, limbs, nmin):
        yt, yp = [], []
        for p in P_:
            tr = g != p
            ip = np.where(g == p)[0]
            ip = ip[np.argsort(order[ip])]
            Ps = []
            for cols in limbs:
                m = maker(mname, 1)()
                m.fit(Xself.loc[tr, cols].to_numpy(float), y[tr])
                Xr = D.loc[ip, cols].reset_index(drop=True)
                rows = []
                for j in range(nmin, len(ip)):
                    prior = Xr.iloc[:j]
                    iqr = (prior.quantile(.75) - prior.quantile(.25)).replace(0, np.nan).fillna(1.0)
                    rows.append(((Xr.iloc[j] - prior.median()) / iqr).to_numpy(float))
                Ps.append(m.predict_proba(np.array(rows)) if rows else np.zeros((0, 3)))
            if len(Ps[0]):
                yp.append(m.classes_[np.argmax(np.mean(Ps, axis=0), axis=1)])
                yt.append(y[ip][nmin:])
        yt, yp = np.concatenate(yt), np.concatenate(yp)
        return balanced_accuracy_score(yt, yp), len(yt)

    W("## 4. Self normalization learned during use (causal)\n")
    W("Each crossing is normalized with the median / IQR of the same person's EARLIER crossings only (in walking order), starting "
      "once n earlier crossings exist; crossings before that are not scored. Here obstacles came in blocks of ~5, so the early history "
      "covers few obstacles - harder than mixed real-world obstacles.\n")
    W("| model | limbs | after 5 crossings | after 10 | after 15 | after 20 |\n|---|---|---|---|---|---|")
    for mname in ("logreg C=0.1", "forest"):
        for lname, limbs in (("lead", [LEAD]), ("fusion", [LEAD, TRAIL])):
            cells = []
            for nmin in (5, 10, 15, 20):
                b, n = causal(mname, limbs, nmin)
                cells.append(f"{b*100:.1f}% (n={n})")
            W(f"| {mname} | {lname} | " + " | ".join(cells) + " |")
    W("")

    # ================= 5. per participant =================
    W("## 5. Per participant (accuracy on each unseen participant)\n")
    settings = [("level", "logreg C=0.1", "lead"), ("self", "logreg C=0.1", "lead"), ("self", "forest", "lead"),
                ("self", "forest", "fusion")]
    W("| setting | " + " | ".join(str(p) for p in P_) + " | overall |\n|---|" + "---|" * (len(P_) + 1))
    pp_rows = {}
    for norm, mname, limb in settings:
        Ps = []
        for lb, cols in (("lead", LEAD), ("trail", TRAIL)):
            if limb in (lb, "fusion"):
                lab, P = lopo_proba(maker(mname), XN[norm][cols].to_numpy(float), y, g)
                Ps.append(P)
        pr = lab[np.argmax(np.mean(Ps, axis=0), axis=1)]
        acc = [np.mean(pr[g == p] == y[g == p]) for p in P_]
        pp_rows[f"{norm}, {mname}, {limb}"] = acc
        W(f"| {norm}, {mname}, {limb} | " + " | ".join(f"{a*100:.0f}%" for a in acc) + f" | {balanced_accuracy_score(y, pr)*100:.1f}% |")
    W("\nFigure: `fig_settings.png`.\n")
    (M.OUT / "ml_settings.md").write_text("\n".join(out), encoding="utf-8")
    figure(S, TR)
    print("wrote", M.OUT / "ml_settings.md")


def figure(S, TR):
    fig, axes = plt.subplots(1, 2, figsize=(13, 4.6), facecolor=M.SURFACE, gridspec_kw={"width_ratios": [1.1, 1]})
    ax = axes[0]
    d = S[S.model == "forest"].copy()
    order = ["lead only", "trail only"] + [k for k in d.features if k not in ("lead only", "trail only")]
    d = d.set_index("features").reindex(order)
    yy = np.arange(len(order))[::-1]
    ax.barh(yy, d.bal_acc * 100, height=0.62, color=M.ORANGE, edgecolor=M.SURFACE, lw=2)
    ax.errorbar(d.bal_acc * 100, yy, xerr=[(d.bal_acc - d.lo) * 100, (d.hi - d.bal_acc) * 100], fmt="none", ecolor=M.INK, lw=1, capsize=2)
    for yi, v, h in zip(yy, d.bal_acc, d.hi):
        ax.text(h * 100 + 1.2, yi, f"{v*100:.0f}", va="center", fontsize=8, color=M.INK2)
    ax.axvline(100 / 3, color=M.INK2, ls="--", lw=1)
    ax.set_yticks(yy, order)
    ax.set_xlim(0, 105)
    ax.set_xlabel("balanced accuracy, unseen participant (%)", color=M.INK2, fontsize=9)
    ax.set_title("Height by segment / limb (self normalization, random forest; 95% CI)", fontsize=10, color=M.INK, loc="left")
    M.style(ax)
    ax = axes[1]
    x = -TR.ms
    for (norm, col) in (("level", M.BLUE), ("self", M.ORANGE)):
        k = f"{norm}|forest"
        ax.fill_between(x, TR[k + "|lo"] * 100, TR[k + "|hi"] * 100, color=col, alpha=0.12, lw=0)
        ax.plot(x, TR[k] * 100, color=col, lw=2, marker="o", ms=4.5, mec=M.SURFACE, mew=1.2, label=f"{norm} normalization")
    ax.axhline(100 / 3, color=M.INK2, ls="--", lw=1)
    for lbl, cut in (("lead toe-off", 0), ("~lead foot apex", 50), ("lead landing", 100)):
        v = -TR.loc[TR.cut == cut, "ms"].iloc[0]
        ax.axvline(v, color=M.INK2, lw=1, ls=":")
        ax.text(v, 99, lbl, rotation=90, va="top", ha="right", fontsize=8, color=M.INK2)
    ax.set_ylim(20, 100)
    ax.set_xlabel("time relative to the trailing foot's toe-off (ms, median)", color=M.INK2, fontsize=9)
    ax.set_ylabel("balanced accuracy (%)", color=M.INK2, fontsize=9)
    ax.set_title("When is height known? Lead-limb data so far (random forest)", fontsize=10, color=M.INK, loc="left")
    M.style(ax)
    ax.yaxis.grid(True, color=M.GRID, lw=0.8)
    ax.xaxis.grid(False)
    ax.legend(frameon=False, fontsize=8.5, labelcolor=M.INK2, loc="lower right")
    fig.tight_layout()
    fig.savefig(M.OUT / "fig_settings.png", dpi=200, facecolor=M.SURFACE)
    plt.close(fig)


if __name__ == "__main__":
    main()
