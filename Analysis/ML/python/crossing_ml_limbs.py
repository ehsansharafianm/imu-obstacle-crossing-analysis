"""Separate leading / trailing limb models, combined by vote, on several targets.

Leading and trailing limbs cross differently, so each gets its OWN model (lead features
only, trail features only). The two are combined only at the END by averaging their class
probabilities ("fusion" = soft vote); features are never concatenated.

  A. Obstacle targets: height (H1/H2/H3), width (W1/W2), all 6 obstacles (11..23)
     x  lead model / trail model / fusion
     x  normalization: "level" (minus own level-walk median, lengths / leg length),
                       "self"  (each participant scaled to their own median / IQR over the
                                analysed rows; no labels used)
     x  model: L2 logistic regression (C = 0.1) / random forest
  B. Leading vs trailing: ONE limb's swing at a time (role-neutral features), can the Dot
     tell whether it was the leading or the trailing limb?
  C. Obstacle vs level walk, per limb and fused.
  D. Personal calibration ("few-shot"): k labelled crossings per class of the new person
     added to the training set (weight w), tested on the rest of that person's crossings.
  E. How many UNLABELLED crossings the "self" normalization needs: the new person's
     median / IQR from only n crossings (random, or the first n walked), tested on the rest.

Rules as crossing_ml.py: leave-one-participant-out, every fitted step inside the training
participants, participant bootstrap 95% CIs, permutation tests (labels shuffled within each
participant) for the headline runs. Descriptive only.
Writes Results/ML Models/ml_limbs.md, fig_limbs.png.
"""
from __future__ import annotations

import sys
from datetime import datetime
from pathlib import Path

import numpy as np
import pandas as pd
from joblib import Parallel, delayed
from sklearn.metrics import balanced_accuracy_score, confusion_matrix
from sklearn.model_selection import LeaveOneGroupOut

sys.path.insert(0, str(Path(__file__).resolve().parent))
import crossing_ml as M                         # noqa: E402
from crossing_ml_followup import boot_ci        # noqa: E402

import matplotlib.pyplot as plt                 # noqa: E402

N_PERM = 300
FS_K = [1, 2, 3]
FS_W = [1, 10]
FS_REPEATS = 20
MODELS = {"logreg": M.logreg, "forest": M.forest}


# ---------------- data helpers ----------------
def selfnorm(X, g):
    """Each participant: (x - own median) / own IQR over the given rows (labels not used)."""
    X = X.copy()
    for p in np.unique(g):
        i = g == p
        med = X.loc[i].median()
        iqr = (X.loc[i].quantile(0.75) - X.loc[i].quantile(0.25)).replace(0, np.nan).fillna(1.0)
        X.loc[i] = (X.loc[i] - med) / iqr
    return X


def lopo_proba(make, X, y, g):
    labels = np.unique(y)
    P = np.zeros((len(y), len(labels)))
    for tr, te in LeaveOneGroupOut().split(X, y, g):
        m = make()
        m.fit(X[tr], y[tr])
        P[te] = m.predict_proba(X[te])
    return labels, P


def fused(Ps):
    return np.mean(Ps, axis=0)


def perm_p(make, Xs, y, g, obs, n=N_PERM):
    """Permutation p for one model (len(Xs) == 1) or the fusion of several."""
    def one(seed):
        yp = M.shuffle_within(y, g, np.random.default_rng(seed))
        lab = None
        Ps = []
        for X in Xs:
            lab, P = lopo_proba(make, X, yp, g)
            Ps.append(P)
        return balanced_accuracy_score(yp, lab[np.argmax(fused(Ps), axis=1)])
    null = np.array(Parallel(n_jobs=-1)(delayed(one)(M.SEED + 7 + s) for s in range(n)))
    return (1 + np.sum(null >= obs)) / (1 + n), float(np.percentile(null, 95))


# ---------------- main ----------------
def main():
    df, feats, units = M.load()
    Xcal = M.calibrate(df, feats, units)
    sets = M.feature_sets(feats)
    LEAD, TRAIL = sets["lead only"], sets["trail only"]
    out = []
    W = out.append
    res = []                                    # summary rows for the figure / text
    conf6 = {}

    def X_for(cols, norm, rows):
        if norm == "raw":
            X = df.loc[rows, cols]
        elif norm == "level":
            X = Xcal.loc[rows, cols]
        else:
            X = selfnorm(df.loc[rows, cols], df.loc[rows, "participant_id"].to_numpy())
        return X.to_numpy(float)

    W("# Separate leading / trailing models, combined by vote\n")
    W(f"_Generated by `Analysis/ML/python/crossing_ml_limbs.py` on {datetime.now():%Y-%m-%d %H:%M}._\n")
    W("Each limb has its own model (lead features only / trail features only). **Fusion** = average of the two models' class "
      "probabilities (soft vote); features are never mixed. Leave-one-participant-out on 10 participants; 95% CI = participant "
      "bootstrap. **Normalization:** *level* = minus the participant's level-walk median, lengths / leg length (as before); "
      "*self* = each participant scaled to their own median and IQR over the analysed crossings (no labels used, but it assumes "
      "the person's recent crossings span a mix of obstacles, which the design guarantees here - an optimistic setting).\n")

    # ================= A. obstacle targets =================
    obs = ((df.is_level == 0) & (df[M.INCLUDE] == 1)).to_numpy()
    g = df.loc[obs, "participant_id"].to_numpy()
    targets = {"height": df.loc[obs, "height_class"].astype(str).to_numpy(),
               "width": df.loc[obs, "width_class"].astype(str).to_numpy(),
               "6 obstacles": ("W" + df.loc[obs, "obstacle_code"].astype(str).str[0] + "H"
                               + df.loc[obs, "obstacle_code"].astype(str).str[1]).to_numpy()}
    W(f"## A. Height, width and the 6 obstacles ({obs.sum()} crossings)\n")
    W("| target | chance | norm | model | lead | trail | fusion (lead + trail vote) |\n|---|---|---|---|---|---|---|")
    best = {}
    for tname, y in targets.items():
        chance = 1 / len(np.unique(y))
        for norm in ("level", "self"):
            XL, XT = X_for(LEAD, norm, obs), X_for(TRAIL, norm, obs)
            for mname, make in MODELS.items():
                lab, PL = lopo_proba(make, XL, y, g)
                _, PT = lopo_proba(make, XT, y, g)
                cells = []
                for limb, P in (("lead", PL), ("trail", PT), ("fusion", fused([PL, PT]))):
                    pred = lab[np.argmax(P, axis=1)]
                    ba = balanced_accuracy_score(y, pred)
                    lo, hi = boot_ci(y, pred, g)
                    cells.append(f"{ba*100:.1f}% ({lo*100:.0f}-{hi*100:.0f})")
                    res.append({"block": "A", "target": tname, "norm": norm, "model": mname, "limb": limb,
                                "bal_acc": ba, "lo": lo, "hi": hi, "chance": chance})
                    if tname == "6 obstacles" and limb == "fusion":
                        conf6[(norm, mname)] = (lab, confusion_matrix(y, pred, labels=lab))
                    k = (tname, limb)
                    if k not in best or ba > best[k][0]:
                        best[k] = (ba, norm, mname)
                W(f"| {tname} | {chance*100:.0f}% | {norm} | {mname} | " + " | ".join(cells) + " |")
    W("\nCells: balanced accuracy (95% CI). Unseen participant in every case.\n")

    # permutation tests for the logistic fusion runs (both norms)
    W("Permutation tests (logistic regression, labels shuffled within participant, "
      f"{N_PERM} permutations; fusion re-fits both limb models on every permutation):\n")
    W("| target | norm | limb | bal. acc | perm p | null 95th pct |\n|---|---|---|---|---|---|")
    for tname, y in targets.items():
        for norm in ("level", "self"):
            XL, XT = X_for(LEAD, norm, obs), X_for(TRAIL, norm, obs)
            for limb, Xs in (("lead", [XL]), ("fusion", [XL, XT])):
                r = next(r for r in res if r["block"] == "A" and r["target"] == tname and r["norm"] == norm
                         and r["model"] == "logreg" and r["limb"] == limb)
                p, n95 = perm_p(M.logreg, Xs, y, g, r["bal_acc"])
                r["perm_p"] = p
                W(f"| {tname} | {norm} | {limb} | {r['bal_acc']*100:.1f}% | {M.fmt_p(p)} | {n95*100:.1f}% |")
                print(f"perm {tname} {norm} {limb} p={p:.4f}", flush=True)
    W("")

    # ================= B. leading vs trailing from one limb =================
    lead_n = [c for c in LEAD if c.startswith("lead_")]
    neutral = sorted({c[5:] for c in lead_n} & {c[6:] for c in TRAIL})
    gl = np.concatenate([g, g])
    yr = np.array(["lead"] * obs.sum() + ["trail"] * obs.sum())
    Lr = pd.concat([df.loc[obs, ["lead_" + c for c in neutral]].set_axis(neutral, axis=1),
                    df.loc[obs, ["trail_" + c for c in neutral]].set_axis(neutral, axis=1)], ignore_index=True)
    lv = (df.is_level == 1) & (df.include_biomech == 1)
    Lv = pd.concat([df.loc[lv, ["lead_" + c for c in neutral]].set_axis(neutral, axis=1),
                    df.loc[lv, ["trail_" + c for c in neutral]].set_axis(neutral, axis=1)], ignore_index=True)
    gv = np.concatenate([df.loc[lv, "participant_id"].to_numpy()] * 2)
    mmn = [c for c in neutral if units["lead_" + c] == "mm"]
    ll = df.groupby("participant_id").leg_length_cm.first() * 10

    def role_X(norm):
        X = Lr.copy()
        if norm == "level":
            for p in np.unique(gl):
                X.loc[gl == p] = X.loc[gl == p] - Lv.loc[gv == p].median()
                X.loc[gl == p, mmn] = X.loc[gl == p, mmn] / ll[p]
        elif norm == "self":
            X = selfnorm(X, gl)
        return X.to_numpy(float)

    W(f"## B. Leading or trailing? One limb's swing at a time ({len(yr)} limb swings, {len(neutral)} role-neutral features)\n")
    W("The model sees one limb's features without its role (thigh / shank / foot tilt and angular velocity, foot acc, ZHC "
      "trajectory, swing / stance time) and predicts whether it was the leading or the trailing limb. Chance 50%.\n")
    W("| norm | model | bal. acc | 95% CI | perm p |\n|---|---|---|---|---|")
    for norm in ("raw", "level", "self"):
        Xr = role_X(norm)
        for mname, make in MODELS.items():
            lab, P = lopo_proba(make, Xr, yr, gl)
            pred = lab[np.argmax(P, axis=1)]
            ba = balanced_accuracy_score(yr, pred)
            lo, hi = boot_ci(yr, pred, gl)
            pp = "-"
            if mname == "logreg":
                p, _ = perm_p(make, [Xr], yr, gl, ba)
                pp = M.fmt_p(p)
            res.append({"block": "B", "target": "lead vs trail", "norm": norm, "model": mname, "limb": "one limb",
                        "bal_acc": ba, "lo": lo, "hi": hi, "chance": 0.5})
            W(f"| {norm} | {mname} | {ba*100:.1f}% | {lo*100:.0f}-{hi*100:.0f} | {pp} |")
    # pairwise: given BOTH swings of a crossing, which one led? (higher P(lead) wins)
    lab, P = lopo_proba(M.logreg, role_X("raw"), yr, gl)
    pl = P[:, list(lab).index("lead")]
    n = obs.sum()
    pair_ok = pl[:n] > pl[n:]
    W(f"\nGiven both swings of the same crossing, picking the one with the higher P(lead) (logistic, raw) identifies the leading limb in "
      f"**{pair_ok.mean()*100:.1f}%** of crossings ({pair_ok.sum()}/{n}); per participant: "
      + ", ".join(f"{p}: {pair_ok[g == p].mean()*100:.0f}%" for p in np.unique(g)) + ".\n")

    # ================= C. obstacle vs level =================
    allr = (df[M.INCLUDE] == 1).to_numpy()
    yo = np.where(df.loc[allr, "is_level"] == 1, "level", "obstacle")
    go = df.loc[allr, "participant_id"].to_numpy()
    W(f"## C. Obstacle or level walk? ({allr.sum()} strides: {np.sum(yo == 'obstacle')} obstacle, {np.sum(yo == 'level')} level)\n")
    W("Level-walk normalization is not used here (it is built from the level rows themselves). Chance 50% (balanced accuracy).\n")
    W("| norm | model | lead | trail | fusion |\n|---|---|---|---|---|")
    for norm in ("raw", "self"):
        XL, XT = X_for(LEAD, norm, allr), X_for(TRAIL, norm, allr)
        for mname, make in MODELS.items():
            lab, PL = lopo_proba(make, XL, yo, go)
            _, PT = lopo_proba(make, XT, yo, go)
            cells = []
            for limb, P in (("lead", PL), ("trail", PT), ("fusion", fused([PL, PT]))):
                pred = lab[np.argmax(P, axis=1)]
                ba = balanced_accuracy_score(yo, pred)
                lo, hi = boot_ci(yo, pred, go)
                cells.append(f"{ba*100:.1f}% ({lo*100:.0f}-{hi*100:.0f})")
                res.append({"block": "C", "target": "obstacle vs level", "norm": norm, "model": mname, "limb": limb,
                            "bal_acc": ba, "lo": lo, "hi": hi, "chance": 0.5})
            W(f"| {norm} | {mname} | " + " | ".join(cells) + " |")
    W("")

    # ================= D. personal calibration (few-shot) =================
    y = targets["height"]
    labs = np.unique(y)
    P_ = np.unique(g)

    def fewshot(norm, limbs, k, w, rep):
        rng = np.random.default_rng(10_000 + 100 * k + 10 * w + rep)
        Xs = [X_for(LEAD if l == "lead" else TRAIL, norm, obs) for l in limbs]
        yt, yp = [], []
        for p in P_:
            ip = np.where(g == p)[0]
            cal = np.concatenate([rng.choice(ip[y[ip] == c], k, replace=False) for c in labs if np.sum(y[ip] == c) > k])
            te = np.setdiff1d(ip, cal)
            tr = np.concatenate([np.where(g != p)[0], cal])
            sw = np.where(np.isin(tr, cal), float(w), 1.0)
            Ps = []
            for X in Xs:
                m = M.logreg()
                m.fit(X[tr], y[tr], logisticregression__sample_weight=sw)
                Ps.append(m.predict_proba(X[te]))
            yt.append(y[te])
            yp.append(labs[np.argmax(fused(Ps), axis=1)])
        return balanced_accuracy_score(np.concatenate(yt), np.concatenate(yp))

    W(f"## D. Personal calibration: k labelled crossings per height from the new person (height, logistic)\n")
    W(f"The k x 3 calibration crossings are added to the 9 training participants with weight w and removed from that person's test set; "
      f"mean over {FS_REPEATS} random draws (10th-90th percentile). k = 0 = no calibration (section A).\n")
    W("| norm | limbs | w | k = 0 | k = 1 | k = 2 | k = 3 |\n|---|---|---|---|---|---|---|")
    fs_rows = []
    for norm in ("level", "self"):
        for limbs in (("lead",), ("lead", "trail")):
            lname = "lead" if len(limbs) == 1 else "fusion"
            k0 = next(r["bal_acc"] for r in res if r["block"] == "A" and r["target"] == "height" and r["norm"] == norm
                      and r["model"] == "logreg" and r["limb"] == lname)
            for w in FS_W:
                cells = [f"{k0*100:.1f}%"]
                for k in FS_K:
                    v = np.array(Parallel(n_jobs=-1)(delayed(fewshot)(norm, limbs, k, w, r) for r in range(FS_REPEATS)))
                    cells.append(f"{v.mean()*100:.1f}% ({np.percentile(v, 10)*100:.0f}-{np.percentile(v, 90)*100:.0f})")
                    fs_rows.append({"norm": norm, "limb": lname, "w": w, "k": k, "bal_acc": v.mean()})
                W(f"| {norm} | {lname} | {w} | " + " | ".join(cells) + " |")
                print(f"fewshot {norm} {lname} w={w} done", flush=True)
    W("")

    # ================= E. self normalization from n unlabelled crossings =================
    D_ = df.loc[obs].reset_index(drop=True)
    order = D_.trial_order.to_numpy()

    def nstats(X, idx):
        s_ = X.iloc[idx]
        iqr = (s_.quantile(.75) - s_.quantile(.25)).replace(0, np.nan).fillna(1.0)
        return (X - s_.median()) / iqr

    def self_n(make, mode, n, rep):
        rng = np.random.default_rng(20_000 + rep)
        X = D_[LEAD]
        yt, yp = [], []
        for p in P_:
            tr = g != p
            Xtr = X[tr].copy()
            for q in np.unique(g[tr]):
                i = np.where(g[tr] == q)[0]
                Xtr.iloc[i] = nstats(Xtr.iloc[i], np.arange(len(i))).to_numpy()
            ip = np.where(g == p)[0]
            if mode == "random":
                sub = rng.choice(len(ip), n, replace=False)
            else:
                sub = np.argsort(order[ip])[:n]
            te = np.setdiff1d(np.arange(len(ip)), sub)
            Xp = nstats(X.iloc[ip], sub).to_numpy(float)[te]
            m = make()
            m.fit(Xtr.to_numpy(float), y[tr])
            yp.append(m.predict(Xp))
            yt.append(y[ip][te])
        return balanced_accuracy_score(np.concatenate(yt), np.concatenate(yp))

    W("## E. How many unlabelled crossings does the self normalization need? (height, lead model)\n")
    W("The new person's median / IQR are taken from only n of their crossings (no labels): a random n (mean of 10 draws), or the "
      "first n they walked (realistic start of use; here obstacles come in blocks of ~5, so the first crossings cover few obstacles). "
      "Tested on the remaining crossings. Training participants are normalized with all their crossings.\n")
    W("| model | first n: n = 3 | 6 | 10 | 15 | random n: n = 3 | 6 | 10 | 15 | all (section A) |\n|---|---|---|---|---|---|---|---|---|---|")
    for mname, make in MODELS.items():
        cells = []
        for mode in ("first", "random"):
            for n_ in (3, 6, 10, 15):
                reps = range(10) if mode == "random" else range(1)
                v = Parallel(n_jobs=-1)(delayed(self_n)(make, mode, n_, r) for r in reps)
                cells.append(f"{np.mean(v)*100:.1f}%")
        a_ = next(r["bal_acc"] for r in res if r["block"] == "A" and r["target"] == "height" and r["norm"] == "self"
                  and r["model"] == mname and r["limb"] == "lead")
        W(f"| {mname} | " + " | ".join(cells) + f" | {a_*100:.1f}% |")
        print(f"self-n {mname} done", flush=True)
    W("")

    # ================= confusion (6 obstacles, best fusion) =================
    k6 = max(conf6, key=lambda k: next(r["bal_acc"] for r in res if r["block"] == "A" and r["target"] == "6 obstacles"
                                         and r["limb"] == "fusion" and r["norm"] == k[0] and r["model"] == k[1]))
    lab, cm = conf6[k6]
    W(f"## 6-obstacle confusion (fusion, {k6[0]} normalization, {k6[1]}; rows = true)\n")
    W("| true \\ pred | " + " | ".join(lab) + " |\n|---|" + "---|" * len(lab))
    for i, l in enumerate(lab):
        W(f"| {l} | " + " | ".join(str(v) for v in cm[i]) + " |")
    same_h = sum(cm[i, j] for i in range(len(lab)) for j in range(len(lab)) if lab[i][3] == lab[j][3])
    same_w = sum(cm[i, j] for i in range(len(lab)) for j in range(len(lab)) if lab[i][1] == lab[j][1])
    W(f"\nHeight right (any width): {same_h / cm.sum()*100:.0f}%; width right (any height): {same_w / cm.sum()*100:.0f}%.\n")

    # ================= best per target =================
    W("## Best setting per target (balanced accuracy, unseen participant, no personal calibration)\n")
    W("| target | limb | best | setting |\n|---|---|---|---|")
    for (t, limb), (ba, norm, mname) in best.items():
        W(f"| {t} | {limb} | {ba*100:.1f}% | {norm}, {mname} |")
    W("\nNote: picking the best of several settings is optimistic; the logistic / level row is the pre-specified main analysis.\n")
    W("Figure: `fig_limbs.png`.\n")
    (M.OUT / "ml_limbs.md").write_text("\n".join(out), encoding="utf-8")
    pd.DataFrame(res).to_csv(M.OUT / "ml_limbs_results.csv", index=False, float_format="%.4f")
    figure(pd.DataFrame(res), pd.DataFrame(fs_rows))
    print("wrote", M.OUT / "ml_limbs.md")


# ---------------- figure ----------------
def figure(R, FS):
    """Logistic regression, both normalizations: lead / trail / fusion per target, plus role & obstacle-vs-level."""
    panels = [("height", "A"), ("width", "A"), ("6 obstacles", "A"), ("obstacle vs level", "C")]
    fig, axes = plt.subplots(1, 5, figsize=(14, 3.8), facecolor=M.SURFACE, sharey=True)
    cols = {"level": M.BLUE, "self": M.ORANGE, "raw": "#8a8984"}
    for ax, (t, b) in zip(axes, panels):
        d = R[(R.block == b) & (R.target == t) & (R.model == "logreg")]
        norms = [n for n in ("raw", "level", "self") if n in set(d.norm)]
        limbs = ["lead", "trail", "fusion"]
        for i, nm in enumerate(norms):
            dd = d[d.norm == nm].set_index("limb").reindex(limbs)
            x = np.arange(3) + (i - (len(norms) - 1) / 2) * 0.28
            ax.bar(x, dd.bal_acc * 100, width=0.26, color=cols[nm], edgecolor=M.SURFACE, lw=1.5, label=nm)
            ax.errorbar(x, dd.bal_acc * 100, yerr=[(dd.bal_acc - dd.lo) * 100, (dd.hi - dd.bal_acc) * 100],
                        fmt="none", ecolor=M.INK, lw=1, capsize=2)
        ax.axhline(d.chance.iloc[0] * 100, color=M.INK2, ls="--", lw=1)
        ax.set_xticks(range(3), limbs)
        ax.set_title(t, fontsize=10, color=M.INK, loc="left")
        M.style(ax)
        ax.xaxis.grid(False)
        ax.yaxis.grid(True, color=M.GRID, lw=0.8)
    ax = axes[4]
    d = R[(R.block == "B") & (R.model == "logreg")].set_index("norm").reindex(["raw", "level", "self"])
    ax.bar(range(3), d.bal_acc * 100, width=0.55, color=[cols[n] for n in d.index], edgecolor=M.SURFACE, lw=1.5)
    ax.errorbar(range(3), d.bal_acc * 100, yerr=[(d.bal_acc - d.lo) * 100, (d.hi - d.bal_acc) * 100], fmt="none", ecolor=M.INK, lw=1, capsize=2)
    ax.axhline(50, color=M.INK2, ls="--", lw=1)
    ax.set_xticks(range(3), list(d.index))
    ax.set_title("lead or trail? (one limb)", fontsize=10, color=M.INK, loc="left")
    M.style(ax)
    ax.xaxis.grid(False)
    ax.yaxis.grid(True, color=M.GRID, lw=0.8)
    axes[0].set_ylabel("balanced accuracy, unseen participant (%)", color=M.INK2, fontsize=9)
    axes[0].set_ylim(0, 105)
    from matplotlib.patches import Patch
    fig.legend(handles=[Patch(color=cols[k], label=k) for k in ("raw", "level", "self")], loc="upper right",
               ncol=3, frameon=False, fontsize=9, labelcolor=M.INK2, title="normalization", title_fontsize=9)
    fig.suptitle("Separate lead / trail models (logistic regression; bars = normalization, whiskers = 95% bootstrap CI, dashed = chance)",
                 fontsize=10, color=M.INK, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(M.OUT / "fig_limbs.png", dpi=200, facecolor=M.SURFACE)
    plt.close(fig)


if __name__ == "__main__":
    main()
