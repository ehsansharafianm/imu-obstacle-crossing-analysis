function [R, cells, P3] = limbRun(R, sec, target, feat, norm, mname, spec, B, y, g, CFG)
PL = mlTools.lopo(spec, B.(feat).lead.(norm), y, g);
PT = mlTools.lopo(spec, B.(feat).trail.(norm), y, g);
P3 = {PL, PT, (PL + PT) / 2};  lb = {'lead', 'trail', 'fusion'};  cells = cell(1, 3);
for k = 1:3
    [R, cells{k}] = addEval(R, sec, target, feat, lb{k}, norm, mname, y, g, P3{k}, CFG);
end
end

function [R, s, mn] = addEval(R, sec, target, feat, limb, norm, model, y, g, P, CFG)
cl = unique(y);  pr = mlTools.argmaxLab(P, cl);
b = mlTools.balAcc(y, pr);  c = mlTools.bootCI(y, pr, g, [], CFG.nBoot);
a = arrayfun(@(p) mean(strcmp(pr(g == p), y(g == p))), unique(g)');  mn = min(a);
r = struct('sec', sec, 'target', target, 'feat', feat, 'limb', limb, 'norm', norm, 'model', model, ...
    'bal', b, 'lo', c(1), 'hi', c(2), 'worst', mn, 'perm_p', NaN, 'P', P);
R = [R, r];
s = sprintf('%.1f%% (%.0f-%.0f; worst %.0f%%)', 100*b, 100*c(1), 100*c(2), 100*mn);
end

function r = getR(R, sec, target, feat, limb, norm, model)
r = R(strcmp({R.sec}, sec) & strcmp({R.target}, target) & strcmp({R.feat}, feat) & strcmp({R.limb}, limb) & ...
      strcmp({R.norm}, norm) & strcmp({R.model}, model));
r = r(1);
end

function P = labelP(pr, cl)
P = zeros(numel(pr), numel(cl));
for k = 1:numel(cl), P(:, k) = strcmp(pr, cl{k}); end
end

function pr = rankThirds(sc, g)
pr = cell(numel(sc), 1);
for p = unique(g)'
    i = find(g == p);  [~, o] = sort(sc(i));  n = numel(i);
    r = zeros(n, 1);  r(o) = 1:n;
    lab = repmat({'H2'}, n, 1);  lab(r <= round(n/3)) = {'H1'};  lab(r > round(2*n/3)) = {'H3'};
    pr(i) = lab;
end
end

function Pr = selfTrain(X, y, g, th, iters)
cl = unique(y);  P = unique(g);  parts = cell(numel(P), 1);
parfor k = 1:numel(P)
    te = g == P(k);  Xtr = X(~te,:);  ytr = y(~te);  Xte = X(te,:); %#ok<PFBNS>
    M = mlTools.fitPipe(mlTools.spec('logreg'), Xtr, ytr);  Pk = mlTools.predictPipe(M, Xte);
    for i = 1:iters
        [pm, j] = max(Pk, [], 2);  sel = pm >= th;
        if ~any(sel), break; end
        M = mlTools.fitPipe(mlTools.spec('logreg'), [Xtr; Xte(sel,:)], [ytr; cl(j(sel))], [ones(numel(ytr), 1); 3 * ones(nnz(sel), 1)]); %#ok<PFBNS>
        Pk = mlTools.predictPipe(M, Xte);
    end
    parts{k} = Pk;
end
Pr = zeros(numel(y), numel(cl));
for k = 1:numel(P), Pr(g == P(k), :) = parts{k}; end
end

function b = fewShot(X, y, g, k, w, seed)
rs = RandStream('mt19937ar', 'Seed', seed);  labs = unique(y);  yt = {};  yp = {};
for p = unique(g)'
    ip = find(g == p);  cal = [];
    for c = 1:numel(labs)
        ic = ip(strcmp(y(ip), labs{c}));
        if numel(ic) > k, cal = [cal; ic(randperm(rs, numel(ic), k))]; end %#ok<AGROW>
    end
    te = setdiff(ip, cal);  tr = [find(g ~= p); cal];
    sw = ones(numel(tr), 1);  sw(ismember(tr, cal)) = w;
    M = mlTools.fitPipe(mlTools.spec('logreg'), X(tr,:), y(tr), sw);
    yt = [yt; y(te)]; %#ok<AGROW>
    yp = [yp; mlTools.argmaxLab(mlTools.predictPipe(M, X(te,:)), M.classes)]; %#ok<AGROW>
end
b = mlTools.balAcc(yt, yp);
end

function [pred, chosen] = nested(cands, B, y, g)
P = unique(g)';  predC = cell(numel(P), 1);  chosen = cell(numel(P), 1);
parfor k = 1:numel(P)
    tr = g ~= P(k);  bs = -inf;  bi = 1;
    for c = 1:size(cands, 1)
        [f, lb, ~, sp, n] = cands{c, :};
        Pq = mlTools.lopo(sp, B.(f).lead.(n)(tr,:), y(tr), g(tr)); %#ok<PFBNS>
        if strcmp(lb, 'fusion'), Pq = (Pq + mlTools.lopo(sp, B.(f).trail.(n)(tr,:), y(tr), g(tr))) / 2; end
        sc = mlTools.balAcc(y(tr), mlTools.argmaxLab(Pq, unique(y(tr))));
        if sc > bs, bs = sc; bi = c; end
    end
    [f, lb, mn, sp, n] = cands{bi, :};
    M = mlTools.fitPipe(sp, B.(f).lead.(n)(tr,:), y(tr));  Pf = mlTools.predictPipe(M, B.(f).lead.(n)(~tr,:));
    if strcmp(lb, 'fusion')
        M2 = mlTools.fitPipe(sp, B.(f).trail.(n)(tr,:), y(tr));  Pf = (Pf + mlTools.predictPipe(M2, B.(f).trail.(n)(~tr,:))) / 2;
    end
    predC{k} = mlTools.argmaxLab(Pf, M.classes);
    chosen{k} = sprintf('%s, %s, %s, %s', strrep(f, '_', ' + '), lb, mn, n);
end
pred = cell(numel(y), 1);
for k = 1:numel(P), pred(g == P(k)) = predC{k}; end
end

function [Cl, Cs] = curveBlock(Cc, T, obs, g, step)
idx = 1:step:51;  Cl = [];  Cs = [];
for s = {'thigh','shank','foot','footacc','zhc_h','zhc_x'}
    M = Cc.(s{1})(:, idx);
    Ml = mlTools.calibrate(T, M, repmat(any(strcmp(s{1}, {'zhc_h', 'zhc_x'})), 1, numel(idx)));
    Cl = [Cl, Ml(obs, :)]; %#ok<AGROW>
    Cs = [Cs, mlTools.selfnorm(M(obs, :), g)]; %#ok<AGROW>
end
end

%% ========================================================================
%  SUMMARY + FIGURE
%% ========================================================================
function L = summarySection(L, R, FS)
q = @(varargin) getR(R, varargin{:});
old = q('X1', 'height', 'summary', 'lead', 'level', 'logreg');
shp = q('X1', 'height', 'shape', 'lead', 'level', 'logreg');
x3 = R(strcmp({R.sec}, 'X3'));  [~, i3] = max([x3.bal]);
x1s = R(strcmp({R.sec}, 'X1') & strcmp({R.norm}, 'self'));  [~, i1] = max([x1s.bal]);
x2 = R(strcmp({R.sec}, 'X2'));  [~, i2] = max([x2.bal]);
ng = q('X7', 'height', 'nested generic', 'chosen', 'chosen', 'chosen');
na = q('X7', 'height', 'nested all', 'chosen', 'chosen', 'chosen');
w0 = q('X6', 'width', 'summary', 'fusion', 'self', 'logreg');
w6 = R(strcmp({R.sec}, 'X6') & strcmp({R.target}, 'width'));  [~, iw] = max([w6.bal]);
