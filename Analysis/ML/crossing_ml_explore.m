function crossing_ml_explore(quick)
% CROSSING_ML_EXPLORE  New ideas to improve the obstacle-height (and width) models.
%
%   crossing_ml_explore         % full run
%   crossing_ml_explore(true)   % quick test (few permutations / repeats)
%
% Builds on crossing_ml_matlab.m (same data, rules, leave-one-participant-out, every fitted
% step on the training participants only). Ideas tested:
%   X1  new inputs: CLEARANCE-SHAPE features (how long / how far the foot stays high, where the
%       apex is, foot tilt at the apex - 13 numbers per limb from the ZHC curves) and the full
%       swing CURVES, vs the summary features; level vs self normalization
%   X2  more models (RBF SVM, boosted trees) and ensembles (soft vote)
%   X3  within-person ranking: rank one person's crossings by the model's height score and
%       split them into thirds (no labels; assumes the person crossed a mix of heights)
%   X4  self-training on the new person (pseudo-labels from confident predictions)
%   X5  personal calibration with the shape features (1-3 labelled crossings per height)
%   X6  width: stride-relative clearance features, and width when the height is known
%   X7  honest nested selection over the enlarged set of settings (generic-only and all)
% Outputs -> Results/ML Models/MATLAB/ml_explore_matlab.md, ml_explore_results.csv, fig_explore.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
CFG.nPerm = ternary(quick, 20, 300);  CFG.nBoot = ternary(quick, 200, 2000);
CFG.fsRep = ternary(quick, 3, 20);    CFG.step = 5;
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end

% ---------------- data ----------------
Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;  mm = strcmp(Dd.units, 'mm');
Xraw = T{:, F};  Xcal = mlTools.calibrate(T, Xraw, mm);
S = mlTools.featureSets(F);
obs = T.is_level == 0 & T.include_ml == 1;
y = T.height_class(obs);  yw = T.width_class(obs);  g = T.participant_id(obs);
J.lead = ci(F, mlTools.getSet(S, 'lead only'));  J.trail = ci(F, mlTools.getSet(S, 'trail only'));
C = mlTools.loadCurvesBoth(root, T.crossing_id);
[SH.lead, pn] = mlTools.shapeFeats(C.lead);  SH.trail = mlTools.shapeFeats(C.trail);
mmS = startsWith(pn, {'x_', 'h_'});
B = struct();                                   % feature blocks: B.(feat).(limb).(norm) = obs rows
for limb = {'lead', 'trail'}
    l = limb{1};
    B.summary.(l).level = Xcal(obs, J.(l));
    B.summary.(l).self  = mlTools.selfnorm(Xraw(obs, J.(l)), g);
    Ps = mlTools.calibrate(T, SH.(l), mmS);
    B.shape.(l).level = Ps(obs, :);
    B.shape.(l).self  = mlTools.selfnorm(SH.(l)(obs, :), g);
    [B.curves.(l).level, B.curves.(l).self] = curveBlock(C.(l), T, obs, g, CFG.step);
    for n = {'level', 'self'}
        B.summary_shape.(l).(n{1})  = [B.summary.(l).(n{1}), B.shape.(l).(n{1})];
        B.summary_curves.(l).(n{1}) = [B.summary.(l).(n{1}), B.curves.(l).(n{1})];
    end
end
lr = mlTools.spec('logreg');  rf = mlTools.spec('forest', 'nTrees', 300);
sv = mlTools.spec('svm');     bo = mlTools.spec('boost');
R = [];  L = {};  t0 = tic;
L = addl(L, '# Improving the models - new ideas (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_explore.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['Same data and rules as `ml_report_matlab.md`: %d obstacle crossings, 10 participants, every result on a participant the model never saw ' ...
    '(leave-one-participant-out; all fitting on the other 9). Height H1/H2/H3 (chance 33%%), width W1/W2 (chance 50%%). Cells = balanced accuracy ' ...
    '(95%% participant-bootstrap CI) and the worst participant. **level** = minus own level-walk median, lengths / leg length (generic: a device needs only ' ...
    'a short normal walk); **self** = each person scaled to their own median / IQR over their crossings (needs ~10-15 unlabelled mixed crossings).'], nnz(obs));
L = addl(L, '');

% ================= X1. new inputs =================
L = addl(L, '## X1. New inputs: clearance-shape features and full swing curves (height)');
L = addl(L, '');
L = addl(L, ['**Clearance-shape features** (13 per limb, from the Dot foot trajectory and foot tilt): peak foot height, forward progression to the peak, ' ...
    'horizontal distance and %% of swing spent above 50 / 70 / 80 / 90 %% of the peak, foot tilt at the apex, progression after the apex, rise / fall ' ...
    'steepness. **Curves** = the six swing curves (thigh, shank, foot tilt, foot |acc|, foot height, foot progression) every 10 %% of swing.']);
L = addl(L, '');
L = addl(L, '| features | n feat (lead) | norm | model | lead | trail | fusion |');
L = addl(L, '|---|---|---|---|---|---|---|');
fl = {'summary', 'shape', 'curves', 'summary_shape', 'summary_curves'};
for f = fl
    for n = {'level', 'self'}
        mods = {'logreg', lr};
        if any(strcmp(f{1}, {'summary', 'shape'})), mods = [mods; {'forest', rf}]; end %#ok<AGROW>
        for m = 1:size(mods, 1)
            [R, cells] = limbRun(R, 'X1', 'height', f{1}, n{1}, mods{m,1}, mods{m,2}, B, y, g, CFG);
            L = addl(L, '| %s | %d | %s | %s | %s |', strrep(f{1}, '_', ' + '), size(B.(f{1}).lead.level, 2), n{1}, mods{m,1}, strjoin(cells, ' | '));
        end
    end
end
r = getR(R, 'X1', 'height', 'shape', 'lead', 'level', 'logreg');
[pp, n95] = mlTools.permTest(lr, {B.shape.lead.level}, y, g, r.bal, CFG.nPerm, 31);
iR = (strcmp({R.sec}, 'X1') & strcmp({R.feat}, 'shape') & strcmp({R.limb}, 'lead') & strcmp({R.norm}, 'level') & strcmp({R.model}, 'logreg'));
R(iR).perm_p = pp;
L = addl(L, '');
L = addl(L, 'Permutation test, shape / lead / level / logistic: p = %s (null 95th percentile %.1f%%, %d permutations).', pstr(pp), 100*n95, CFG.nPerm);
L = addl(L, '');
fprintf('X1 done (%.0f s)\n', toc(t0));

% ================= X2. models & ensembles =================
L = addl(L, '## X2. More models and ensembles (height, self normalization)');
L = addl(L, '');
L = addl(L, '| features | model | lead | trail | fusion |');
L = addl(L, '|---|---|---|---|---|');
Pens = {};
for f = {'summary', 'shape'}
    for mo = {'logreg', lr; 'forest', rf; 'svm', sv; 'boost', bo}'
        [R, cells, P3] = limbRun(R, 'X2', 'height', f{1}, 'self', mo{1}, mo{2}, B, y, g, CFG);
        L = addl(L, '| %s | %s | %s |', f{1}, mo{1}, strjoin(cells, ' | '));
        Pens{end+1} = P3{3}; %#ok<AGROW>
    end
end
Pe = mean(cat(3, Pens{:}), 3);
[R, e] = addEval(R, 'X2', 'height', 'ensemble (8 models)', 'fusion', 'self', 'soft vote', y, g, Pe, CFG);
L = addl(L, '');
L = addl(L, 'Ensemble = soft vote of all 8 fusion models above: %s.', e);
L = addl(L, '');
fprintf('X2 done (%.0f s)\n', toc(t0));

% ================= X3. within-person ranking =================
L = addl(L, '## X3. Within-person ranking (generic model + ranking, no person normalization)');
L = addl(L, '');
L = addl(L, ['The generic (level-normalized) model gives each crossing an expected height score (sum P x 10/20/30). Each person''s crossings are then ranked ' ...
    'and split into thirds (lowest third = H1, ...). No labels are used, but it assumes the person crossed roughly equal numbers of each height, ' ...
    'which the protocol guarantees here (optimistic for real-world use).']);
L = addl(L, '');
L = addl(L, '| features | limb | generic model | + ranking into thirds |');
L = addl(L, '|---|---|---|---|');
for f = {'summary', 'shape', 'summary_shape'}
    for lb = {'lead', 'fusion'}
        r = getR(R, 'X1', 'height', f{1}, lb{1}, 'level', 'logreg');
        pr = rankThirds(r.P * [10; 20; 30], g);
        [R, e] = addEval(R, 'X3', 'height', f{1}, lb{1}, 'level', 'logistic + ranking', y, g, labelP(pr, unique(y)), CFG);
        L = addl(L, '| %s | %s | %.1f%% | %s |', strrep(f{1}, '_', ' + '), lb{1}, 100*r.bal, e);
    end
end
L = addl(L, '');
fprintf('X3 done (%.0f s)\n', toc(t0));

% ================= X4. self-training =================
L = addl(L, '## X4. Self-training on the new person (generic model, pseudo-labels)');
L = addl(L, '');
L = addl(L, 'The generic model labels the new person''s crossings; those with probability >= threshold are added to training (weight 3) and the model is refitted (1 or 3 rounds). No true labels used.');
L = addl(L, '');
L = addl(L, '| features (lead, level) | no self-training | th 0.5, 1 round | th 0.5, 3 rounds | th 0.7, 1 round | th 0.7, 3 rounds |');
L = addl(L, '|---|---|---|---|---|---|');
for f = {'summary', 'shape'}
    X = B.(f{1}).lead.level;  c = {sprintf('%.1f%%', 100*getR(R, 'X1', 'height', f{1}, 'lead', 'level', 'logreg').bal)};
    for th = [0.5 0.7]
        for it = [1 3]
            [R, e] = addEval(R, 'X4', 'height', f{1}, 'lead', 'level', sprintf('self-train th %.1f x%d', th, it), y, g, selfTrain(X, y, g, th, it), CFG);
            c{end+1} = e; %#ok<AGROW>
        end
    end
    L = addl(L, '| %s | %s |', f{1}, strjoin(c, ' | '));
end
L = addl(L, '');
fprintf('X4 done (%.0f s)\n', toc(t0));

% ================= X5. personal calibration with shape features =================
L = addl(L, '## X5. Personal calibration: k labelled crossings per height from the new person (generic level normalization, logistic, weight 10)');
L = addl(L, '');
L = addl(L, 'Mean over %d random draws (10th-90th percentile); the calibration crossings are removed from the test set.', CFG.fsRep);
L = addl(L, '');
L = addl(L, '| features (lead) | k = 0 | k = 1 | k = 2 | k = 3 |');
L = addl(L, '|---|---|---|---|---|');
FS = struct('feat', {}, 'k', {}, 'm', {});
for f = {'summary', 'shape', 'summary_shape'}
    X = B.(f{1}).lead.level;  k0 = getR(R, 'X1', 'height', f{1}, 'lead', 'level', 'logreg').bal;
    c = {sprintf('%.1f%%', 100*k0)};  FS(end+1) = struct('feat', f{1}, 'k', 0, 'm', k0); %#ok<AGROW>
    for k = 1:3
        v = zeros(CFG.fsRep, 1);
        parfor rr = 1:CFG.fsRep, v(rr) = fewShot(X, y, g, k, 10, 700 + 10*k + rr); end
        c{end+1} = sprintf('%.1f%% (%.0f-%.0f)', 100*mean(v), 100*mlTools.q7(v, 0.1), 100*mlTools.q7(v, 0.9)); %#ok<AGROW>
        FS(end+1) = struct('feat', f{1}, 'k', k, 'm', mean(v)); %#ok<AGROW>
    end
    L = addl(L, '| %s | %s |', strrep(f{1}, '_', ' + '), strjoin(c, ' | '));
end
L = addl(L, '');
fprintf('X5 done (%.0f s)\n', toc(t0));

% ================= X6. width =================
L = addl(L, '## X6. Width (W1 = 5 cm vs W2 = 15 cm)');
L = addl(L, '');
L = addl(L, ['**Stride-relative shape** = the horizontal clearance distances divided by the limb''s own stride progression (a wider obstacle should need a ' ...
    'longer high phase relative to the step). **Within height** = width model trained and tested inside each height class (is width visible once height is known?).']);
L = addl(L, '');
xc = startsWith(pn, 'x_');
for limb = {'lead', 'trail'}
    Rl = SH.(limb{1});  Rl(:, xc) = Rl(:, xc) ./ C.(limb{1}).zhc_x(:, end);
    B.ratio.(limb{1}).self = mlTools.selfnorm(Rl(obs, :), g);
    B.ratio_summary.(limb{1}).self = [B.ratio.(limb{1}).self, B.summary.(limb{1}).self];
end
L = addl(L, '| features | norm | model | lead | trail | fusion |');
L = addl(L, '|---|---|---|---|---|---|');
for wf = {'summary', 'logreg', lr; 'summary', 'boost', bo; 'shape', 'logreg', lr; 'ratio', 'logreg', lr; 'ratio_summary', 'logreg', lr}'
    [R, cells] = limbRun(R, 'X6', 'width', wf{1}, 'self', wf{2}, wf{3}, B, yw, g, CFG);
    L = addl(L, '| %s | self | %s | %s |', strrep(wf{1}, '_', ' + '), wf{2}, strjoin(cells, ' | '));
end
for wf = {'summary', 'ratio_summary'}
    pr = cell(numel(yw), 1);
    for h = {'H1', 'H2', 'H3'}
        m = strcmp(y, h{1});
        Pq = (mlTools.lopo(lr, B.(wf{1}).lead.self(m,:), yw(m), g(m)) + mlTools.lopo(lr, B.(wf{1}).trail.self(m,:), yw(m), g(m))) / 2;
        pr(m) = mlTools.argmaxLab(Pq, unique(yw));
    end
    [R, e] = addEval(R, 'X6', 'width within height', wf{1}, 'fusion', 'self', 'logreg', yw, g, labelP(pr, unique(yw)), CFG);
    L = addl(L, '');
    L = addl(L, 'Width within each height class (%s, fusion, self, logistic): %s.', strrep(wf{1}, '_', ' + '), e);
end
L = addl(L, '');
fprintf('X6 done (%.0f s)\n', toc(t0));

% ================= X7. nested selection =================
L = addl(L, '## X7. Honest nested selection over the enlarged settings (height)');
L = addl(L, '');
L = addl(L, ['Candidates = features {summary, shape, summary + shape} x limb {lead, fusion} x model {logistic, forest, RBF SVM} x normalization. For each unseen ' ...
    'participant the setting with the best inner leave-one-participant-out accuracy on the other 9 is chosen, refitted on them and applied to the unseen one. ' ...
    '**Generic** = level normalization only (what a device knows after a short normal walk); **all** = level or self.']);
L = addl(L, '');
L = addl(L, '| candidate set | n settings | nested accuracy (95%% CI; worst participant) | settings chosen |');
L = addl(L, '|---|---|---|---|');
cands = {};
for f = {'summary', 'shape', 'summary_shape'}
    for lb = {'lead', 'fusion'}
        for mo = {'logreg', lr; 'forest', rf; 'svm', sv}'
            for n = {'level', 'self'}, cands(end+1, :) = {f{1}, lb{1}, mo{1}, mo{2}, n{1}}; end %#ok<AGROW>
        end
    end
end
for set = {'generic', 'all'}
    cs = cands;  if strcmp(set{1}, 'generic'), cs = cands(strcmp(cands(:,5), 'level'), :); end
    [pred, chosen] = nested(cs, B, y, g);
    [R, e] = addEval(R, 'X7', 'height', ['nested ' set{1}], 'chosen', 'chosen', 'chosen', y, g, labelP(pred, unique(y)), CFG);
    [u, ~, jj] = unique(chosen);  cnt = accumarray(jj, 1);  [~, o] = sort(-cnt);
    L = addl(L, '| %s | %d | %s | %s |', set{1}, size(cs, 1), e, strjoin(arrayfun(@(i) sprintf('%s (%d/10)', u{i}, cnt(i)), o', 'UniformOutput', false), '; '));
end
L = addl(L, '');
fprintf('X7 done (%.0f s)\n', toc(t0));

% ================= summary =================
L = summarySection(L, R, FS);
writeLines(fullfile(out, 'ml_explore_matlab.md'), L);
Rt = struct2table(rmfield(R, 'P'));
writetable(Rt, fullfile(out, 'ml_explore_results.csv'));
mlTools.figures(out, 'explore', struct('R', rmfield(R, 'P'), 'FS', FS));
fprintf('Wrote %s (%.0f s)\n', out, toc(t0));
end

%% ========================================================================
%  RUNS
