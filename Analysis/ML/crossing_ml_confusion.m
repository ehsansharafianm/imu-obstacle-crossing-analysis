function crossing_ml_confusion(quick)
% CROSSING_ML_CONFUSION  Confusion matrices of the generic and the person-scaled model, side by side.
%
%   crossing_ml_confusion          % full run
%   crossing_ml_confusion(true)    % quick test (fewer bootstrap draws)
%
% Same rows, features and model as the confusion matrices of crossing_ml_matlab.m (fig_confusion):
% obstacle crossings with include_ml = 1, L2 logistic regression (C = 0.1), leave-one-participant-out.
% Three panels (height from all features, height from the leading limb only, width from all
% features), each with two normalisations:
%   level  generic: minus the person's level-walk median, lengths / leg length (mlTools.calibrate)
%   self   person scaling: (x - own median) / own IQR over the person's obstacle crossings, no
%          labels (mlTools.selfnorm)
% The level matrices reproduce fig_confusion; the self ones show where person scaling removes errors.
% Outputs -> Results/ML Models/MATLAB/ml_confusion_matlab.md, fig_confusion_self.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
nBoot = ternary(quick, 200, 2000);

D = mlTools.load(root);  T = D.T;  F = D.feats;
Xraw = T{:, F};  Xcal = mlTools.calibrate(T, Xraw, strcmp(D.units, 'mm'));
S = mlTools.featureSets(F);
obs = T.is_level == 0 & T.include_ml == 1;
g = T.participant_id(obs);
panels = {'height', 'all',       'height_class', 'Height, all features';
          'height', 'lead only', 'height_class', 'Height, leading limb only';
          'width',  'all',       'width_class',  'Width, all features'};
norms = {'level', 'generic (level-walk) scaling';  'self', 'person scaling'};
s = mlTools.spec('logreg');

conf = struct('key', {}, 'norm', {}, 'title', {}, 'lab', {}, 'cm', {}, 'bal', {}, 'ci', {});
for k = 1:size(panels, 1)
    [~, j] = ismember(mlTools.getSet(S, panels{k,2}), F);
    y = T.(panels{k,3})(obs);
    for n = 1:size(norms, 1)
        if strcmp(norms{n,1}, 'level'), X = Xcal(obs, j); else, X = mlTools.selfnorm(Xraw(obs, j), g); end
        [Pr, cl] = mlTools.lopo(s, X, y, g);
        pred = mlTools.argmaxLab(Pr, cl);
        conf(end+1) = struct('key', [panels{k,1} '|' panels{k,2}], 'norm', norms{n,1}, 'title', panels{k,4}, 'lab', {cl}, ...
            'cm', confmat(y, pred, cl), 'bal', mlTools.balAcc(y, pred), 'ci', mlTools.bootCI(y, pred, g, [], nBoot)); %#ok<AGROW>
        fprintf('  %-26s %-6s bal_acc=%.3f\n', panels{k,4}, norms{n,1}, conf(end).bal);
    end
end

L = {};
L = addl(L, '# Confusion matrices: generic vs person scaling (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_confusion.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings (include_ml), 10 participants, L2 logistic regression (C = 0.1), every participant tested unseen ' ...
    '(leave-one-participant-out). **level** = minus own level-walk median, lengths / leg length (the model of `fig_confusion`); ' ...
    '**self** = person scaling, (x - own median) / own IQR over the person''s obstacle crossings, no labels. Rows = true class. ' ...
    'Balanced accuracy with 95%% participant-bootstrap CI (%d resamples).'], nnz(obs), nBoot);
L = addl(L, '');
for k = 1:size(panels, 1)
    for n = 1:size(norms, 1)
        c = conf(strcmp({conf.key}, [panels{k,1} '|' panels{k,2}]) & strcmp({conf.norm}, norms{n,1}));
        L = addl(L, '**%s - %s**: balanced accuracy %.1f%% (95%% CI %.0f-%.0f)', panels{k,4}, norms{n,2}, 100*c.bal, 100*c.ci(1), 100*c.ci(2));
        L = addl(L, '');
        L = addl(L, ['| true \\ pred | ' strjoin(c.lab', ' | ') ' | correct |']);
        L = addl(L, ['|---|' repmat('---|', 1, numel(c.lab) + 1)]);
        for i = 1:numel(c.lab)
            L = addl(L, ['| %s | ' strjoin(arrayfun(@num2str, c.cm(i,:), 'UniformOutput', false), ' | ') ' | %.0f%% |'], c.lab{i}, 100 * c.cm(i,i) / sum(c.cm(i,:)));
        end
        L = addl(L, '');
    end
end
h = conf(strcmp({conf.key}, 'height|all'));  hl = h(strcmp({h.norm}, 'level'));  hs = h(strcmp({h.norm}, 'self'));
ext = @(c) c.cm(1,3) + c.cm(3,1);  mid = @(c) 100 * c.cm(2,2) / sum(c.cm(2,:));
L = addl(L, ['**Reading.** Height from all features: person scaling raises the balanced accuracy from %.1f%% to %.1f%%. The middle height ' ...
    'gains most (H2 correct %.0f%% -> %.0f%%): with the generic model one person''s medium lift looks like another person''s low or high ' ...
    'lift. H1 and H3 are confused in %d and %d of %d crossings: the remaining errors are between neighbouring heights.'], ...
    100*hl.bal, 100*hs.bal, mid(hl), mid(hs), ext(hl), ext(hs), sum(sum(hl.cm([1 3], :))));
writeLines(fullfile(out, 'ml_confusion_matlab.md'), L);
mlTools.figures(out, 'confusion', struct('conf', conf, 'norms', {norms}));
fprintf('Wrote %s\n', fullfile(out, 'ml_confusion_matlab.md'));
end

function cm = confmat(y, pred, lab)
cm = zeros(numel(lab), numel(lab));
for i = 1:numel(lab)
    for j = 1:numel(lab), cm(i,j) = sum(strcmp(y, lab{i}) & strcmp(pred, lab{j})); end
end
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
