function q = holm(p)
% Holm-adjusted p-values.
[ps, o] = sort(p(:));  m = numel(ps);
qs = min(1, cummax((m - (1:m)' + 1) .* ps));
q = zeros(size(p));  q(o) = qs;
end

function k = kappa(y, pred, cl)
po = mean(strcmp(y, pred));  pe = 0;
for c = 1:numel(cl), pe = pe + mean(strcmp(y, cl{c})) * mean(strcmp(pred, cl{c})); end
k = (po - pe) / (1 - pe);
end

function s = listSig(S, p, none)
if nargin < 3, none = 'none'; end
i = find(p < 0.05);
if isempty(i), s = none; return; end
s = strjoin(arrayfun(@(k) sprintf('%s %s', S(k).limb, S(k).name), i, 'UniformOutput', false), ', ');
end

function n = dec(unit)
% Decimals for a unit.
switch unit
    case 's', n = 3;
    case 'deg', n = 1;
    otherwise, n = 0;
end
end

function s = pstr(p)
if isnan(p), s = 'p = -'; elseif p < 0.001, s = 'p < 0.001'; else, s = sprintf('p = %.3f', p); end
end

function L = addl(L, fmt, varargin)
if isempty(varargin), L{end+1} = strrep(fmt, '%%', '%'); else, L{end+1} = sprintf(fmt, varargin{:}); end
end

function v = ternary(c, a, b)
if c, v = a; else, v = b; end
end

function writeLines(f, L)
fid = fopen(f, 'w', 'n', 'UTF-8');  assert(fid > 0, 'cannot open %s', f);
c = onCleanup(@() fclose(fid));
fprintf(fid, '%s\n', L{:});
end
