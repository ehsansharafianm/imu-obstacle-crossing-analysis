function crossing_ml_stats(quick)
% CROSSING_ML_STATS  Statistical analysis of the crossing variables and of the model comparisons.
%
%   crossing_ml_stats          % full run
%   crossing_ml_stats(true)    % quick test (fewer bootstrap draws)
%
% The leading and the trailing limb are analysed separately (never compared with each other).
%   S1  REPEATED-MEASURES ANOVA: height (3) x width (2) on the participant means of key wearable variables
%       and the camera clearance (Greenhouse-Geisser p, partial eta^2, Holm-corrected height contrasts)
%   S2  MIXED MODELS on every crossing: height (cm) x width + repeat number, random intercept and height slope
%       per participant (Satterthwaite df)
%   S3  AGREEMENT of the IMU with the camera: foot lift (Bland-Altman) and toe-off time
%   S4  MODEL COMPARISONS: McNemar tests on the paired predictions, Wilcoxon signed-rank tests on the
%       participant accuracies and paired bootstrap CIs, Holm-corrected
%   S5  DOMINANCE: does leading with the dominant leg change the crossing or its recognition?
% Outputs -> Results/ML Models/MATLAB/ml_stats_matlab.md, fig_stats.png

if nargin < 1, quick = false; end
here = fileparts(mfilename('fullpath'));
root = fileparts(fileparts(here));
addpath(here);
out = fullfile(root, 'Results', 'ML Models', 'MATLAB');
if ~isfolder(out), mkdir(out); end
if isempty(gcp('nocreate')), parpool('Processes'); end
nBoot = ternary(quick, 200, 2000);

Dd = mlTools.load(root);  T = Dd.T;  F = Dd.feats;  mm = strcmp(Dd.units, 'mm');
obs = T.is_level == 0 & T.include_ml == 1;
D.d = T(obs, :);  D.g = D.d.participant_id;  D.y = D.d.height_class;  D.w = D.d.width_class;
D.h = D.d.height_pct_LL / 100 .* D.d.leg_length_cm;               % nominal obstacle height, cm
D.V = {'lead', 'zhc_peak_foot_h', 'foot lift (Dot)', 'mm';
       'lead', 'thigh_max_corr', 'thigh flexion (Dot)', 'deg';
       'lead', 'swing_time', 'swing time (Dot)', 's';
       'lead', 'cam_min_clearance', 'minimum clearance (camera)', 'mm';
       'trail', 'zhc_peak_foot_h', 'foot lift (Dot)', 'mm';
       'trail', 'shank_min_corr', 'shank heel-up (Dot)', 'deg';
       'trail', 'swing_time', 'swing time (Dot)', 's';
       'trail', 'cam_min_clearance', 'minimum clearance (camera)', 'mm'};
% device features (crossing_ml_device.m D1 / crossing_ml_validate.m): two foot IMUs, person scaling
C = mlTools.loadCurvesBoth(root, T.crossing_id);
[SH.lead, pn] = mlTools.shapeFeats(C.lead);  SH.trail = mlTools.shapeFeats(C.trail);  mmS = startsWith(pn, {'x_', 'h_'});
leadG = {'stride_len_app1','stride_len_app2','speed_approach','speed_cross','cadence'};
for r = {'lead', 'trail'}
    l = r{1};
    cols = F(startsWith(F, [l '_foot_']) | startsWith(F, [l '_zhc_']) | ismember(F, {[l '_swing_time'], [l '_stance_time']}) | ...
        (strcmp(l, 'lead') & ismember(F, leadG)));
    raw = [T{:, cols}, SH.(l)];  mk = [mm(ismember(F, cols)), mmS];
    Xc = mlTools.calibrate(T, raw, mk);
    D.FX.(l).self = mlTools.selfnorm(raw(obs, :), D.g);
    D.FX.(l).level = Xc(obs, :);
    D.FX.(l).six = mlTools.selfnorm([T{obs, F(startsWith(F, [l '_thigh_']))}, T{obs, F(startsWith(F, [l '_shank_']))}, raw(obs, :)], D.g);
end
leadOnly = mlTools.getSet(mlTools.featureSets(F), 'lead only');
Xs = mlTools.calibrate(T, T{:, leadOnly}, mm(ismember(F, leadOnly)));  D.Xsum = Xs(obs, :);
Sc = mlTools.calibrate(T, SH.lead, mmS);  D.Xshape = Sc(obs, :);

L = {};
L = addl(L, '# Statistical analysis of the crossings and of the models (MATLAB)');
L = addl(L, '');
L = addl(L, '_Generated by `Analysis/ML/crossing_ml_stats.m` on %s._%s', char(datetime('now', 'Format', 'yyyy-MM-dd HH:mm')), ternary(quick, ' **QUICK TEST RUN.**', ''));
L = addl(L, '');
L = addl(L, ['%d obstacle crossings (include_ml), 10 participants, 6 obstacles (heights H1-H3 = 10 / 20 / 30 %% of leg length, widths W1 / W2 = ' ...
    '5 / 15 cm). The leading and the trailing limb are analysed separately. p < 0.05 is called significant; Holm correction within each family.'], nnz(obs));
L = addl(L, '');
t0 = tic;
[L, S1, lift] = partAnova(D, L);          fprintf('S1 done (%.0f s)\n', toc(t0));
L = partLme(D, L);                        fprintf('S2 done (%.0f s)\n', toc(t0));
[L, BA] = partAgreement(D, L);            fprintf('S3 done (%.0f s)\n', toc(t0));
[L, MC, dev] = partModels(D, L, nBoot);   fprintf('S4 done (%.0f s)\n', toc(t0));
L = partDominance(D, L, dev);             fprintf('S5 done (%.0f s)\n', toc(t0));
mlTools.figures(out, 'stats', struct('S1', S1, 'lift', lift, 'BA', BA, 'MC', MC));
writeLines(fullfile(out, 'ml_stats_matlab.md'), L);
fprintf('Wrote %s (%.0f s)\n', fullfile(out, 'ml_stats_matlab.md'), toc(t0));
end

%% ========================================================================
%  S1: repeated-measures ANOVA on participant means
%% ========================================================================
function [L, S, lift] = partAnova(D, L)
cells = {'W1','H1'; 'W1','H2'; 'W1','H3'; 'W2','H1'; 'W2','H2'; 'W2','H3'};  vn = {'W1H1','W1H2','W1H3','W2H1','W2H2','W2H3'};
within = table(categorical(cells(:,2)), categorical(cells(:,1)), 'VariableNames', {'Height', 'Width'});
P = unique(D.g)';  nV = size(D.V, 1);
S = struct('limb', {}, 'name', {}, 'unit', {}, 'n', {}, 'cellMean', {}, 'cellSD', {}, 'F', {}, 'df1', {}, 'df2', {}, 'p', {}, 'eta', {}, 'post', {});
L = addl(L, '## S1. Repeated-measures ANOVA: height x width (participant means)');
L = addl(L, '');
L = addl(L, ['Each participant''s mean per obstacle (6 cells), then a 3 (height) x 2 (width) repeated-measures ANOVA (`fitrm` / `ranova`), separately ' ...
    'for each limb and variable. p = Greenhouse-Geisser corrected (width has 2 levels, so its p is uncorrected); partial eta^2 = SS_effect / ' ...
    '(SS_effect + SS_error). Height contrasts: paired t-tests on the participant means averaged over width, Holm-corrected over the 3 pairs; ' ...
    'dz = mean difference / SD of the differences. Participants with all 6 cells only.']);
L = addl(L, '');
L = addl(L, '| limb | variable | n | height: F (df), p, partial eta^2 | width: F (df), p, partial eta^2 | height x width: F (df), p, partial eta^2 |');
L = addl(L, '|---|---|---|---|---|---|');
eff = {'(Intercept):Height', 'Error(Height)'; '(Intercept):Width', 'Error(Width)'; '(Intercept):Height:Width', 'Error(Height:Width)'};
for v = 1:nV
    x = D.d.([D.V{v,1} '_' D.V{v,2}]);
    M = nan(numel(P), 6);
    for k = 1:numel(P)
        for c = 1:6, M(k,c) = mean(x(D.g == P(k) & strcmp(D.w, cells{c,1}) & strcmp(D.y, cells{c,2})), 'omitnan'); end
    end
    ok = all(isfinite(M), 2);
    rm = fitrm(array2table(M(ok,:), 'VariableNames', vn), 'W1H1-W2H3 ~ 1', 'WithinDesign', within);
    ra = ranova(rm, 'WithinModel', 'Height*Width');
    r = struct('limb', D.V{v,1}, 'name', D.V{v,3}, 'unit', D.V{v,4}, 'n', nnz(ok), 'cellMean', mean(M(ok,:), 1), 'cellSD', std(M(ok,:), 0, 1), ...
        'F', zeros(1,3), 'df1', zeros(1,3), 'df2', zeros(1,3), 'p', zeros(1,3), 'eta', zeros(1,3), 'post', []);
    c = cell(1, 3);
    for e = 1:3
        r.F(e) = ra{eff{e,1}, 'F'};  r.df1(e) = ra{eff{e,1}, 'DF'};  r.df2(e) = ra{eff{e,2}, 'DF'};
        r.p(e) = ra{eff{e,1}, 'pValueGG'};
        r.eta(e) = ra{eff{e,1}, 'SumSq'} / (ra{eff{e,1}, 'SumSq'} + ra{eff{e,2}, 'SumSq'});
        c{e} = sprintf('F(%d, %d) = %.1f, %s, %.2f', r.df1(e), r.df2(e), r.F(e), pstr(r.p(e)), r.eta(e));
    end
    Hm = [mean(M(ok, [1 4]), 2), mean(M(ok, [2 5]), 2), mean(M(ok, [3 6]), 2)];
    pr = [1 2; 2 3; 1 3];  pp = zeros(3, 1);  dm = pp;  dz = pp;
    for q = 1:3
        df = Hm(:, pr(q,2)) - Hm(:, pr(q,1));  [~, pp(q)] = ttest(df);  dm(q) = mean(df);  dz(q) = mean(df) / std(df);
    end
    r.post = struct('pair', {{'H2 - H1', 'H3 - H2', 'H3 - H1'}}, 'diff', dm, 'dz', dz, 'p', holm(pp));
    S(end+1) = r; %#ok<AGROW>
    L = addl(L, '| %s | %s (%s) | %d | %s | %s | %s |', D.V{v,1}, D.V{v,3}, D.V{v,4}, nnz(ok), c{:});
end
L = addl(L, '');
L = addl(L, '**Height contrasts** (mean difference of the participant means, dz, Holm p):');
L = addl(L, '');
L = addl(L, '| limb | variable | H2 - H1 | H3 - H2 | H3 - H1 |');
L = addl(L, '|---|---|---|---|---|');
for v = 1:nV
    q = S(v).post;  c = arrayfun(@(k) sprintf('%+.*f (dz %.1f, %s)', dec(S(v).unit), q.diff(k), q.dz(k), pstr(q.p(k))), 1:3, 'UniformOutput', false);
    L = addl(L, '| %s | %s (%s) | %s |', S(v).limb, S(v).name, S(v).unit, strjoin(c, ' | '));
end
L = addl(L, '');
pH = arrayfun(@(s) s.p(1), S);  pW = arrayfun(@(s) s.p(2), S);  pI = arrayfun(@(s) s.p(3), S);
dot = ~contains({S.name}, 'camera');
L = addl(L, ['**Reading.** Obstacle height changes %d of the %d variables (%d of the %d wearable ones; camera clearance: %s). Width ' ...
    'changes %d (%s) and the height x width interaction %d (%s). With participant means the width shifts are consistent enough to be ' ...
    'significant; S2 gives their size in physical units next to the height effect.'], sum(pH < 0.05), numel(S), sum(pH(dot) < 0.05), ...
    nnz(dot), listSig(S(~dot), pH(~dot), 'neither limb'), sum(pW < 0.05), listSig(S, pW), sum(pI < 0.05), listSig(S, pI));
L = addl(L, '');
% foot lift per obstacle (participant means) for the step 9-style figure
iL = find(strcmp({S.limb}, 'lead') & strcmp({S.name}, 'foot lift (Dot)'));  iT = find(strcmp({S.limb}, 'trail') & strcmp({S.name}, 'foot lift (Dot)'));
lift = struct('cells', {strcat(cells(:,1), '_', cells(:,2))'}, 'mean', [S(iL).cellMean; S(iT).cellMean], 'sd', [S(iL).cellSD; S(iT).cellSD]);
end

%% ========================================================================
%  S2: linear mixed models on every crossing
%% ========================================================================
function L = partLme(D, L)
L = addl(L, '## S2. Mixed models on every crossing: height (cm), width, repeat');
L = addl(L, '');
L = addl(L, ['`y ~ 1 + h * W + repeat + (1 + h | participant)` (`fitlme`, REML), h = nominal obstacle height (cm) centred on its mean, ' ...
    'W = width coded -0.5 (W1) / +0.5 (W2), repeat = position of the crossing in its block of the same obstacle (1-5, linear). So the height ' ...
    'slope is the mean over the two widths, the width effect is W2 - W1 at the mean height, and the interaction is the difference of the ' ...
    'height slopes (W2 - W1). Estimates with 95 %% CI and Satterthwaite p; residual SD = crossing-to-crossing SD left by the model. ' ...
    'R^2 marginal / conditional = squared correlation of the observed values with the fixed-effects / full fitted values.']);
L = addl(L, '');
L = addl(L, '| limb | variable | per cm of height | W2 vs W1 | slope W2 - W1 (per cm) | per repeat | residual SD | R^2 m / c |');
L = addl(L, '|---|---|---|---|---|---|---|---|');
E = zeros(size(D.V, 1), 4);  rsd = zeros(size(D.V, 1), 1);
for v = 1:size(D.V, 1)
    x = D.d.([D.V{v,1} '_' D.V{v,2}]);  u = D.V{v,4};
    tb = table(x, D.h - mean(D.h), strcmp(D.w, 'W2') - 0.5, D.d.block_pos, categorical(D.g), 'VariableNames', {'y', 'h', 'W', 'rep', 'pid'});
    tb = tb(isfinite(x), :);
    try
        lme = fitlme(tb, 'y ~ 1 + h*W + rep + (1 + h | pid)');
    catch
        lme = fitlme(tb, 'y ~ 1 + h*W + rep + (1 | pid)');
    end
    [~, ~, st] = fixedEffects(lme, 'DFMethod', 'satterthwaite');
    nm = cellstr(st.Name);  c = cell(1, 4);  key = {'h', 'W', 'h:W', 'rep'};
    for k = 1:4
        i = find(strcmp(nm, key{k}), 1);  E(v, k) = st.Estimate(i);
        c{k} = sprintf('%+.*f (%+.*f to %+.*f), %s', dec(u) + 1, st.Estimate(i), dec(u) + 1, st.Lower(i), dec(u) + 1, st.Upper(i), pstr(st.pValue(i)));
    end
    rsd(v) = sqrt(lme.MSE);
    r2m = corr(tb.y, fitted(lme, 'Conditional', false))^2;  r2c = corr(tb.y, fitted(lme))^2;
    L = addl(L, '| %s | %s (%s) | %s | %.*f | %.2f / %.2f |', D.V{v,1}, D.V{v,3}, u, strjoin(c, ' | '), dec(u) + 1, rsd(v), r2m, r2c);
end
L = addl(L, '');
iL = 1;  iT = 5;                                   % foot lift rows of D.V
L = addl(L, ['**Reading.** A 15 cm (vs 5 cm) deep obstacle changes the foot lift by %+.0f mm (leading) and %+.0f mm (trailing) at the same ' ...
    'height, the same as %.1f and %.1f cm of extra obstacle height (slopes %.1f and %.1f mm per cm), against a residual crossing-to-crossing ' ...
    'SD of %.0f and %.0f mm. Such a shift is consistent over people (hence significant for the means, S1) but small next to the variation of ' ...
    'single crossings - why width cannot be recognised from one crossing while height can.'], E(iL,2), E(iT,2), E(iL,2) / E(iL,1), ...
    E(iT,2) / E(iT,1), E(iL,1), E(iT,1), rsd(iL), rsd(iT));
L = addl(L, '');
end

%% ========================================================================
%  S3: agreement of the IMU with the camera
%% ========================================================================
function [L, BA] = partAgreement(D, L)
BA = struct();
L = addl(L, '## S3. Agreement of the IMU with the camera');
L = addl(L, '');
L = addl(L, ['**Foot lift (Bland-Altman).** Dot foot-sensor rise above its stance height vs camera toe-marker rise above its stance height (the ' ...
    'sensor sits on the dorsum, the marker on the toe). Bias = mean(Dot - camera); limits of agreement (LoA) = bias +- 1.96 SD; proportional ' ...
    'bias = slope of the difference on the mean of the two. **Toe-off time.** Step-4 IMU toe-off (foot-angle minimum) minus the camera toe ' ...
    'lift-off; its change per cm of obstacle from `dt ~ h + (1 | participant)`.']);
L = addl(L, '');
L = addl(L, '| limb | n | foot lift: bias (mm) | LoA (mm) | proportional bias (mm per mm) | toe-off: bias (ms) | LoA (ms) | median (IQR) | per cm of obstacle |');
L = addl(L, '|---|---|---|---|---|---|---|---|---|');
for l = {'lead', 'trail'}
    dl = D.d.([l{1} '_dotcam_peak_h_err']);  dot = D.d.([l{1} '_zhc_peak_foot_h']);  cam = dot - dl;  mn = (dot + cam) / 2;
    ok = isfinite(dl) & isfinite(mn);  b = mean(dl(ok));  sd = std(dl(ok));
    c = [ones(nnz(ok), 1), mn(ok)] \ dl(ok);
    rr = corrcoef(mn(ok), dl(ok));  n = nnz(ok);  tt = rr(1,2) * sqrt((n - 2) / (1 - rr(1,2)^2));  pp = 2 * tcdf(-abs(tt), n - 2);
    dt = (D.d.([l{1} '_toeoff_t']) - D.d.([l{1} '_toeoff_t_cam'])) * 1000;  ot = isfinite(dt);
    tb = table(dt(ot), D.h(ot), categorical(D.g(ot)), 'VariableNames', {'dt', 'h', 'pid'});
    lme = fitlme(tb, 'dt ~ 1 + h + (1 | pid)');
    [~, ~, st] = fixedEffects(lme, 'DFMethod', 'satterthwaite');  i = strcmp(cellstr(st.Name), 'h');
    q = prctile(dt(ot), [25 50 75]);  bt = mean(dt(ot));  st2 = std(dt(ot));
    BA.(l{1}) = struct('mean', mn(ok), 'diff', dl(ok), 'bias', b, 'lo', b - 1.96 * sd, 'hi', b + 1.96 * sd, 'slope', c(2), 'pSlope', pp, ...
        'dt', dt(ot), 'h', D.h(ot), 'tBias', bt, 'tLo', bt - 1.96 * st2, 'tHi', bt + 1.96 * st2);
    L = addl(L, '| %s | %d | %+.0f | %+.0f to %+.0f | %+.2f (%s) | %+.0f | %+.0f to %+.0f | %+.0f (%+.0f to %+.0f) | %+.1f ms (%s) |', l{1}, n, b, ...
        b - 1.96 * sd, b + 1.96 * sd, c(2), pstr(pp), bt, bt - 1.96 * st2, bt + 1.96 * st2, q(2), q(1), q(3), st.Estimate(i), pstr(st.pValue(i)));
end
L = addl(L, '');
L = addl(L, ['**Reading.** The foot sensor and the toe marker measure different points of the foot, so a bias is expected; the limits of ' ...
    'agreement give the crossing-to-crossing disagreement a toe-height estimate from the foot sensor would carry (the reason clearance is only ' ...
    'partly predictable, `ml_validate_matlab.md` V3). The IMU toe-off event comes after the camera lift-off, much later for the trailing ' ...
    'limb, which is why every timing in the haptic analyses uses the camera lift-off.']);
L = addl(L, '');
end

%% ========================================================================
%  S4: statistical comparison of the main models
%% ========================================================================
function [L, MC, dev] = partModels(D, L, nBoot)
y = D.y;  g = D.g;  P = unique(g)';  rf = mlTools.spec('forest', 'nTrees', 300);  lr = mlTools.spec('logreg');
X = D.FX;
M = {'generic, forest vote, 2 foot IMUs', rf, X.lead.level, X.trail.level;
     'person scaling, forest vote, 2 foot IMUs (device)', rf, X.lead.self, X.trail.self;
     'person scaling, forest vote, 6 IMUs', rf, X.lead.six, X.trail.six;
     'person scaling, forest, leading foot only', rf, X.lead.self, [];
     'person scaling, logistic vote, 2 foot IMUs', lr, X.lead.self, X.trail.self;
     'generic, logistic, leading summary features', lr, D.Xsum, [];
     'generic, logistic, leading clearance-shape features', lr, D.Xshape, []};
nM = size(M, 1);  pred = cell(nM, 1);  cl = {};
for m = 1:nM
    [Pr, cl] = mlTools.lopo(M{m,2}, M{m,3}, y, g);
    if ~isempty(M{m,4}), Pr = (Pr + mlTools.lopo(M{m,2}, M{m,4}, y, g)) / 2; end
    pred{m} = mlTools.argmaxLab(Pr, cl);
    if m == 2, dev = struct('pred', pred(m), 'P', Pr, 'classes', {cl}); end
end
L = addl(L, '## S4. Statistical comparison of the main models (obstacle height)');
L = addl(L, '');
L = addl(L, ['Leave-one-participant-out predictions of every model on the same %d crossings. Kappa = Cohen''s kappa. Pairs: McNemar exact test on ' ...
    'the crossings one model gets right and the other wrong, Wilcoxon signed-rank test on the 10 participant accuracies, and the participant-' ...
    'bootstrap 95 %% CI of the difference in balanced accuracy; p Holm-corrected over the 5 pairs within each test.'], numel(y));
L = addl(L, '');
L = addl(L, '| model | balanced accuracy (95 % CI) | macro F1 | kappa |');
L = addl(L, '|---|---|---|---|');
for m = 1:nM
    c = mlTools.bootCI(y, pred{m}, g, [], nBoot);
    L = addl(L, '| %s | %.1f%% (%.0f-%.0f) | %.2f | %.2f |', M{m,1}, 100 * mlTools.balAcc(y, pred{m}), 100 * c(1), 100 * c(2), ...
        mlTools.macroF1(y, pred{m}), kappa(y, pred{m}, cl));
end
L = addl(L, '');
pairs = [2 1; 2 3; 2 4; 2 5; 7 6];
nm = {'person scaling vs generic (forest vote, 2 foot IMUs)', '2 foot IMUs vs 6 IMUs (person scaling)', ...
      'both feet vs leading foot only (person scaling)', 'forest vs logistic (person scaling)', 'clearance-shape vs summary features (generic, leading)'};
nP = size(pairs, 1);  dA = zeros(nP, 1);  lo = dA;  hi = dA;  pM = dA;  pW = dA;  b = dA;  cc = dA;
for q = 1:nP
    a = pred{pairs(q,1)};  o = pred{pairs(q,2)};
    ci = mlTools.bootCI(y, a, g, o, nBoot);
    dA(q) = 100 * (mlTools.balAcc(y, a) - mlTools.balAcc(y, o));  lo(q) = 100 * ci(3);  hi(q) = 100 * ci(4);
    ra = strcmp(a, y);  ro = strcmp(o, y);  b(q) = nnz(ra & ~ro);  cc(q) = nnz(~ra & ro);
    pM(q) = min(1, 2 * binocdf(min(b(q), cc(q)), b(q) + cc(q), 0.5));
    pa = arrayfun(@(p) mean(ra(g == p)), P);  po = arrayfun(@(p) mean(ro(g == p)), P);
    pW(q) = signrank(pa, po);
end
pMh = holm(pM);  pWh = holm(pW);
L = addl(L, '| comparison | difference (points, 95 % CI) | only A right / only B right | McNemar p (Holm) | Wilcoxon p (Holm) |');
L = addl(L, '|---|---|---|---|---|');
for q = 1:nP
    L = addl(L, '| %s | %+.1f (%+.1f to %+.1f) | %d / %d | %s | %s |', nm{q}, dA(q), lo(q), hi(q), b(q), cc(q), pstr(pMh(q)), pstr(pWh(q)));
end
L = addl(L, '');
sig = pMh < 0.05;
L = addl(L, ['**Reading.** Significant after correction (McNemar): %s. Not significant: %s. With 10 participants the Wilcoxon test on ' ...
    'participant accuracies has little power (smallest possible two-sided p = 0.002 when all 10 agree), so it confirms only the large effects.'], ...
    ternary(any(sig), strjoin(nm(sig), '; '), 'none'), ternary(any(~sig), strjoin(nm(~sig), '; '), 'none'));
L = addl(L, '');
MC = struct('names', {nm}, 'short', {{'person scaling vs generic', '2 foot IMUs vs 6 IMUs', 'both feet vs leading foot', ...
    'forest vs logistic', 'shape vs summary features'}}, 'd', dA, 'lo', lo, 'hi', hi, 'pM', pMh, 'pW', pWh);
end

%% ========================================================================
%  S5: leading with the dominant leg
%% ========================================================================
function L = partDominance(D, L, dev)
dom = D.d.lead_is_dominant;  okd = isfinite(dom);  P = unique(D.g)';
L = addl(L, '## S5. Leading with the dominant leg');
L = addl(L, '');
sh = arrayfun(@(p) mean(dom(D.g == p & okd)), P);
L = addl(L, ['%.1f%% of the crossings were led with the dominant leg (per participant %s). Mixed models per variable: ' ...
    '`y ~ 1 + h + W + leadDominant + (1 + h | participant)`; for the trailing variables leadDominant = 1 means the trailing leg is the ' ...
    'non-dominant one. Recognition: correct / wrong predictions of the device model by dominance (Fisher''s exact test).'], ...
    100 * mean(dom(okd)), strjoin(arrayfun(@(p, s) sprintf('%d: %.0f%%', p, 100 * s), P, sh, 'UniformOutput', false), ', '));
L = addl(L, '');
sigE = {};
L = addl(L, '| limb | variable | dominant-led minus non-dominant-led (95 % CI) | p |');
L = addl(L, '|---|---|---|---|');
for v = 1:size(D.V, 1)
    x = D.d.([D.V{v,1} '_' D.V{v,2}]);  u = D.V{v,4};  ok = isfinite(x) & okd;
    tb = table(x(ok), D.h(ok) - mean(D.h), categorical(D.w(ok)), dom(ok), categorical(D.g(ok)), 'VariableNames', {'y', 'h', 'W', 'dom', 'pid'});
    try
        lme = fitlme(tb, 'y ~ 1 + h + W + dom + (1 + h | pid)');
    catch
        lme = fitlme(tb, 'y ~ 1 + h + W + dom + (1 | pid)');
    end
    [~, ~, st] = fixedEffects(lme, 'DFMethod', 'satterthwaite');  i = strcmp(cellstr(st.Name), 'dom');
    L = addl(L, '| %s | %s (%s) | %+.*f (%+.*f to %+.*f) | %s |', D.V{v,1}, D.V{v,3}, u, dec(u) + 1, st.Estimate(i), dec(u) + 1, st.Lower(i), ...
        dec(u) + 1, st.Upper(i), pstr(st.pValue(i)));
    if st.pValue(i) < 0.05, sigE{end+1} = sprintf('%s %s %+.*f %s', D.V{v,1}, D.V{v,3}, dec(u) + 1, st.Estimate(i), u); end %#ok<AGROW>
end
L = addl(L, '');
right = strcmp(dev.pred, D.y);
tab = [nnz(right & dom == 1), nnz(~right & dom == 1); nnz(right & dom == 0), nnz(~right & dom == 0)];
[~, pf] = fishertest(tab);
L = addl(L, ['Device model (two foot IMUs, person scaling, forest vote): %.1f%% right when the dominant leg led (%d crossings), %.1f%% when the ' ...
    'non-dominant leg led (%d); Fisher''s exact %s.'], 100 * tab(1,1) / sum(tab(1,:)), sum(tab(1,:)), 100 * tab(2,1) / sum(tab(2,:)), ...
    sum(tab(2,:)), pstr(pf));
L = addl(L, '');
L = addl(L, ['**Reading.** When the dominant leg leads (so the non-dominant leg trails), the crossings differ significantly in: %s. Recognition ' ...
    'by the device model %s (%.1f%% vs %.1f%%, Fisher %s), so the device does not need to know which leg is dominant. The leg choice is not ' ...
    'controlled in this study (most participants alternate), so these differences are associations, not effects of dominance alone.'], ...
    ternary(isempty(sigE), 'none', strjoin(sigE, '; ')), ternary(pf < 0.05, 'differs', 'does not differ significantly'), ...
    100 * tab(1,1) / sum(tab(1,:)), 100 * tab(2,1) / sum(tab(2,:)), pstr(pf));
L = addl(L, '');
end

